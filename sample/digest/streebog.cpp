/**
 * Стандартные модули
 */
#include <cstring>
#include <iomanip>
#include <iostream>

/**
 * Подключаем заголовочные файлы проекта
 */
#include <digest/kdf.hpp>
#include <digest/hmac.hpp>
#include <digest/streebog.hpp>

/**
 * Используем стандартное пространство имён
 */
using namespace std;

/**
 * Подписываемся на пространство имён библиотеки
 */
using namespace anyks;

/**
 * @brief Пространство имён образца
 *
 */
namespace {
	/**
	 * @brief Метод вывода области байтов шестнадцатеричной записью
	 *
	 * @param title заголовок выводимой области байтов
	 * @param data  выводимая область байтов
	 * @param size  размер выводимой области байтов
	 *
	 */
	void print(const char * title, const uint8_t * data, const size_t size) noexcept {
		// Выводим заголовок области байтов
		cout << title << ": ";
		/**
		 * Выполняем перебор байтов выводимой области
		 */
		for(size_t i = 0; i < size; i++)
			// Выводим очередной байт шестнадцатеричной записью
			cout << hex << setw(2) << setfill('0') << static_cast <uint32_t> (data[i]);
		// Выполняем перевод строки за областью байтов
		cout << dec << endl;
	}
	/**
	 * @brief Метод получения просмотра строки знаков
	 *
	 * @param text строка знаков, на которую заводится просмотр
	 *
	 * @return     просмотр области байтов строки знаков
	 *
	 */
	view_t text(const char * text) noexcept {
		// Выводим просмотр области байтов строки знаков
		return view_t(reinterpret_cast <const uint8_t *> (text), ::strlen(text));
	}
};

/**
 * @brief Функция запуска приложения
 *
 * @param argc длина массива параметров
 * @param argv массив параметров
 *
 * @return     код выхода из приложения
 *
 */
int main(int argc, char * argv[]) noexcept {
	// Не используем параметры приложения
	(void) argc;
	// Не используем параметры приложения
	(void) argv;
	// Хешируемое сообщение образца
	const char * message = "Сообщение, которое требуется захешировать";
	// Место, в которое помещается хеш длиной 256 разрядов
	uint8_t result[64];
	/**
	 * Выполняем хеширование сообщения разом
	 *
	 * @note Умолчанием берётся запись строкой байтов - та, которой хеш идёт в
	 *       протоколах. Записи вектором, какой хеш печатает сам стандарт, просят
	 *       отдельно: она нужна там, где хеш толкуется числом
	 */
	if(!digest::streebog(digest::type_t::SHORT, ::text(message), result, 32)){
		// Выводим сообщение об отказе хеширования
		cout << "Захешировать сообщение не удалось" << endl;
		// Выходим из приложения с признаком отказа
		return EXIT_FAILURE;
	}
	// Выводим хеш сообщения длиной 256 разрядов
	::print("Хеш 256 строкой байтов", result, 32);
	// Выполняем хеширование сообщения записью вектором
	digest::streebog(digest::type_t::SHORT, ::text(message), result, 32, digest::order_t::VECTOR);
	// Выводим хеш сообщения записью вектором
	::print("Хеш 256 вектором     ", result, 32);
	// Выполняем хеширование сообщения хешем длиной 512 разрядов
	digest::streebog(digest::type_t::LONG, ::text(message), result, 64);
	// Выводим хеш сообщения длиной 512 разрядов
	::print("Хеш 512 строкой байтов", result, 64);
	// Объект хеширования сообщения потоком
	digest::streebog_t hash(digest::type_t::SHORT);
	/**
	 * Выполняем перебор знаков хешируемого сообщения
	 *
	 * @note Сообщение подаётся по одному знаку нарочно: хеш обязан выйти тем же, что
	 *       и у хеширования разом, - разбиение на куски на итог не влияет
	 */
	for(const char * item = message; *item != '\0'; item++)
		// Выполняем подачу очередного знака сообщения
		hash.update(view_t(reinterpret_cast <const uint8_t *> (item), 1));
	// Выполняем завершение хеширования сообщения
	hash.finish(result, 32);
	// Выводим хеш сообщения, захешированного потоком
	::print("Хеш 256 потоком      ", result, 32);
	// Ключ выработки имитовставки образца
	const char * secret = "ключ выработки имитовставки";
	// Выполняем выработку имитовставки сообщения
	if(!digest::hmac(digest::type_t::SHORT, ::text(secret), ::text(message), result, 32)){
		// Выводим сообщение об отказе выработки имитовставки
		cout << "Выработать имитовставку не удалось" << endl;
		// Выходим из приложения с признаком отказа
		return EXIT_FAILURE;
	}
	// Выводим имитовставку сообщения
	::print("Имитовставка HMAC    ", result, 32);
	/**
	 * Выполняем выработку производного ключа
	 *
	 * @note Метка назначения входит в выработку наравне с ключом: тот же ключ с иной
	 *       меткой даёт иной производный ключ, и связать их между собою нельзя
	 */
	if(!digest::kdf(::text(secret), ::text("метка назначения"), ::text("затравка"), result)){
		// Выводим сообщение об отказе выработки производного ключа
		cout << "Выработать производный ключ не удалось" << endl;
		// Выходим из приложения с признаком отказа
		return EXIT_FAILURE;
	}
	// Выводим выработанный производный ключ
	::print("Производный ключ     ", result, digest::KDF_KEY);
	// Место, в которое помещается порождённая последовательность
	uint8_t sequence[80];
	/**
	 * Выполняем выработку порождающей последовательности протокола
	 *
	 * @note Длина последовательности ничем не ограничена: она набирается частями
	 *       длиной в хеш, пока не наберётся требуемого
	 */
	if(!digest::prf(digest::type_t::SHORT, ::text(secret), ::text("метка"), ::text("затравка"), sequence, sizeof(sequence))){
		// Выводим сообщение об отказе выработки последовательности
		cout << "Выработать последовательность не удалось" << endl;
		// Выходим из приложения с признаком отказа
		return EXIT_FAILURE;
	}
	// Выводим порождённую последовательность длиной в восемьдесят байтов
	::print("Последовательность   ", sequence, sizeof(sequence));
	// Выходим из приложения с признаком успеха
	return EXIT_SUCCESS;
}
