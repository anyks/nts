/**
 * Стандартные модули
 */
#include <cstring>
#include <iomanip>
#include <iostream>

/**
 * Подключаем заголовочные файлы проекта
 */
#include <math/number.hpp>
#include <sign/gost.hpp>
#include <entropy/entropy.hpp>
#include <curve/parameters.hpp>
#include <digest/streebog.hpp>

/**
 * Используем стандартное пространство имён
 */
using namespace std;

/**
 * Подписываемся на пространство имён библиотеки
 */
using namespace nts;

/**
 * @brief Пространство имён образца
 *
 */
namespace {
	/**
	 * @brief Опознаватель набора параметров кривой образца
	 *
	 * @details Набор параметров A длиной 256 разрядов - тот же, на котором работает
	 *          группа обмена ключами GC256A протокола TLS
	 *
	 */
	static const char * CURVE = "1.2.643.7.1.2.1.1.1";

	/**
	 * @brief Функция вывода области байтов шестнадцатеричной записью
	 *
	 * @param title заголовок выводимой области байтов
	 * @param data  выводимая область байтов
	 * @param size  размер выводимой области байтов
	 *
	 */
	void print(const char * title, const uint8_t * data, const size_t size) noexcept {
		// Выводим заголовок области байтов
		cout << title << ": ";
		/**
		 * Выполняем перебор байтов выводимой области
		 */
		for(size_t i = 0; i < size; i++)
			// Выводим очередной байт шестнадцатеричной записью
			cout << hex << setw(2) << setfill('0') << static_cast <uint32_t> (data[i]);
		// Выполняем перевод строки за областью байтов
		cout << dec << endl;
	}
};

/**
 * @brief Функция запуска приложения
 *
 * @param argc длина массива параметров
 * @param argv массив параметров
 * @return     код выхода из приложения
 *
 */
int main(int argc, char * argv[]) noexcept {
	// Не используем параметры приложения
	(void) argc;
	// Не используем параметры приложения
	(void) argv;
	// Объект эллиптической кривой подписи
	curve::curve_t curve;
	// Если кривую набора параметров завести не удалось
	if(!curve::parameters(CURVE, curve)){
		// Выводим сообщение об отказе заведения кривой
		cout << "Набор параметров кривой неизвестен" << endl;
		// Выходим из приложения с признаком отказа
		return EXIT_FAILURE;
	}
	// Выводим опознаватель набора параметров кривой
	cout << "Кривая             : " << CURVE << endl;
	// Выводим длину порядка группы точек кривой
	cout << "Длина порядка      : " << curve.size() << " байтов" << endl;
	// Объект электронной подписи
	sign::gost_t sign;
	// Если объект подписи на кривой завести не удалось
	if(!sign.start(curve)){
		// Выводим сообщение об отказе заведения подписи
		cout << "Завести подпись на кривой не удалось" << endl;
		// Выходим из приложения с признаком отказа
		return EXIT_FAILURE;
	}
	// Закрытый ключ подписи
	uint8_t secret[64];
	// Вырабатываемое случайное число закрытого ключа подписи
	math::number_t number;
	/**
	 * Выполняем выработку закрытого ключа подписи
	 *
	 * @details Закрытый ключ есть число от единицы до порядка группы точек кривой, и
	 *          вырабатывается оно отбором: случайное значение, в этот промежуток не
	 *          попавшее, отбрасывается и берётся следующее. Обрезание случайного
	 *          значения по остатку сместило бы разброд, а с ним и стойкость подписи
	 *
	 * @note Источником случайности берётся источник самой системы: своего у библиотеки
	 *       нет и быть не должно
	 *
	 */
	if(!entropy::number(curve.order(), number)){
		// Выводим сообщение об отказе выработки закрытого ключа
		cout << "Выработать закрытый ключ не удалось" << endl;
		// Выходим из приложения с признаком отказа
		return EXIT_FAILURE;
	}
	// Выполняем запись выработанного закрытого ключа строкой байтов
	curve.order().store(number, secret, curve.size());
	// Если закрытый ключ подписи установить не удалось
	if(!sign.secret(view_t(secret, curve.size()))){
		// Выводим сообщение об отказе установки закрытого ключа
		cout << "Установить закрытый ключ не удалось" << endl;
		// Выходим из приложения с признаком отказа
		return EXIT_FAILURE;
	}
	// Открытая часть ключа подписи по первой оси
	uint8_t x[64];
	// Открытая часть ключа подписи по второй оси
	uint8_t y[64];
	// Выполняем получение открытой части ключа подписи
	sign.key(x, y, curve.size());
	// Выводим открытую часть ключа подписи по первой оси
	::print("Открытый ключ, x   ", x, curve.size());
	// Выводим открытую часть ключа подписи по второй оси
	::print("Открытый ключ, y   ", y, curve.size());
	// Подписываемое сообщение образца
	const char * message = "Сообщение, которое требуется подписать";
	// Место, в которое помещается хеш подписываемого сообщения
	uint8_t digest[32];
	/**
	 * Выполняем хеширование подписываемого сообщения
	 *
	 * @note Хеш берётся записью вектором: стандарт подписи толкует его числом, и запись
	 *       строкой байтов дала бы иное число, а с ним и иную подпись
	 *
	 */
	if(!digest::streebog(digest::type_t::SHORT, view_t(reinterpret_cast <const uint8_t *> (message), ::strlen(message)), digest, sizeof(digest), digest::order_t::VECTOR)){
		// Выводим сообщение об отказе хеширования сообщения
		cout << "Захешировать сообщение не удалось" << endl;
		// Выходим из приложения с признаком отказа
		return EXIT_FAILURE;
	}
	// Выводим хеш подписываемого сообщения
	::print("Хеш сообщения      ", digest, sizeof(digest));
	// Место, в которое помещается подпись сообщения
	uint8_t signature[128];
	/**
	 * Выполняем подписание сообщения
	 *
	 * @note Случайное значение подписи вырабатывается самой подписью: значение это
	 *       обязано быть свежим у всякой подписи, и вручную его не подают
	 *
	 */
	if(!sign.make(view_t(digest, sizeof(digest)), signature)){
		// Выводим сообщение об отказе подписания сообщения
		cout << "Подписать сообщение не удалось" << endl;
		// Выходим из приложения с признаком отказа
		return EXIT_FAILURE;
	}
	// Выводим подпись сообщения
	::print("Подпись            ", signature, (curve.size() * 2));
	// Если подпись сообщения не сошлась
	if(!sign.check(view_t(digest, sizeof(digest)), view_t(signature, (curve.size() * 2)))){
		// Выводим сообщение об отказе проверки подписи
		cout << "Подпись сообщения не сошлась" << endl;
		// Выходим из приложения с признаком отказа
		return EXIT_FAILURE;
	}
	// Выводим сообщение об успешной проверке подписи
	cout << "Проверка подписи   : подпись сошлась" << endl;
	// Портим один байт хеша подписанного сообщения
	digest[0] = static_cast <uint8_t> (digest[0] ^ 0x01);
	// Если подпись испорченного сообщения отвергнута
	if(!sign.check(view_t(digest, sizeof(digest)), view_t(signature, (curve.size() * 2))))
		// Выводим сообщение об отвержении подписи испорченного сообщения
		cout << "Проверка подмены   : подпись подменённого сообщения отвергнута" << endl;
	// Выходим из приложения с признаком успеха
	return EXIT_SUCCESS;
}
