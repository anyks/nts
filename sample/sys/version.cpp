/**
 * Стандартные модули
 */
#include <iostream>

/**
 * Подключаем заголовочные файлы проекта
 */
#include <sys/version.hpp>

/**
 * Используем стандартное пространство имён
 */
using namespace std;

/**
 * Подписываемся на пространство имён библиотеки
 */
using namespace nts;

/**
 * @brief Точка входа образца
 *
 * @param argc число доводов
 * @param argv доводы
 * @return     код завершения: нуль при успехе
 *
 */
int main(int argc, char * argv[]) noexcept {
	// Печатаем строку издания библиотеки
	cout << "Издание библиотеки: " << sys::version() << endl;
	// Печатаем номера издания по одному
	cout << "Старший номер: " << sys::majorVersion() << ", младший: " << sys::minorVersion() << ", заплатка: " << sys::patchVersion() << endl;
	// Печатаем сводное число издания
	cout << "Сводное число: " << sys::number() << endl;
	/**
	 * Ворота условной компиляции: макросы издания видны потребителю цели nts
	 */
#if ANTS_VERSION_NUMBER >= 1000000
	// Печатаем сведение открытых ворот издания 1.0
	cout << "Ворота компиляции издания 1.0: открыты" << endl;
#endif
	// Решение на исполнении: сводное число сравнивается одним знаком
	if(sys::number() >= 1000000)
		// Печатаем сведение о издании 1.0 и новее
		cout << "Решение на исполнении: издание 1.0 и новее" << endl;
	// Выходим с успехом
	return EXIT_SUCCESS;
}
