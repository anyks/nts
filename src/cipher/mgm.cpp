/**
 * @brief Метод запуска режима работы
 *
 * @param block базовый алгоритм блочного шифрования
 * @param nonce начальное заполнение счётчика длиной в блок шифра с нулевым старшим разрядом
 * @param size  длина метки целостности в байтах, ноль означает длину блока шифра
 * @return      признак успешности запуска режима работы
 *
 */
bool nts::cipher::Galois::start(const block_t & block, const view_t & nonce, const size_t size) noexcept {
	// Выполняем сброс прежнего состояния режима работы
	this->clear();
	/**
	 * Умножение в поле задано RFC 9058 лишь для блоков длиной 64 и 128 разрядов
	 */
	if((block.cipher == nullptr) || (block.encrypt == nullptr) || ((block.size != 8) && (block.size != 16)))
		// Выводим отказ запуска режима работы
		return false;
	// Определяем требуемую длину метки целостности
	const size_t tag = (size > 0 ? size : block.size);
	// Если требуемая длина метки целостности выходит за допустимые пределы
	if((tag < MGM_TAG) || (tag > block.size))
		// Выводим отказ запуска режима работы
		return false;
	// Если начальное заполнение счётчика не занимает блока шифра
	if((nonce.data == nullptr) || (nonce.size != block.size))
		// Выводим отказ запуска режима работы
		return false;
	/**
	 * Старший разряд начального заполнения счётчика занят самим режимом: им
	 * разделяются ветвь выработки гаммы и ветвь выработки метки целостности
	 */
	if((nonce.data[0] & 0x80) != 0)
		// Выводим отказ запуска режима работы
		return false;
	// Запоминаем базовый алгоритм блочного шифрования
	this->_block = block;
	// Запоминаем длину метки целостности
	this->_size = tag;
	// Запоминаем начальное заполнение счётчика
	::memcpy(this->_nonce, nonce.data, nonce.size);
	// Снимаем признак расходования начального заполнения счётчика на зашифрование
	this->_spent = false;
	// Устанавливаем признак готовности режима к работе
	this->_ready = true;
	// Выводим успешность запуска режима работы
	return true;
}
/**
 * @brief Метод сброса состояния режима работы
 *
 */
void nts::cipher::Galois::clear() noexcept {
	// Выполняем затирание начального заполнения счётчика
	wipe(this->_nonce, sizeof(this->_nonce));
	// Сбрасываем базовый алгоритм блочного шифрования
	this->_block = block_t();
	// Сбрасываем длину метки целостности
	this->_size = 0;
	// Снимаем признак расходования начального заполнения счётчика на зашифрование
	this->_spent = false;
	// Снимаем признак готовности режима к работе
	this->_ready = false;
}
/**
 * @brief Метод зашифрования сообщения с выработкой метки целостности
 *
 * @param associated связанные данные, целостность которых проверяется без их зашифрования
 * @param source     зашифровываемое сообщение
 * @param result     место, в которое помещается шифртекст
 * @param tag        место, в которое помещается метка целостности
 * @return           признак успешности зашифрования
 *
 */
bool nts::cipher::Galois::encrypt(const view_t & associated, const view_t & source, uint8_t * result, uint8_t * tag) noexcept {
	// Если режим не готов к работе либо место метки целостности не передано
	if(!this->_ready || (tag == nullptr))
		// Выводим отказ зашифрования
		return false;
	/**
	 * Начальное заполнение счётчика годится на одно зашифрование: повтор на том же
	 * заполнении раскрывает сумму открытых текстов и ключ выработки метки, оттого
	 * следующее зашифрование дозволяется лишь после запуска режима с новым заполнением
	 */
	if(this->_spent)
		// Выводим отказ зашифрования
		return false;
	// Если зашифровываемое сообщение передано неверно
	if((source.size > 0) && ((source.data == nullptr) || (result == nullptr)))
		// Выводим отказ зашифрования
		return false;
	// Если связанные данные переданы неверно
	if((associated.size > 0) && (associated.data == nullptr))
		// Выводим отказ зашифрования
		return false;
	/**
	 * RFC 9058 требует, чтобы суммарная длина связанных данных и сообщения была
	 * положительной: подписывать нечего, когда не передано ни того, ни другого
	 */
	if((associated.size == 0) && (source.size == 0))
		// Выводим отказ зашифрования
		return false;
	/**
	 * Раздел 4.1 RFC 9058 держит суммарную длину связанных данных и сообщения ниже
	 * 2^(n/2) разрядов: длины эти пишутся в метку целостности половинами блока
	 */
	if(!measurable(associated.size, source.size, this->_block.size))
		// Выводим отказ зашифрования
		return false;
	/**
	 * Слагаемое !gamma(...) ложно всегда: наложение гаммы отказывает лишь при
	 * непереданных местах, а те отсечены заслоном выше. Слагаемое оставлено ради
	 * самостоятельности выражения: молчаливый пропуск отказа наложения гаммы выдал бы
	 * наружу неполный шифртекст
	 */
	// Отмечаем начальное заполнение счётчика израсходованным на зашифрование
	this->_spent = true;
	// Если сообщение всё же передано
	if((source.size > 0) && !gamma(this->_block, this->_nonce, source, result))
		// Выводим отказ зашифрования
		return false;
	// Выработанная метка целостности длиной в блок шифра
	uint8_t buffer[MODE_BLOCK];
	// Выполняем выработку метки целостности по связанным данным и шифртексту
	if(!authenticate(this->_block, this->_nonce, associated, view_t(result, source.size), buffer)){
		// Выполняем затирание выработанной метки целостности
		wipe(buffer, sizeof(buffer));
		// Выводим отказ зашифрования
		return false;
	}
	// Выполняем усечение выработанной метки целостности до требуемой длины
	::memcpy(tag, buffer, this->_size);
	// Выполняем затирание выработанной метки целостности
	wipe(buffer, sizeof(buffer));
	// Выводим успешность зашифрования
	return true;
}
/**
 * @brief Метод расшифрования сообщения с проверкой метки целостности
 *
 * @param associated связанные данные, целостность которых проверяется без их расшифрования
 * @param source     расшифровываемый шифртекст
 * @param result     место, в которое помещается открытый текст
 * @param tag        проверяемая метка целостности
 * @return           признак успешности расшифрования
 *
 */
bool nts::cipher::Galois::decrypt(const view_t & associated, const view_t & source, uint8_t * result, const view_t & tag) noexcept {
	// Если режим не готов к работе либо метка целостности передана неверно
	if(!this->_ready || (tag.data == nullptr) || (tag.size != this->_size))
		// Выводим отказ расшифрования
		return false;
	// Если расшифровываемый шифртекст передан неверно
	if((source.size > 0) && ((source.data == nullptr) || (result == nullptr)))
		// Выводим отказ расшифрования
		return false;
	// Если связанные данные переданы неверно
	if((associated.size > 0) && (associated.data == nullptr))
		// Выводим отказ расшифрования
		return false;
	// Если ни связанных данных, ни шифртекста не передано
	if((associated.size == 0) && (source.size == 0))
		// Выводим отказ расшифрования
		return false;
	/**
	 * Раздел 4.1 RFC 9058 держит суммарную длину связанных данных и шифртекста ниже
	 * 2^(n/2) разрядов: длины эти пишутся в метку целостности половинами блока
	 */
	if(!measurable(associated.size, source.size, this->_block.size))
		// Выводим отказ расшифрования
		return false;
	// Выработанная метка целостности длиной в блок шифра
	uint8_t buffer[MODE_BLOCK];
	// Выполняем выработку метки целостности по связанным данным и шифртексту
	if(!authenticate(this->_block, this->_nonce, associated, source, buffer)){
		// Выполняем затирание выработанной метки целостности
		wipe(buffer, sizeof(buffer));
		// Выводим отказ расшифрования
		return false;
	}
	// Собираемое расхождение метки целостности
	uint8_t difference = 0;
	/**
	 * Выполняем сличение выработанной метки целостности с проверяемой: сличение
	 * ведётся целиком, без выхода при первом же расхождении, иначе время работы
	 * выдало бы длину совпавшего начала метки
	 */
	for(size_t i = 0; i < this->_size; i++)
		// Собираем расхождение очередных байтов метки целостности
		difference = static_cast <uint8_t> (difference | (buffer[i] ^ tag.data[i]));
	// Выполняем затирание выработанной метки целостности
	wipe(buffer, sizeof(buffer));
	// Если метки целостности разошлись
	if(difference != 0)
		// Выводим отказ расшифрования
		return false;
	/**
	 * Открытый текст записывается лишь теперь, когда метка целостности сошлась:
	 * расшифрованное сообщение с непроверенной меткой выдавать наружу нельзя
	 */
	/**
	 * Слагаемое !gamma(...) ложно всегда: наложение гаммы отказывает лишь при
	 * непереданных местах, а те отсечены заслоном выше. Слагаемое оставлено ради
	 * самостоятельности выражения: молчаливый пропуск отказа наложения гаммы выдал бы
	 * наружу неполный шифртекст
	 */
	if((source.size > 0) && !gamma(this->_block, this->_nonce, source, result))
		// Выводим отказ расшифрования
		return false;
	// Выводим успешность расшифрования
	return true;
}
/**
 * @brief Конструктор
 *
 */
nts::cipher::Galois::Galois() noexcept : _ready(false), _spent(false), _size(0) {
	// Выполняем затирание начального заполнения счётчика
	wipe(this->_nonce, sizeof(this->_nonce));
}
/**
 * @brief Деструктор
 *
 */
nts::cipher::Galois::~Galois() noexcept {
	// Выполняем сброс состояния режима работы
	this->clear();
}
