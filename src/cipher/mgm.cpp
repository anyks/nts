	#if defined(__ANTS_CARRYLESS__)
		/**
		 * @brief Функция умножения чисел без переносов машинной командой
		 *
		 * @param first  первый сомножитель
		 * @param second второй сомножитель
		 * @param hi     место, в которое помещается старшая половина произведения
		 * @param lo     место, в которое помещается младшая половина произведения
		 *
		 * @note Машинная команда работает одно и то же время при всяких сомножителях:
		 *       ни ветвления, ни обращения к памяти по значению в ней нет
		 *
		 */
		static void carryless(const uint64_t first, const uint64_t second, uint64_t & hi, uint64_t & lo) noexcept {
			/**
			 * Если умножение ведётся командой PMULL
			 */
			#if defined(__aarch64__)
				// Выполняем умножение сомножителей без переносов
				const uint64x2_t value = vreinterpretq_u64_p128(vmull_p64(static_cast <poly64_t> (first), static_cast <poly64_t> (second)));
				// Записываем младшую половину произведения
				lo = vgetq_lane_u64(value, 0);
				// Записываем старшую половину произведения
				hi = vgetq_lane_u64(value, 1);
			/**
			 * Если умножение ведётся командой PCLMULQDQ
			 */
			#else
				// Выполняем умножение сомножителей без переносов
				const __m128i value = _mm_clmulepi64_si128(_mm_set_epi64x(0, static_cast <long long> (first)), _mm_set_epi64x(0, static_cast <long long> (second)), 0x00);
				// Записываем младшую половину произведения
				lo = static_cast <uint64_t> (_mm_cvtsi128_si64(value));
				/**
				 * Старшая половина снимается перестановкой, а не извлечением по месту:
				 * извлечение потребовало бы набора команд SSE4.1, тогда как самому
				 * умножению без переносов довольно SSE2, и лишний набор сузил бы круг
				 * машин, на которых собирается быстрый путь
				 */
				hi = static_cast <uint64_t> (_mm_cvtsi128_si64(_mm_unpackhi_epi64(value, value)));
			#endif
		}
	#endif
