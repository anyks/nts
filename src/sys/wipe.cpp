/**
 * Подключаем заголовочные файлы проекта
 */
#include <cstdint>
#include <sys/wipe.hpp>

/**
 * Используем стандартное пространство имён
 */
using namespace std;

/**
 * @brief Метод затирания области памяти
 *
 * @param data затираемая область памяти
 * @param size размер затираемой области памяти в байтах
 *
 */
void nts::sys::wipe(void * data, const size_t size) noexcept {
	// Если область памяти передана
	if((data != nullptr) && (size > 0)){
		// Изменчивый указатель на байты области: запись через него собиратель не выбрасывает
		volatile uint8_t * item = static_cast <volatile uint8_t *> (data);
		// Число байтов до выравнивания на слово
		const size_t head = ((8 - (reinterpret_cast <uintptr_t> (data) & 7)) & 7);
		// Смещение затираемого байта
		size_t offset = 0;
		/**
		 * Выполняем затирание байтов до границы слова
		 */
		for(; (offset < head) && (offset < size); offset++)
			// Обнуляем очередной байт
			item[offset] = 0;
		/**
		 * Выполняем затирание словами: восемь байтов записью, а не восемью - у процессоров
		 * с широкой командой и в отладочных сборках побайтная запись стоила столько же,
		 * сколько сама арифметика над затираемым числом
		 */
		for(; (offset + 8) <= size; offset += 8)
			// Обнуляем очередное слово через изменчивый указатель на слово
			*reinterpret_cast <volatile uint64_t *> (static_cast <uint8_t *> (data) + offset) = 0;
		/**
		 * Выполняем затирание хвоста, не кратного слову
		 */
		for(; offset < size; offset++)
			// Обнуляем очередной байт
			item[offset] = 0;
	}
}
/**
 * @brief Метод затирания набора байтов с его опустошением
 *
 * @param data затираемый набор байтов; после затирания пуст
 *
 */
void nts::sys::wipe(vector <uint8_t> & data) noexcept {
	// Затираем содержимое набора байтов
	wipe(data.data(), data.size());
	// Опустошаем набор байтов
	data.clear();
}
/**
 * @brief Метод затирания строки с её опустошением
 *
 * @param data затираемая строка; после затирания пуста
 *
 */
void nts::sys::wipe(string & data) noexcept {
	// Затираем содержимое строки: у строки собственный буфер, и запись в него законна
	wipe(&data[0], data.size());
	// Опустошаем строку
	data.clear();
}
