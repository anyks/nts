/**
 * Стандартные модули
 */
#include <cstring>
#include <iomanip>
#include <iostream>

/**
 * Подключаем заголовочные файлы проекта
 */
#include <agreement/ffdhe.hpp>

/**
 * Используем стандартное пространство имён
 */
using namespace std;

/**
 * Подписываемся на пространство имён библиотеки
 */
using namespace nts;

/**
 * @brief Пространство имён образца
 *
 */
namespace {
	/**
	 * @brief Функция вывода области байтов шестнадцатеричной записью
	 *
	 * @param title заголовок выводимой области байтов
	 * @param data  выводимая область байтов
	 * @param size  размер выводимой области байтов
	 *
	 */
	void print(const char * title, const uint8_t * data, const size_t size) noexcept {
		// Выводим заголовок области байтов
		cout << title << ": ";
		/**
		 * Выполняем перебор байтов выводимой области
		 */
		for(size_t i = 0; i < size; i++)
			// Выводим очередной байт шестнадцатеричной записью
			cout << hex << setw(2) << setfill('0') << static_cast <uint32_t> (data[i]);
		// Выполняем перевод строки за областью байтов
		cout << dec << endl;
	}
};

/**
 * @brief Функция запуска приложения
 *
 * @param argc длина массива параметров
 * @param argv массив параметров
 * @return     код выхода из приложения
 *
 */
int main(int argc, char * argv[]) noexcept {
	// Не используем параметры приложения
	(void) argc;
	// Не используем параметры приложения
	(void) argv;
	// Длина модуля группы ffdhe2048 в байтах
	const size_t size = 256;
	// Секретный показатель первой стороны и её открытый ключ
	uint8_t secretA[32], keyA[256];
	// Секретный показатель второй стороны и её открытый ключ
	uint8_t secretB[32], keyB[256];
	/**
	 * Выполняем выработку пары ключей первой стороны
	 *
	 * @details Показатель берётся длиной exponent(size) по разделу 5.2 RFC 7919 - не
	 *          короче удвоенной стойкости группы; открытый ключ есть 2^x mod p длиной модуля
	 *
	 */
	if(!agreement::pairffdhe(size, secretA, keyA)){
		// Выводим сообщение об отказе выработки пары
		cout << "Выработать пару первой стороны не удалось" << endl;
		// Выходим из приложения с признаком отказа
		return EXIT_FAILURE;
	}
	// Выполняем выработку пары ключей второй стороны
	if(!agreement::pairffdhe(size, secretB, keyB)){
		// Выводим сообщение об отказе выработки пары
		cout << "Выработать пару второй стороны не удалось" << endl;
		// Выходим из приложения с признаком отказа
		return EXIT_FAILURE;
	}
	// Выводим начало открытого ключа первой стороны
	::print("Открытый ключ A    ", keyA, 16);
	// Общее значение у первой и у второй стороны
	uint8_t sharedA[256], sharedB[256];
	/**
	 * Выполняем выработку общего значения первой стороной
	 *
	 * @details Общее значение есть Y^x mod p: встречный открытый ключ возводится в свой
	 *          показатель, и у обеих сторон выходит одно значение. Встречный ключ сверяется
	 *          прежде выработки: 1 < Y < p − 1, как велит раздел 4.2.8.1 RFC 8446
	 *
	 */
	if(!agreement::ffdhe(size, view_t(secretA, sizeof(secretA)), view_t(keyB, sizeof(keyB)), sharedA)){
		// Выводим сообщение об отказе выработки общего значения
		cout << "Выработать общее значение первой стороны не удалось" << endl;
		// Выходим из приложения с признаком отказа
		return EXIT_FAILURE;
	}
	// Выполняем выработку общего значения второй стороной
	if(!agreement::ffdhe(size, view_t(secretB, sizeof(secretB)), view_t(keyA, sizeof(keyA)), sharedB)){
		// Выводим сообщение об отказе выработки общего значения
		cout << "Выработать общее значение второй стороны не удалось" << endl;
		// Выходим из приложения с признаком отказа
		return EXIT_FAILURE;
	}
	// Выводим начала общих значений сторон
	::print("Общее значение A   ", sharedA, 16);
	::print("Общее значение B   ", sharedB, 16);
	// Если общие значения сторон разошлись
	if(::memcmp(sharedA, sharedB, sizeof(sharedA)) != 0){
		// Выводим сообщение о расхождении общих значений
		cout << "Общие значения сторон разошлись" << endl;
		// Выходим из приложения с признаком отказа
		return EXIT_FAILURE;
	}
	// Выводим сообщение о совпадении общих значений
	cout << "Общий секрет       : значения сторон сошлись" << endl;
	// Выводим длину модуля группы modp14 (RFC 3526) для сличения
	cout << "Модуль modp14      : " << agreement::prime3526(14).size << " байтов у SSH" << endl;
	// Выходим из приложения с признаком успеха
	return EXIT_SUCCESS;
}
