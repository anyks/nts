/**
 * @note Пути (круг 37, 23.09.2026). Переносимый путь - пять конечностей по 26 разрядов,
 *       блоки парами (h + m0) * r^2 + m1 * r. 64-разрядный путь у собирателей с числом
 *       в 128 разрядов - три конечности по 64 разряда и пять произведений 64×64 на блок
 *       вместо двадцати пяти 32×32: на x86-64 1,0 → 2,0 ГБ/с, вровень с целочисленным
 *       путём OpenSSL; на x86-64 те же блоки идут ядром на ассемблере, ибо GCC переводит
 *       число в 128 разрядов хуже clang (Astra 1,2 ГБ/с). Векторные ветви NEON и AVX2 - восемь блоков разом на восьми
 *       дорожках по 26 разрядов: всякая дорожка ведёт свою сумму и умножается на r^8,
 *       последняя восьмёрка умножается на r^8…r по дорожкам, и дорожки складываются;
 *       накопитель между вызовами хранится тремя конечностями по 64 разряда, а в
 *       векторную ветвь и обратно переводится на месте. Четырёх дорожек мало: цепочка
 *       произведение - переносы одной дорожки тянется десятки тактов, и две пары
 *       дорожек давали на M4 лишь 3,2 ГБ/с - хуже скалярных пар; восемь дорожек - четыре
 *       независимые цепочки. Степени r^2…r^8 считаются лишь при первом входе в
 *       векторную ветвь: имитовставка заводится на каждую запись связи, и семь лишних
 *       умножений на короткую запись были бы видны. Основание 2^44 на четырёх блоках
 *       пробовано: на M4 6,9 ГБ/с против 4,6 у пар, но на x86 хуже основания 2^64 (1,6
 *       против 2,0) - оно упирается в число команд умножения; не взято. Эльбрус
 *       остаётся на переносимом пути: число в 128 разрядов у lcc есть, но произведения
 *       через него вдвое медленнее пар (1,28 → 0,85 ГБ/с). Векторная ветвь берётся от
 *       256 байтов целых блоков.
 *       NEON двумя четвёрками (круг 38, 24.09.2026): четыре пары дорожек в массиве под
 *       циклом собиратель держал в памяти, грузя и сохраняя конечности на каждой паре, а
 *       перенос между конечностями произведения переставлял в начало цепочки умножений
 *       следующей конечности, вытягивая двадцать пять умножений пары в одну цепочку.
 *       Теперь восемь блоков идут двумя четвёрками дорожек по 32 разряда в регистрах, а
 *       произведения закрепляются пустыми вставками ассемблера до переносов: M4 5,2 →
 *       9,2 ГБ/с при 8,2 у OpenSSL (221 команда на восьмёрку вместо 332).
 *       Ядро AVX2 на ассемблере (круг 42, 28.09.2026): ветви на интринсиках собиратель давал
 *       десять векторов степеней, десять дорожек, пять конечностей блоков и пять произведений
 *       на шестнадцать регистров - перегрузки через стек на каждой четвёрке (Xeon E5-2630 v4
 *       3,0 ГБ/с при 3,4 у OpenSSL). Ядро из tools/cipher/poly1305.py ведёт четыре дорожки:
 *       конечности r^4 и 5·r^4 берутся операндами в памяти, переносы идут двумя переплетёнными
 *       потоками, конечности блоков разбираются в регистры произведений после переносов, и
 *       регистров хватает без перегрузок; степени нужны лишь до r^4, стол ядра строится вместе
 *       с ними на каждый ключ (степени 64-разрядным ядром пробованы: выигрыша нет, а перенос за
 *       2^130 при h2 = 4 не закрыть проверкой - не взято). Ветвь на интринсиках остаётся
 *       собирателям без ядра и сборке под ASan без оптимизации. Затирание (круги 42 и 45): clear
 *       звался из start и finish, и шесть затираний по полям давали двенадцать вызовов wipe на
 *       сообщение - 303 такта TSC из 1 426 на записи в 1 200 байтов; круг 42 объявил секретные поля
 *       подряд под одним доступом с затиранием одним вызовом, дорожки итога и конечности ядра положил
 *       за стол в объекте (216 тактов из 1 266 на два затирания). Круг 45 (29.09.2026) снял затирание
 *       из start и finish вовсе: ключ одноразовый, у AEAD он выведен из нулевого блока гаммы под
 *       ключом сеанса, который живёт в объекте шифра, пока жив сеанс, и затирание одноразового
 *       ключа между сообщениями не защищало ничего; start обнуляет накопители и признаки прямо,
 *       степени и стол строятся заново под новый ключ, затирают clear и разрушитель. У OpenSSL
 *       затирания нет вовсе
 *
 */

