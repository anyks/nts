/**
 * Стандартные модули
 */
#include <vector>
#include <cstring>
#include <iostream>

/**
 * Подключаем заголовочные файлы проекта
 */
#include <record/record.hpp>

/**
 * Используем стандартное пространство имён
 */
using namespace std;

/**
 * Подписываемся на пространство имён библиотеки
 */
using namespace nts;

/**
 * @brief Пространство имён образца
 *
 */
namespace {
	/**
	 * @brief Функция получения названия вида содержимого записи
	 *
	 * @param type вид содержимого записи
	 * @return     название вида содержимого записи
	 *
	 */
	const char * title(const record::type_t type) noexcept {
		/**
		 * Выполняем определение вида содержимого записи
		 */
		switch(static_cast <uint8_t> (type)){
			// Если это извещение о смене набора шифрования
			case static_cast <uint8_t> (record::type_t::CHANGE): return "смена набора";
			// Если это извещение о событии либо об отказе
			case static_cast <uint8_t> (record::type_t::ALERT): return "извещение";
			// Если это сообщение рукопожатия
			case static_cast <uint8_t> (record::type_t::HANDSHAKE): return "рукопожатие";
			// Если это данные прикладного протокола
			case static_cast <uint8_t> (record::type_t::APPLICATION): return "прикладные данные";
		}
		// Выводим название неизвестного вида содержимого записи
		return "неизвестно";
	}
};

/**
 * @brief Функция запуска приложения
 *
 * @param argc длина массива параметров
 * @param argv массив параметров
 * @return     код выхода из приложения
 *
 */
int main(int argc, char * argv[]) noexcept {
	// Не используем параметры приложения
	(void) argc;
	// Не используем параметры приложения
	(void) argv;
	// Объект нарезчика исходящих записей
	record::writer_t writer;
	/**
	 * Устанавливаем предел длины содержимого нарезаемой записи
	 *
	 * @note Умолчанием предел равен наибольшей длине, дозволенной протоколом. Здесь он
	 *       опущен нарочно, чтобы сообщение легло не в одну запись, а в несколько
	 *
	 */
	if(!writer.limit(24)){
		// Выводим сообщение об отказе установки предела
		cout << "Установить предел длины записи не удалось" << endl;
		// Выходим из приложения с признаком отказа
		return EXIT_FAILURE;
	}
	// Нарезаемое на записи сообщение рукопожатия
	const char * message = "Сообщение рукопожатия, которое в одну запись не помещается";
	// Выполняем нарезку сообщения рукопожатия на записи
	if(writer.push(record::type_t::HANDSHAKE, record::version_t::TLS12, view_t(reinterpret_cast <const uint8_t *> (message), ::strlen(message))) != record::error_t::NONE){
		// Выводим сообщение об отказе нарезки сообщения
		cout << "Нарезать сообщение на записи не удалось" << endl;
		// Выходим из приложения с признаком отказа
		return EXIT_FAILURE;
	}
	// Выполняем нарезку извещения о смене набора шифрования
	writer.push(record::type_t::CHANGE, record::version_t::TLS12, view_t(reinterpret_cast <const uint8_t *> ("\x01"), 1));
	// Получаем готовый поток нарезанных записей
	const view_t data = writer.data();
	// Выводим объём готового потока нарезанных записей
	cout << "Нарезано байтов    : " << data.size << endl;
	// Поток байтов, подаваемый сборщику входящих записей
	const vector <uint8_t> stream(data.data, data.data + data.size);
	// Объект сборщика входящих записей
	record::reader_t reader;
	// Число уже собранных записей
	size_t count = 0;
	// Содержимое собранных записей рукопожатия, склеенное обратно
	vector <uint8_t> assembled;
	// Место чтения в подаваемом потоке байтов
	size_t offset = 0;
	// Длина очередного подаваемого куска потока
	size_t chunk = 1;
	/**
	 * Выполняем подачу потока байтов кусками разной длины
	 *
	 * @note Длина куска нарочно берётся всякий раз иною: слой записей обязан вести себя
	 *       одинаково и когда запись приходит целиком, и когда она приходит по байту
	 *
	 */
	while(offset < stream.size()){
		// Определяем длину очередного подаваемого куска
		const size_t size = ((stream.size() - offset) < chunk ? (stream.size() - offset) : chunk);
		// Выполняем подачу очередного куска потока байтов
		if(reader.push(view_t(stream.data() + offset, size)) != record::error_t::NONE){
			// Выводим сообщение об отказе подачи куска потока
			cout << "Подать кусок потока сборщику не удалось" << endl;
			// Выходим из приложения с признаком отказа
			return EXIT_FAILURE;
		}
		// Подвигаем место чтения в подаваемом потоке байтов
		offset += size;
		// Увеличиваем длину очередного подаваемого куска
		chunk = ((chunk * 2) + 1);
		// Заголовок очередной собранной записи
		record::header_t header;
		// Содержимое очередной собранной записи
		view_t payload;
		/**
		 * Выполняем выборку всех собранных на этот миг записей
		 */
		while(reader.next(header, payload) == record::error_t::NONE){
			// Увеличиваем число уже собранных записей
			count++;
			// Выводим вид содержимого и длину очередной собранной записи
			cout << "Запись " << count << ": " << ::title(header.type) << ", длина " << header.size << endl;
			/**
			 * Выполняем склейку содержимого собранной записи рукопожатия
			 *
			 * @note Границы записей границам сообщения не подчиняются: запись вправе
			 *       оборваться посреди знака, и печатать её содержимое поштучно
			 *       бестолку - его склеивает слой выше
			 *
			 */
			if(header.type == record::type_t::HANDSHAKE)
				// Выполняем склейку содержимого очередной записи рукопожатия
				assembled.insert(assembled.end(), payload.data, payload.data + payload.size);
		}
	}
	// Выводим число собранных записей
	cout << "Собрано записей    : " << count << endl;
	// Выводим объём неразобранного остатка накопителя сборщика
	cout << "Осталось в разборе : " << reader.pending() << endl;
	// Выводим склеенное обратно содержимое записей рукопожатия
	cout << "Склеено обратно    : " << string(reinterpret_cast <const char *> (assembled.data()), assembled.size()) << endl;
	// Выходим из приложения с признаком успеха
	return EXIT_SUCCESS;
}
