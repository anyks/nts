			/**
			 * Ядра на четыре слова для x86-64 на встроенном ассемблере у gcc и clang: у gcc код
			 * из __int128 хуже ручного на треть (Astra, gcc 12: умножение 46 → 31,5 нс, квадрат
			 * 38 → 25,5). У clang одно ядро цепочкой ручное медленнее собранного им самим
			 * (FreeBSD, clang 19: умножение 26,6 → 32 нс), и порознь ядра ему не годились:
			 * ассемблерное умножение с C++ сложениями давало удвоение точки 256 → 262 нс, а
			 * ассемблерные сложения с C++ умножением 256 → 275 - через память они друг с другом
			 * не дружат. Все четыре ядра вместе (умножение, квадрат, сложение, вычитание)
			 * дружат: умножение точки 104 → 90 мкс, сличение подписи 7,5 → 8,1…8,5 тыс./с,
			 * обмен ключами 9,0…9,3 → 10,1…10,3 (FreeBSD, clang 19, замер 22.09.2026), оттого
			 * ядра заведены и у clang. Простое P-256 идёт теми же телами произведения и квадрата
			 * (макросы __ANTS_X86_64_PRODUCT4__ и __ANTS_X86_64_SQUARE4__) с приведением
			 * Монтгомери сдвигами и вычитаниями (settlenist4) и своими сложением и вычитанием:
			 * числа по стендам в CONFORMANCE.md, круг 24. Формулы точки собираются из ядер на
			 * значениях (multiplyminus4v и прочие ниже): итог умножения остаётся в регистрах,
			 * сложения и вычитания идут целиком в регистрах - удвоение точки P-256 FreeBSD 281 → 260 нс,
			 * Astra 274 → 235, MinGW 280 → 257 при 194…199 у ecp_nistz256, умножение точки 98…100 → 87…94 мкс;
			 * сличение и обмен ГОСТ на x86 сравнялись с ECDSA и ECDH P-256 на ассемблере (CONFORMANCE.md,
			 * круг 26). Формулы точки целиком одним телом на ассемблере (кадр на стеке, все операнды
			 * по смещениям от одного регистра, по образцу ecp_nistz256_point_double) испытаны щупом
			 * на трёх стендах x86 и НЕ быстрее сборки из ядер на значениях: удвоение 203…230 нс против
			 * 206…225 - собиратель стыкует вставки не хуже руки, а остаток над nistz256 (8…10 % по
			 * формуле без обёртки) лежит в цепочках задержек самих ядер. Оттуда взяты два устройства
			 * nistz256 (CONFORMANCE.md, круг 27): умножение по P-256 с приведением, переплетённым со
			 * строками произведения (__ANTS_X86_64_NIST_MULMONT__, одно тело на четырнадцати
			 * регистрах), и сложения через копию с выбором cmov (две цепочки зависимостей вместо
			 * трёх): удвоение P-256 FreeBSD 260 → 245, MinGW 257 → 243, умножение точки 93,6 → 87,1 и
			 * 92,6 → 87,6 мкс, обмен ECDH P-256 на FreeBSD и Astra вровень с nistz256. Прочие варианты
			 * ядер (слово второго сомножителя в регистре при полном произведении, свёртка 2^256 - c
			 * по Горнеру сверху) выигрыша не показали либо не обещали его по счёту цепочек.
			 * Команды mulx/adx не берутся: их нет у стендов, а без
			 * замера путь не заводится. Произведение считается по одному слову с проносом переноса
			 * (add/adc/adc $0), регистров впритык к пятнадцати: тело разбито на два вставных
			 * блока, между ними накопитель живёт в переменных. Хвост c и указатель на модуль
			 * передаются через структуру, чтобы не занимать регистры. Времени от значений
			 * нет: ветвлений нет, выбор итога через cmov. Входы читаются до первой записи
			 */
