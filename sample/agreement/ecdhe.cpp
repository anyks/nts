/**
 * Стандартные модули
 */
#include <cstring>
#include <iomanip>
#include <iostream>

/**
 * Подключаем заголовочные файлы проекта
 */
#include <agreement/ecdhe.hpp>
#include <curve/parameters.hpp>

/**
 * Используем стандартное пространство имён
 */
using namespace std;

/**
 * Подписываемся на пространство имён библиотеки
 */
using namespace nts;

/**
 * @brief Пространство имён образца
 *
 */
namespace {
	/**
	 * @brief Опознаватель кривой обмена мимолётными ключами образца
	 *
	 */
	static const char * CURVE = "1.2.643.2.2.35.1";

	/**
	 * @brief Метод вывода области байтов шестнадцатеричной записью
	 *
	 * @param title заголовок выводимой области байтов
	 * @param data  выводимая область байтов
	 * @param size  размер выводимой области байтов
	 *
	 */
	static void print(const char * title, const uint8_t * data, const size_t size) noexcept {
		// Выводим заголовок области байтов
		cout << title << ": ";
		/**
		 * Выполняем перебор байтов выводимой области
		 */
		for(size_t i = 0; i < size; i++)
			// Выводим очередной байт области шестнадцатеричной записью
			cout << hex << uppercase << setw(2) << setfill('0') << static_cast <uint16_t> (data[i]);
		// Выводим перевод строки
		cout << dec << endl;
	}
};

/**
 * @brief Функция запуска приложения
 *
 * @param argc длина массива параметров
 * @param argv массив параметров
 *
 * @return     код выхода из приложения
 *
 */
int main(int argc, char * argv[]) noexcept {
	// Не используем параметры приложения
	(void) argc;
	// Не используем параметры приложения
	(void) argv;
	// Эллиптическая кривая обмена мимолётными ключами
	curve::curve_t curve;
	// Если кривую обмена мимолётными ключами завести не удалось
	if(!curve::parameters(CURVE, curve)){
		// Выводим сообщение об отказе заведения кривой
		cout << "Завести кривую обмена мимолётными ключами не удалось" << endl;
		// Выходим из приложения с признаком отказа
		return EXIT_FAILURE;
	}
	// Мимолётная пара ключей клиента
	uint8_t secret[32] = {0}, opened[64] = {0};
	// Мимолётная пара ключей сервера
	uint8_t element[32] = {0}, answer[64] = {0};
	// Если мимолётную пару ключей клиента выработать не удалось
	if(!agreement::generate(curve, secret, opened)){
		// Выводим сообщение об отказе выработки пары ключей
		cout << "Выработать мимолётную пару ключей клиента не удалось" << endl;
		// Выходим из приложения с признаком отказа
		return EXIT_FAILURE;
	}
	// Если мимолётную пару ключей сервера выработать не удалось
	if(!agreement::generate(curve, element, answer)){
		// Выводим сообщение об отказе выработки пары ключей
		cout << "Выработать мимолётную пару ключей сервера не удалось" << endl;
		// Выходим из приложения с признаком отказа
		return EXIT_FAILURE;
	}
	// Выводим открытый ключ клиента, уходящий приветствием
	print("Открытый ключ клиента", opened, sizeof(opened));
	// Выводим открытый ключ сервера, уходящий приветствием
	print("Открытый ключ сервера", answer, sizeof(answer));
	// Общие значения, выработанные сторонами связи
	uint8_t client[32] = {0}, server[32] = {0};
	// Если общее значение стороной клиента выработать не удалось
	if(!agreement::ecdhe(curve, view_t(secret, sizeof(secret)), view_t(answer, sizeof(answer)), client)){
		// Выводим сообщение об отказе выработки общего значения
		cout << "Выработать общее значение стороной клиента не удалось" << endl;
		// Выходим из приложения с признаком отказа
		return EXIT_FAILURE;
	}
	// Если общее значение стороной сервера выработать не удалось
	if(!agreement::ecdhe(curve, view_t(element, sizeof(element)), view_t(opened, sizeof(opened)), server)){
		// Выводим сообщение об отказе выработки общего значения
		cout << "Выработать общее значение стороной сервера не удалось" << endl;
		// Выходим из приложения с признаком отказа
		return EXIT_FAILURE;
	}
	// Выводим общее значение, выработанное стороной клиента
	print("Значение у клиента   ", client, sizeof(client));
	// Выводим общее значение, выработанное стороной сервера
	print("Значение у сервера   ", server, sizeof(server));
	// Если общие значения сторон разошлись
	if(::memcmp(client, server, sizeof(client)) != 0){
		// Выводим сообщение о расхождении общих значений сторон
		cout << "Общие значения сторон разошлись" << endl;
		// Выходим из приложения с признаком отказа
		return EXIT_FAILURE;
	}
	// Выводим сообщение о схождении общих значений сторон
	cout << "Стороны получили одно и то же значение, по связи его не передав" << endl;
	// Выходим из приложения с признаком успеха
	return EXIT_SUCCESS;
}
