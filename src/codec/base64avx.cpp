/**
 * Иначе векторные команды разрешает атрибут цели
 */
#else
/**
 * Разрешаем векторные команды одной функции: чек ключа -mavx2 утилитой сторонней
 * сборки может не пройти, и атрибут держит команды при функции сам
 */
