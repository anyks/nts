		/**
		 * @brief Ступени рукопожатия издания TLS 1.2
		 *
		 * @details Раздел 7.3 RFC 5246: порядок сообщений издания TLS 1.2 иной, нежели у
		 *          TLS 1.3, и ход рукопожатия ему не подходит; ступень называет сообщение,
		 *          которого связь ждёт от собеседника следующим
		 *
		 */
		enum class phase_t : uint8_t {
			NONE        = 0x00, // Рукопожатие издания TLS 1.2 не ведётся
			CERTIFICATE = 0x01, // Ожидается цепочка сертификатов сервера
			STATUS      = 0x02, // Ожидается состояние сертификата сервера либо его обмен ключами
			AGREEMENT   = 0x03, // Ожидается обмен ключами сервера
			REQUEST     = 0x04, // Ожидается запрос подлинности клиента либо конец приветствия сервера
			DONE        = 0x05, // Ожидается конец приветствия сервера
			ANSWER      = 0x06, // Ожидается цепочка сертификатов клиента
			PREMASTER   = 0x07, // Ожидается обмен ключами клиента
			VERIFY      = 0x08, // Ожидается подпись владения ключом клиента
			CHANGE      = 0x09, // Ожидается смена набора шифрования собеседником
			FINISHED    = 0x0A, // Ожидается завершение рукопожатия собеседником
			ESTABLISHED = 0x0B, // Рукопожатие издания TLS 1.2 завершено
			EITHER      = 0x0C  // Клиент предъявил билет сеанса и ждёт либо полного рукопожатия (цепочка, обмен ключами), либо сокращённого (билет, смена набора)
		};
		/**
		 * @brief Места значений GREASE связи
		 *
		 * @details Раздел 2 RFC 8701: у каждого места своё значение вида 0x?A?A, выводимое
		 *          из зерна связи по байту на место, как у BoringSSL; расширениям клиента
		 *          отведены два места, и значения их различны
		 *
		 */
		/**
		 * @brief Состояние зашифрованного приветствия клиента ECH (RFC 9849)
		 *
		 */
		enum class ech_t : uint8_t {
			NONE     = 0x00, /*!< ECH не предлагалось */
			OFFERED  = 0x01, /*!< Внешнее приветствие с зашифрованным внутренним отправлено, ответ сервера ещё не судился */
			ACCEPTED = 0x02, /*!< Сервер подтвердил принятие: рукопожатие идёт по внутреннему приветствию */
			REJECTED = 0x03, /*!< Сервер ECH отверг: рукопожатие идёт по внешнему приветствию и публичному имени */
			GREASED  = 0x04  /*!< Отправлено лишь значение GREASE ECH: ответ сервера не значим */
		};
		/**
		 * @brief Место значения GREASE в приветствии
		 *
		 */
		enum class grease_t : uint8_t {
			SUITE   = 0x00, // Набор шифрования приветствия клиента
			GROUP   = 0x01, // Группа обмена и доля ключа приветствия клиента
			FIRST   = 0x02, // Первое расширение приветствия клиента и расширение запроса подлинности
			SECOND  = 0x03, // Последнее расширение приветствия клиента
			VERSION = 0x04, // Издание протокола приветствия клиента
			TICKET  = 0x05  // Расширение билета возобновления связи
		};
