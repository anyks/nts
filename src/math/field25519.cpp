/**
 * Используем стандартное пространство имён
 */
using namespace std;

/**
 * @brief Внутренние служебные объекты
 *
 */
namespace {
	/**
	 * Пространство имён библиотеки
	 */
	using namespace nts;

	/**
	 * Пространство имён модуля
	 */
	using namespace nts::math::field25519;

	/**
	 * @brief Удвоенное слово для произведений конечностей
	 *
	 */
	// Целое число двойной разрядности: __uint128_t либо своя запись у MSVC (math/wide.hpp)
	typedef nts::math::wide_t wide_t;

	/**
	 * @brief Маска пятидесяти одного разряда конечности
	 *
	 */
	static constexpr uint64_t MASK = ((static_cast <uint64_t> (1) << 51) - 1);

	/**
	 * @brief Младшая конечность удвоенного модуля
	 *
	 * @details Удвоенный модуль 2^256 - 38 раскладывается на конечности так: младшая
	 *          равна 2^52 - 38, каждая из прочих равна 2^52 - 2
	 *
	 */
	static constexpr uint64_t TWICE_LOW = ((static_cast <uint64_t> (1) << 52) - 38);

	/**
	 * @brief Старшие конечности удвоенного модуля
	 *
	 */
	static constexpr uint64_t TWICE_HIGH = ((static_cast <uint64_t> (1) << 52) - 2);

	/**
	 * @brief Функция волны переносов между конечностями
	 *
	 * @details Разряды всякой конечности сверх пятидесяти одного переносятся в следующую,
	 *          а перенос из старшей конечности возвращается в младшую с множителем
	 *          девятнадцать: 2^255 равно 19 по модулю поля. После волны конечности с
	 *          первой по четвёртую меньше 2^51, а младшая меньше 2^52
	 *
	 * @param value приводимый элемент
	 *
	 */
	static void carry(element_t & value) noexcept {
		// Перенос из младшей конечности во вторую
		uint64_t item = (value.limbs[0] >> 51);
		// Отбрасываем перенесённые разряды младшей конечности
		value.limbs[0] &= MASK;
		// Прибавляем перенос ко второй конечности
		value.limbs[1] += item;
		// Перенос из второй конечности в третью
		item = (value.limbs[1] >> 51);
		// Отбрасываем перенесённые разряды второй конечности
		value.limbs[1] &= MASK;
		// Прибавляем перенос к третьей конечности
		value.limbs[2] += item;
		// Перенос из третьей конечности в четвёртую
		item = (value.limbs[2] >> 51);
		// Отбрасываем перенесённые разряды третьей конечности
		value.limbs[2] &= MASK;
		// Прибавляем перенос к четвёртой конечности
		value.limbs[3] += item;
		// Перенос из четвёртой конечности в старшую
		item = (value.limbs[3] >> 51);
		// Отбрасываем перенесённые разряды четвёртой конечности
		value.limbs[3] &= MASK;
		// Прибавляем перенос к старшей конечности
		value.limbs[4] += item;
		// Перенос из старшей конечности в младшую с множителем сворачивания
		item = (value.limbs[4] >> 51);
		// Отбрасываем перенесённые разряды старшей конечности
		value.limbs[4] &= MASK;
		// Прибавляем свёрнутый перенос к младшей конечности
		value.limbs[0] += (item * 19);
	}
	/**
	 * @brief Функция полного приведения элемента до единственной записи
	 *
	 * @details После двух волн переносов элемент меньше 2^255 и мог остаться в области
	 *          от модуля до 2^255: признак этого выводится сложением с девятнадцатью
	 *          сквозь все конечности, и модуль вычитается наложением признака, а не
	 *          ветвлением по нему
	 *
	 * @param value приводимый элемент
	 *
	 */
	static void reduce(element_t & value) noexcept {
		// Первую волну переносов
		carry(value);
		// Вторую волну переносов: после первой младшая конечность могла вырасти
		carry(value);
		// Признак того, что элемент не меньше модуля: сложение с девятнадцатью выходит за 2^255
		uint64_t flag = ((value.limbs[0] + 19) >> 51);
		// Проносим признак сквозь вторую конечность
		flag = ((value.limbs[1] + flag) >> 51);
		// Проносим признак сквозь третью конечность
		flag = ((value.limbs[2] + flag) >> 51);
		// Проносим признак сквозь четвёртую конечность
		flag = ((value.limbs[3] + flag) >> 51);
		// Проносим признак сквозь старшую конечность
		flag = ((value.limbs[4] + flag) >> 51);
		// Прибавляем девятнадцать по признаку: вычитание модуля есть сложение с девятнадцатью и сброс 2^255
		value.limbs[0] += (flag * 19);
		/**
		 * Выполняем волну переносов без сворачивания: разряд 2^255 здесь сбрасывается,
		 * а не возвращается в младшую конечность, иначе модуль вычелся бы дважды
		 */
		for(size_t i = 0; i < (LIMBS - 1); i++){
			// Переносим разряды очередной конечности сверх пятидесяти одного в следующую
			value.limbs[i + 1] += (value.limbs[i] >> 51);
			// Отбрасываем перенесённые разряды очередной конечности
			value.limbs[i] &= MASK;
		}
		// Сбрасываем разряд 2^255 старшей конечности
		value.limbs[LIMBS - 1] &= MASK;
	}
	/**
	 * @brief Функция возведения элемента в степень 2^count
	 *
	 * @param value  возводимый элемент
	 * @param count  число возведений в квадрат
	 * @param result место, в которое помещается степень
	 *
	 */
	static void power(const element_t & value, const size_t count, element_t & result) noexcept {
		// Переносим возводимый элемент в место итога
		result = value;
		/**
		 * Выполняем возведение в квадрат заданное число раз
		 */
		for(size_t i = 0; i < count; i++)
			// Возводим накопленное значение в квадрат
			square(result, result);
	}
	/**
	 * @brief Функция возведения элемента в степень 2^250 - 1
	 *
	 * @details Общая часть цепочек обращения и извлечения корня: из неё обращение
	 *          выводится пятью квадратами и умножением на z^11, а корень - двумя
	 *          квадратами и умножением на z
	 *
	 * @param value  возводимый элемент
	 * @param eleven место, в которое помещается z^11
	 * @param result место, в которое помещается степень
	 *
	 */
	static void chain(const element_t & value, element_t & eleven, element_t & result) noexcept {
		// Промежуточные степени цепочки
		element_t z2, z9, z10, z50, item;
		// Вырабатываем z^2
		square(value, z2);
		// Вырабатываем z^4
		square(z2, item);
		// Вырабатываем z^8
		square(item, item);
		// Вырабатываем z^9
		mul(item, value, z9);
		// Вырабатываем z^11
		mul(z9, z2, eleven);
		// Вырабатываем z^22
		square(eleven, item);
		// Вырабатываем z^(2^5 - 1)
		mul(item, z9, item);
		// Вырабатываем z^(2^10 - 2^5)
		power(item, 5, z10);
		// Вырабатываем z^(2^10 - 1)
		mul(z10, item, z10);
		// Вырабатываем z^(2^20 - 2^10)
		power(z10, 10, item);
		// Вырабатываем z^(2^20 - 1)
		mul(item, z10, item);
		// Вырабатываем z^(2^40 - 2^20)
		power(item, 20, result);
		// Вырабатываем z^(2^40 - 1)
		mul(result, item, result);
		// Вырабатываем z^(2^50 - 2^10)
		power(result, 10, item);
		// Вырабатываем z^(2^50 - 1)
		mul(item, z10, z50);
		// Вырабатываем z^(2^100 - 2^50)
		power(z50, 50, item);
		// Вырабатываем z^(2^100 - 1)
		mul(item, z50, item);
		// Вырабатываем z^(2^200 - 2^100)
		power(item, 100, result);
		// Вырабатываем z^(2^200 - 1)
		mul(result, item, result);
		// Вырабатываем z^(2^250 - 2^50)
		power(result, 50, item);
		// Вырабатываем z^(2^250 - 1)
		mul(item, z50, result);
	}
};

/**
 * @brief Функция получения нуля поля
 *
 * @param result место, в которое помещается ноль поля
 *
 */
void nts::math::field25519::zero(element_t & result) noexcept {
	/**
	 * Выполняем перебор конечностей элемента
	 */
	for(size_t i = 0; i < LIMBS; i++)
		// Обнуляем очередную конечность
		result.limbs[i] = 0;
}
/**
 * @brief Функция получения единицы поля
 *
 * @param result место, в которое помещается единица поля
 *
 */
void nts::math::field25519::one(element_t & result) noexcept {
	// Обнуляем все конечности элемента
	zero(result);
	// Записываем единицу в младшую конечность
	result.limbs[0] = 1;
}
/**
 * @brief Функция разбора элемента поля из тридцати двух байтов
 *
 * @param data   разбираемые байты, записанные младшим байтом вперёд
 * @param result место, в которое помещается разобранный элемент
 *
 */
void nts::math::field25519::load(const uint8_t * data, element_t & result) noexcept {
	// Слова разбираемой записи
	uint64_t words[4];
	/**
	 * Выполняем перебор слов записи
	 */
	for(size_t i = 0; i < 4; i++){
		// Обнуляем очередное слово
		words[i] = 0;
		/**
		 * Выполняем перебор байтов очередного слова от старшего к младшему
		 */
		for(size_t j = 8; j > 0; j--)
			// Дописываем очередной байт в слово
			words[i] = ((words[i] << 8) | data[(i * 8) + (j - 1)]);
	}
	// Выделяем младшую конечность из первого слова
	result.limbs[0] = (words[0] & MASK);
	// Выделяем вторую конечность из первого и второго слов
	result.limbs[1] = (((words[0] >> 51) | (words[1] << 13)) & MASK);
	// Выделяем третью конечность из второго и третьего слов
	result.limbs[2] = (((words[1] >> 38) | (words[2] << 26)) & MASK);
	// Выделяем четвёртую конечность из третьего и четвёртого слов
	result.limbs[3] = (((words[2] >> 25) | (words[3] << 39)) & MASK);
	// Выделяем старшую конечность из четвёртого слова с отбрасыванием старшего разряда
	result.limbs[4] = ((words[3] >> 12) & MASK);
	// Приведение записи, не меньшей модуля
	reduce(result);
}
/**
 * @brief Функция записи элемента поля в тридцать два байта
 *
 * @param value записываемый элемент
 * @param data  место, в которое помещается запись младшим байтом вперёд
 *
 */
void nts::math::field25519::store(const element_t & value, uint8_t * data) noexcept {
	// Приводимая копия элемента
	element_t item = value;
	// Полное приведение элемента
	reduce(item);
	// Слова записываемого элемента
	uint64_t words[4];
	// Собираем первое слово из младшей и второй конечностей
	words[0] = (item.limbs[0] | (item.limbs[1] << 51));
	// Собираем второе слово из второй и третьей конечностей
	words[1] = ((item.limbs[1] >> 13) | (item.limbs[2] << 38));
	// Собираем третье слово из третьей и четвёртой конечностей
	words[2] = ((item.limbs[2] >> 26) | (item.limbs[3] << 25));
	// Собираем четвёртое слово из четвёртой и старшей конечностей
	words[3] = ((item.limbs[3] >> 39) | (item.limbs[4] << 12));
	/**
	 * Выполняем перебор слов записи
	 */
	for(size_t i = 0; i < 4; i++){
		/**
		 * Выполняем перебор байтов очередного слова от младшего к старшему
		 */
		for(size_t j = 0; j < 8; j++)
			// Записываем очередной байт слова
			data[(i * 8) + j] = static_cast <uint8_t> (words[i] >> (j * 8));
	}
}
/**
 * @brief Функция сложения элементов поля
 *
 * @param first  первое слагаемое
 * @param second второе слагаемое
 * @param result место, в которое помещается сумма
 *
 */
void nts::math::field25519::add(const element_t & first, const element_t & second, element_t & result) noexcept {
	/**
	 * Выполняем перебор конечностей слагаемых
	 */
	for(size_t i = 0; i < LIMBS; i++)
		// Складываем очередные конечности
		result.limbs[i] = (first.limbs[i] + second.limbs[i]);
	// Волну переносов
	carry(result);
}
/**
 * @brief Функция вычитания элементов поля
 *
 * @param first  уменьшаемое
 * @param second вычитаемое
 * @param result место, в которое помещается разность
 *
 */
void nts::math::field25519::sub(const element_t & first, const element_t & second, element_t & result) noexcept {
	// Вычитаем младшие конечности с прибавлением удвоенного модуля
	result.limbs[0] = ((first.limbs[0] + TWICE_LOW) - second.limbs[0]);
	/**
	 * Выполняем перебор старших конечностей
	 */
	for(size_t i = 1; i < LIMBS; i++)
		// Вычитаем очередные конечности с прибавлением удвоенного модуля
		result.limbs[i] = ((first.limbs[i] + TWICE_HIGH) - second.limbs[i]);
	// Волну переносов
	carry(result);
}
/**
 * @brief Функция умножения элементов поля
 *
 * @param first  первый сомножитель
 * @param second второй сомножитель
 * @param result место, в которое помещается произведение
 *
 */
void nts::math::field25519::mul(const element_t & first, const element_t & second, element_t & result) noexcept {
	// Умножаем ядром
	kernel::multiply(first, second, result);
}
/**
 * @brief Функция возведения элемента поля в квадрат
 *
 * @param value  возводимый элемент
 * @param result место, в которое помещается квадрат
 *
 */
void nts::math::field25519::square(const element_t & value, element_t & result) noexcept {
	// Возводим в квадрат ядром
	kernel::square(value, result);
}
/**
 * @brief Функция умножения элемента поля на малое число
 *
 * @param value  умножаемый элемент
 * @param factor множитель, не больше 2^32
 * @param result место, в которое помещается произведение
 *
 */
void nts::math::field25519::mul(const element_t & value, const uint64_t factor, element_t & result) noexcept {
	// Умножаем на малое число ядром
	kernel::scale(value, factor, result);
}
/**
 * @brief Функция обращения элемента поля
 *
 * @param value  обращаемый элемент
 * @param result место, в которое помещается обратный элемент
 *
 */
void nts::math::field25519::invert(const element_t & value, element_t & result) noexcept {
	// Степени z^11 и z^(2^250 - 1)
	element_t eleven, item;
	// Общую часть цепочки степеней
	chain(value, eleven, item);
	// Вырабатываем z^(2^255 - 32)
	power(item, 5, item);
	// Вырабатываем z^(2^255 - 21)
	mul(item, eleven, result);
}
/**
 * @brief Функция возведения элемента поля в степень (2^255 - 24) / 8
 *
 * @param value  возводимый элемент
 * @param result место, в которое помещается степень
 *
 */
void nts::math::field25519::root(const element_t & value, element_t & result) noexcept {
	// Степени z^11 и z^(2^250 - 1)
	element_t eleven, item;
	// Общую часть цепочки степеней
	chain(value, eleven, item);
	// Вырабатываем z^(2^252 - 4)
	power(item, 2, item);
	// Вырабатываем z^(2^252 - 3)
	mul(item, value, result);
}
/**
 * @brief Функция сличения элементов поля
 *
 * @param first  первый сличаемый элемент
 * @param second второй сличаемый элемент
 * @return       признак равенства элементов
 *
 */
bool nts::math::field25519::equal(const element_t & first, const element_t & second) noexcept {
	// Записи сличаемых элементов
	uint8_t a[SIZE], b[SIZE];
	// Записываем первый элемент
	store(first, a);
	// Записываем второй элемент
	store(second, b);
	// Накопленная разность записей
	uint8_t item = 0;
	/**
	 * Выполняем перебор байтов записей
	 */
	for(size_t i = 0; i < SIZE; i++)
		// Накапливаем разность очередных байтов
		item |= (a[i] ^ b[i]);
	// Выводим признак равенства: разность обратилась в ноль
	return (((static_cast <uint32_t> (item) - 1) >> 8) & 1);
}
/**
 * @brief Функция проверки обращения элемента поля в ноль
 *
 * @param value проверяемый элемент
 * @return      признак обращения элемента в ноль
 *
 */
bool nts::math::field25519::nil(const element_t & value) noexcept {
	// Ноль поля
	element_t item;
	// Выводим признак равенства элемента нулю
	return equal(value, item);
}
/**
 * @brief Функция условного обмена элементов поля
 *
 * @param first  первый обмениваемый элемент
 * @param second второй обмениваемый элемент
 * @param flag   признак обмена
 *
 */
void nts::math::field25519::swap(element_t & first, element_t & second, const uint64_t flag) noexcept {
	// Маска обмена: все разряды по признаку
	const uint64_t mask = (0 - (flag & 1));
	/**
	 * Выполняем перебор конечностей элементов
	 */
	for(size_t i = 0; i < LIMBS; i++){
		// Разность конечностей под маской
		const uint64_t item = ((first.limbs[i] ^ second.limbs[i]) & mask);
		// Накладываем разность на первую конечность
		first.limbs[i] ^= item;
		// Накладываем разность на вторую конечность
		second.limbs[i] ^= item;
	}
}
