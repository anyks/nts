#include <cstring>

/**
 * Подключаем заголовочные файлы проекта
 */
#include <cipher/magma.hpp>

/**
 * Используем стандартное пространство имён
 */
using namespace std;

/**
 * @brief Внутренние служебные объекты
 *
 */
namespace {
	/**
	 * Пространство имён библиотеки
	 */
	using namespace anyks;

	/**
	 * Пространство имён модуля
	 */
	using namespace anyks::cipher;

	/**
	 * @brief Набор нелинейных биективных преобразований
	 *
	 * @details Подстановки Pi'_0 ... Pi'_7 по разделу 4.1 ГОСТ Р 34.12-2015, набор
	 *          id-tc26-gost-28147-param-Z
	 *
	 */
	static constexpr uint8_t PI[8][16] = {
		{0x0C, 0x04, 0x06, 0x02, 0x0A, 0x05, 0x0B, 0x09, 0x0E, 0x08, 0x0D, 0x07, 0x00, 0x03, 0x0F, 0x01},
		{0x06, 0x08, 0x02, 0x03, 0x09, 0x0A, 0x05, 0x0C, 0x01, 0x0E, 0x04, 0x07, 0x0B, 0x0D, 0x00, 0x0F},
		{0x0B, 0x03, 0x05, 0x08, 0x02, 0x0F, 0x0A, 0x0D, 0x0E, 0x01, 0x07, 0x04, 0x0C, 0x09, 0x06, 0x00},
		{0x0C, 0x08, 0x02, 0x01, 0x0D, 0x04, 0x0F, 0x06, 0x07, 0x00, 0x0A, 0x05, 0x03, 0x0E, 0x09, 0x0B},
		{0x07, 0x0F, 0x05, 0x0A, 0x08, 0x01, 0x06, 0x0D, 0x00, 0x09, 0x03, 0x0E, 0x0B, 0x04, 0x02, 0x0C},
		{0x05, 0x0D, 0x0F, 0x06, 0x09, 0x02, 0x0C, 0x0A, 0x0B, 0x07, 0x08, 0x01, 0x04, 0x03, 0x0E, 0x00},
		{0x08, 0x0E, 0x02, 0x05, 0x06, 0x09, 0x01, 0x0C, 0x0F, 0x04, 0x0B, 0x00, 0x0D, 0x0A, 0x03, 0x07},
		{0x01, 0x07, 0x0E, 0x0D, 0x00, 0x05, 0x08, 0x03, 0x04, 0x0F, 0x0A, 0x06, 0x09, 0x0C, 0x0B, 0x02}
	};
	/**
	 * @brief Метод подстановки полубайтов слова
	 *
	 * @details Преобразование t по разделу 4.2 ГОСТ Р 34.12-2015
	 *
	 * @param value преобразуемое слово
	 *
	 * @return      слово с подставленными полубайтами
	 *
	 */
	static uint32_t substitute(const uint32_t value) noexcept {
		// Собираемое слово итога подстановки
		uint32_t result = 0;
		/**
		 * Выполняем перебор полубайтов преобразуемого слова
		 */
		for(size_t i = 0; i < 8; i++)
			// Выполняем подстановку очередного полубайта слова
			result |= (static_cast <uint32_t> (PI[i][(value >> (i * 4)) & 0x0F]) << (i * 4));
		// Выводим слово с подставленными полубайтами
		return result;
	}
	/**
	 * @brief Метод раундового преобразования
	 *
	 * @details Функция g по разделу 4.2 ГОСТ Р 34.12-2015: сложение с раундовым
	 *          ключом по модулю два в степени 32, подстановка полубайтов и
	 *          круговой сдвиг на одиннадцать разрядов влево
	 *
	 * @param value преобразуемое слово
	 * @param key   раундовый ключ
	 *
	 * @return      итог раундового преобразования
	 *
	 */
	static uint32_t round(const uint32_t value, const uint32_t key) noexcept {
		// Выполняем подстановку полубайтов суммы слова и раундового ключа
		const uint32_t item = substitute(value + key);
		// Выводим итог кругового сдвига подставленного слова
		return ((item << 11) | (item >> 21));
	}
	/**
	 * @brief Метод разбора слова из потока байтов
	 *
	 * @param data разбираемый поток байтов
	 *
	 * @return     разобранное слово
	 *
	 */
	static uint32_t load(const uint8_t * data) noexcept {
		// Выводим слово, собранное от старшего байта к младшему
		return ((static_cast <uint32_t> (data[0]) << 24) | (static_cast <uint32_t> (data[1]) << 16) |
		        (static_cast <uint32_t> (data[2]) << 8) | static_cast <uint32_t> (data[3]));
	}
	/**
	 * @brief Метод записи слова в поток байтов
	 *
	 * @param value записываемое слово
	 * @param data  место, в которое записывается слово
	 *
	 */
	static void store(const uint32_t value, uint8_t * data) noexcept {
		// Записываем старший байт слова
		data[0] = static_cast <uint8_t> ((value >> 24) & 0xFF);
		// Записываем второй байт слова
		data[1] = static_cast <uint8_t> ((value >> 16) & 0xFF);
		// Записываем третий байт слова
		data[2] = static_cast <uint8_t> ((value >> 8) & 0xFF);
		// Записываем младший байт слова
		data[3] = static_cast <uint8_t> (value & 0xFF);
	}
	/**
	 * @brief Метод затирания области памяти
	 *
	 * @details Затирание ведётся через изменчивый указатель: обычное присваивание
	 *          собиратель вправе выбросить, увидев, что записанное значение больше
	 *          никем не читается, - и ключ остался бы в памяти
	 *
	 * @param data затираемая область памяти
	 * @param size размер затираемой области памяти
	 *
	 */
	static void wipe(void * data, const size_t size) noexcept {
		// Получаем изменчивый указатель на затираемую область памяти
		volatile uint8_t * item = static_cast <volatile uint8_t *> (data);
		/**
		 * Выполняем перебор байтов затираемой области памяти
		 */
		for(size_t i = 0; i < size; i++)
			// Обнуляем очередной байт области памяти
			item[i] = 0;
	}
	/**
	 * @brief Метод преобразования блока набором раундовых ключей
	 *
	 * @details Сеть Фейстеля по разделу 5 ГОСТ Р 34.12-2015. Зашифрование и
	 *          расшифрование различаются лишь порядком раундовых ключей, оттого
	 *          телом отличаться им незачем
	 *
	 * @param keys    набор раундовых ключей в порядке применения
	 * @param source  преобразуемый блок
	 * @param result  место, в которое помещается преобразованный блок
	 *
	 */
	static void process(const uint32_t * keys, const uint8_t * source, uint8_t * result) noexcept {
		// Разбираем старшую половину преобразуемого блока
		uint32_t high = load(source);
		// Разбираем младшую половину преобразуемого блока
		uint32_t low = load(source + 4);
		/**
		 * Выполняем тридцать один раунд преобразования
		 */
		for(size_t i = 0; i < 31; i++){
			// Вычисляем новое значение младшей половины блока
			const uint32_t item = (round(low, keys[i]) ^ high);
			// Переносим прежнюю младшую половину блока в старшую
			high = low;
			// Запоминаем новое значение младшей половины блока
			low = item;
		}
		// Записываем старшую половину преобразованного блока
		store(round(low, keys[31]) ^ high, result);
		// Записываем младшую половину преобразованного блока
		store(low, result + 4);
	}
};

/**
 * @brief Метод проверки готовности шифра к работе
 *
 * @return признак того, что ключ установлен
 *
 */
bool anyks::cipher::Magma::ready() const noexcept {
	// Выводим признак того, что ключ установлен
	return this->_ready;
}
/**
 * @brief Метод установки ключа шифрования
 *
 * @param key устанавливаемый ключ шифрования
 *
 * @return    признак успешности установки ключа
 *
 */
bool anyks::cipher::Magma::key(const view_t & key) noexcept {
	// Выполняем затирание прежних раундовых ключей
	this->clear();
	// Если ключ шифрования не той длины
	if((key.data == nullptr) || (key.size != MAGMA_KEY))
		// Выводим отказ установки ключа
		return false;
	/**
	 * Выполняем разбор ключа шифрования на восемь слов
	 */
	for(size_t i = 0; i < 8; i++){
		// Разбираем очередное слово ключа шифрования
		const uint32_t item = load(key.data + (i * 4));
		// Записываем слово раундовым ключом первых трёх восьмёрок раундов
		this->_keys[i] = item;
		this->_keys[i + 8] = item;
		this->_keys[i + 16] = item;
		/**
		 * Последняя восьмёрка раундов применяет ключи в обратном порядке: этим и
		 * достигается обратимость сети Фейстеля с нечётным числом раундов
		 */
		this->_keys[31 - i] = item;
	}
	// Устанавливаем признак того, что ключ установлен
	this->_ready = true;
	// Выводим успешность установки ключа
	return true;
}
/**
 * @brief Метод затирания раундовых ключей
 *
 */
void anyks::cipher::Magma::clear() noexcept {
	// Выполняем затирание раундовых ключей
	wipe(this->_keys, sizeof(this->_keys));
	// Снимаем признак того, что ключ установлен
	this->_ready = false;
}
/**
 * @brief Метод зашифрования блока
 *
 * @param source зашифровываемый блок
 * @param result место, в которое помещается зашифрованный блок
 *
 * @return       признак успешности зашифрования
 *
 */
bool anyks::cipher::Magma::encrypt(const uint8_t * source, uint8_t * result) const noexcept {
	// Если ключ не установлен либо места не переданы
	if(!this->_ready || (source == nullptr) || (result == nullptr))
		// Выводим отказ зашифрования
		return false;
	// Выполняем преобразование блока раундовыми ключами в прямом порядке
	process(this->_keys, source, result);
	// Выводим успешность зашифрования
	return true;
}
/**
 * @brief Метод расшифрования блока
 *
 * @param source расшифровываемый блок
 * @param result место, в которое помещается расшифрованный блок
 *
 * @return       признак успешности расшифрования
 *
 */
bool anyks::cipher::Magma::decrypt(const uint8_t * source, uint8_t * result) const noexcept {
	// Если ключ не установлен либо места не переданы
	if(!this->_ready || (source == nullptr) || (result == nullptr))
		// Выводим отказ расшифрования
		return false;
	// Набор раундовых ключей в порядке расшифрования
	uint32_t keys[32];
	/**
	 * Выполняем разворот набора раундовых ключей
	 */
	for(size_t i = 0; i < 32; i++)
		// Переносим очередной раундовый ключ
		keys[i] = this->_keys[31 - i];
	// Выполняем преобразование блока раундовыми ключами в обратном порядке
	process(keys, source, result);
	// Выполняем затирание набора раундовых ключей
	wipe(keys, sizeof(keys));
	// Выводим успешность расшифрования
	return true;
}
/**
 * @brief Конструктор
 *
 */
anyks::cipher::Magma::Magma() noexcept : _ready(false) {
	// Выполняем затирание раундовых ключей
	wipe(this->_keys, sizeof(this->_keys));
}
/**
 * @brief Деструктор
 *
 */
anyks::cipher::Magma::~Magma() noexcept {
	// Выполняем затирание раундовых ключей
	this->clear();
}
