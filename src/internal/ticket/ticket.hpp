/**
 * @brief Основное пространство имён
 *
 */
namespace nts {
	/**
	 * Подписываемся на стандартное пространство имён
	 */
	using namespace std;

	/**
	 * @brief Пространство имён внутренних модулей библиотеки
	 *
	 */
	namespace internal {
		/**
		 * @brief Пространство имён билетов сеансов издания TLS 1.2
		 *
		 * @details Раздел 4 RFC 5077: сервер не держит запаса сеансов, а кладёт состояние
		 *          связи в билет под своим ключом - имя ключа, вектор замены, длина,
		 *          состояние под AES-128-CBC и имитовставка HMAC-SHA256 над всем перед нею.
		 *          Ключей живёт два поколения: нынешнее выдаёт билеты, предыдущее лишь
		 *          признаёт выданные им
		 *
		 */
		namespace ticket {
			/**
			 * Устройство ключа билетов по разделу 4 RFC 5077: имя ключа в шестнадцать
			 * байтов, ключ AES-128 в шестнадцать и ключ HMAC-SHA256 в тридцать два -
			 * подряд в одном месте
			 */
			static constexpr size_t TICKET_NAME = 16;
			// Длина ключа AES-128 билетов
			static constexpr size_t TICKET_KEY = 16;
			// Длина ключа HMAC-SHA256 билетов
			static constexpr size_t TICKET_MAC = 32;
			// Длина места ключа билетов целиком
			static constexpr size_t TICKET_VAULT = (TICKET_NAME + TICKET_KEY + TICKET_MAC);
			/**
			 * Длина главного секрета издания TLS 1.2: раздел 8.1 RFC 5246
			 */
			static constexpr size_t TICKET_MASTER = 48;
			/**
			 * Наибольшая длина билета: раздел 3.3 RFC 5077 велит слать его с двухбайтовой длиной
			 */
			static constexpr size_t TICKET_LONGEST = 0xFFFF;
			/**
			 * @brief Отказы модуля билетов
			 *
			 */
			enum class error_t : uint8_t {
				NONE   = 0x00, // Отказа нет
				VAULT  = 0x01, // Ключ билетов нынешнего поколения не заведён
				CIPHER = 0x02, // Шифр либо имитовставка билета отказали
				LENGTH = 0x03, // Билет в двухбайтовую длину не входит
				MEMORY = 0x04  // Памяти под билет не хватило
			};
			/**
			 * @brief Состояние возобновляемой связи, запечатываемое в билет
			 *
			 * @details Раздел 4 RFC 5077 и раздел 5.3 RFC 7627: набор, главный секрет и
			 *          признак расширенного главного секрета; раздел 3.1 RFC 7366: порядок
			 *          «шифрование, затем имитовставка» выдавшей связи; подлинность клиента и
			 *          имя запрошенного узла - чтобы возобновлённая связь наследовала
			 *          проверенное, а не обходила его
			 *
			 * @note Главный секрет затирается сбросом и деструктором
			 *
			 */
			typedef struct State {
				// Набор шифрования связи, выдавшей билет
				protect::suite_t suite;
				// Главный секрет связи
				uint8_t master[TICKET_MASTER];
				// Признак порядка «шифрование, затем имитовставка» RFC 7366 у связи, выдавшей билет
				bool etm;
				// Признак издания DTLS 1.0/TLS 1.1 у выдавшей связи: раздел 3.4 RFC 5077 велит возобновлять лишь тем же изданием
				bool ancient;
				// Признак того, что подлинность клиента связью проверена: цепочка непуста, подпись владения сошлась
				bool verified;
				// Миг выдачи билета в секундах
				int64_t moment;
				// Миг первичного удостоверения клиента в секундах: перевыдача билета его не продлевает (раздел 5.6 RFC 5077)
				int64_t authenticated;
				// Срок жизни билета в секундах
				uint32_t lifetime;
				// Прикладной протокол связи, выдавшей билет
				string protocol;
				// Имя узла, запрошенное клиентом у связи, выдавшей билет (раздел 3 RFC 6066)
				string name;
				// Сертификат клиента в записи DER, предъявленный связи с проверенной подлинностью; пуст без неё
				vector <uint8_t> leaf;
				/**
				 * @brief Метод сброса состояния с затиранием главного секрета
				 *
				 */
				void clear() noexcept;
				/**
				 * @brief Конструктор
				 *
				 */
				State() noexcept;
				/**
				 * @brief Деструктор
				 *
				 */
				~State() noexcept;
			} state_t;
			/**
			 * @brief Хранитель ключей билетов сеансов двух поколений
			 *
			 * @details Ключ поколения выводится из секрета потребителя тремя значениями
			 *          HMAC-SHA256 своими метками; новое поколение становится нынешним,
			 *          нынешнее - предыдущим, а более старое забывается
			 *
			 */
			typedef class Keeper {
				private:
					/**
					 * @brief Структура ключей билетов, живущих между вызовами
					 *
					 * @details Лежит целиком в укрытой памяти хранилища (sys::Vault)
					 *
					 */
					typedef struct Keys {
						// Ключи билетов двух поколений: имя ключа, ключ шифрования и ключ имитовставки подряд
						uint8_t vault[2][TICKET_VAULT];
					} keys_t;
				private:
					// Участок укрытой памяти под ключи билетов
					sys::secret_t _shelter;
					// Ключи билетов в укрытой памяти; nullptr, если хранилище участка не дало
					keys_t * _keys;
					// Признаки заведённости поколений ключей билетов
					bool _vaulted[2];
				public:
					/**
					 * @brief Метод проверки того, что ключ нынешнего поколения заведён
					 *
					 * @return признак заведённости ключа нынешнего поколения
					 *
					 */
					bool ready() const noexcept;
					/**
					 * @brief Метод заведения ключа билетов нового поколения из секрета
					 *
					 * @param secret секрет любой длины
					 * @return       признак успешности заведения ключа
					 *
					 * @details Памяти заведение не занимает и годится заведению связи под noexcept;
					 *          отказ оставляет поколения прежними
					 *
					 */
					bool stash(const view_t & secret) noexcept;
					/**
					 * @brief Метод запечатывания состояния связи в октеты билета ключом нынешнего поколения
					 *
					 * @param state  запечатываемое состояние связи
					 * @param result накопитель, в который помещаются октеты билета
					 * @return       отказ запечатывания
					 *
					 * @details Раздел 4 RFC 5077: имя ключа, случайный вектор замены, длина, состояние
					 *          под AES-128-CBC с дополнением по образцу раздела 6.2.3.2 RFC 5246 и
					 *          имитовставка HMAC-SHA256 над всем перед нею
					 *
					 */
					error_t mint(const state_t & state, vector <uint8_t> & result) noexcept;
					/**
					 * @brief Метод распечатывания предъявленного билета ключом ведомого поколения
					 *
					 * @param ticket октеты предъявленного билета
					 * @param result состояние, в которое помещается распечатанное
					 * @return       признак того, что билет запечатан ведомым ключом и цел
					 *
					 * @details Имитовставка сличается за постоянное время прежде расшифрования;
					 *          негодный, чужой либо порченый билет ведёт к полному рукопожатию, а не
					 *          к отказу, оттого итог - признак, а не отказ. Срок билета модуль не
					 *          судит: мигом владеет связь
					 *
					 */
					bool redeem(const view_t & ticket, state_t & result) noexcept;
					/**
					 * @brief Метод затирания ключей обоих поколений
					 *
					 */
					void clear() noexcept;
				public:
					/**
					 * @brief Конструктор
					 *
					 */
					Keeper() noexcept;
					/**
					 * @brief Деструктор
					 *
					 */
					~Keeper() noexcept;
			} keeper_t;
		};
	};
};

#endif
