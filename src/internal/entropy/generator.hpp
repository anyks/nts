#include <sys/global.hpp>

/**
 * @brief Основное пространство имён
 *
 */
namespace nts {
	/**
	 * Подписываемся на стандартное пространство имён
	 */
	using namespace std;

	/**
	 * @brief Пространство имён внутренних модулей библиотеки
	 *
	 */
	namespace internal {
		/**
		 * @brief Порождатель случайных байтов одного потока
		 *
		 * @details Устройство «ключ стирается на ходу» (fast key erasure) по образцу
		 *          arc4random OpenBSD: на ключе и заполнении ChaCha20 вырабатывается разом
		 *          запас гаммы в BUFFER байтов, первые KEY + NONCE байтов запаса становятся
		 *          новыми ключом и заполнением и в запасе затираются, остальные выдаются
		 *          потребителю и затираются по мере выдачи. Прежнего ключа после наполнения
		 *          нет нигде, оттого по состоянию порождателя нельзя восстановить ни одного
		 *          уже выданного байта. Каждые RESEED наполнений ключ складывается со
		 *          свежими байтами системы: наполнение от системы не подменяет ключ, а
		 *          примешивается к нему, и худшие байты системы состояния не ухудшат
		 *
		 * @note Состояние заводится по потоку (thread_local): замка нет, потоки друг друга
		 *       не ждут. Поколение процесса растёт у потомка при разветвлении, и порождатель
		 *       с чужим поколением переналивается прежде выдачи, отбросив запас: у потомка
		 *       он тот же, что у родителя
		 *
		 */
		typedef struct Generator {
			public:
				// Длина ключа ChaCha20 в байтах
				static constexpr size_t KEY = 32;
				// Длина заполнения ChaCha20 в байтах
				static constexpr size_t NONCE = 12;
				// Длина запаса гаммы в байтах: шестнадцать блоков, четыре пачки векторных команд
				static constexpr size_t BUFFER = 1024;
				// Число байтов запаса, уходящих в новые ключ и заполнение
				static constexpr size_t TAKEN = (KEY + NONCE);
				// Число байтов запаса, выдаваемых потребителю за одно наполнение
				static constexpr size_t REST = (BUFFER - TAKEN);
				// Число наполнений между переналивками от системы: около 61 КиБ выдачи
				static constexpr size_t RESEED = 64;
			public:
				// Ключ ChaCha20 текущего наполнения
				uint8_t key[KEY];
				// Заполнение ChaCha20 текущего наполнения
				uint8_t nonce[NONCE];
				// Запас гаммы: выданные байты затёрты, неизрасходованные лежат в хвосте
				uint8_t buffer[BUFFER];
			public:
				// Число неизрасходованных байтов запаса
				size_t rest;
				// Число наполнений с последней переналивки от системы, включая её собственное
				size_t refills;
				// Число переналивок от системы за время жизни потока
				size_t stirs;
			public:
				// Поколение процесса, при котором состоялась последняя переналивка
				uint64_t generation;
				// Признак того, что порождатель наполнен от системы
				bool seeded;
			public:
				/**
				 * @brief Конструктор: пустое, ненаполненное состояние
				 *
				 */
				Generator() noexcept;
				/**
				 * @brief Деструктор: затирание состояния при завершении потока
				 *
				 */
				~Generator() noexcept;
		} generator_t;
		/**
		 * @brief Функция получения порождателя текущего потока
		 *
		 * @return порождатель случайных байтов текущего потока
		 *
		 */
		generator_t & generator() noexcept;
	};
};

