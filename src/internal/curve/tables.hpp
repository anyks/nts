#include <cstddef>
#include <cstdint>

/**
 * nts пространство имён
 */
namespace nts {
	/**
	 * curve пространство имён
	 */
	namespace curve {
		/**
		 * @brief Размер знакового окна перебора множителя в разрядах
		 *
		 * @details Окна знаковые (кодирование Бута): цифра окна лежит от -2^(w-1) до
		 *          2^(w-1), а отрицательная цифра берёт кратное со сменой знака второй
		 *          координаты. Шесть разрядов дают 43 окна на 256 разрядов при строке в 32
		 *          кратных - против 52 окон и 31 кратного у беззнаковых окон по пять: на
		 *          девять смешанных сложений меньше при той же заготовке. Семь разрядов
		 *          дали бы 37 окон, но строка в 64 кратных удваивает заготовку и перебор.
		 *          Так же устроена таблица основания OpenSSL (ecp_nistz256, w = 7)
		 *
		 * @note Число окон берётся с запасом в один разряд: разряд выше последнего окна
		 *       обязан быть нулевым, иначе старшее окно несло бы знак
		 *
		 */
		static constexpr size_t TABLES_WINDOW = 6;

		/**
		 * @brief Число кратных точки основания, хранимых на одно окно
		 *
		 * @note Кратное нулевое не хранится: оно есть бесконечно удалённая точка, и
		 *       выдаётся она обнулением третьей координаты, а не чтением из таблицы.
		 *       Величина цифры знакового окна не превосходит 2^(w-1)
		 *
		 */
		static constexpr size_t TABLES_MULTIPLES = (1 << (TABLES_WINDOW - 1));

		/**
		 * @brief Функция счёта числа окон множителя данной разрядности
		 *
		 * @param bits разрядность множителя
		 * @return     число окон с запасом в один разряд
		 *
		 */
		static constexpr size_t windows(const size_t bits) noexcept {
			// Выводим число окон: разряд выше последнего окна обязан быть нулевым
			return ((bits / TABLES_WINDOW) + 1);
		}

		/**
		 * @brief Описание заготовленных кратных точки основания одной кривой
		 *
		 */
		typedef struct Precomputed {
			// Число слов в одной координате точки
			size_t words;
			// Число окон, на которые разбит множитель
			size_t positions;
			/**
			 * Кратные точки основания в области Монтгомери, идущие подряд:
			 * окно за окном, внутри окна кратное за кратным, у кратного первая
			 * координата за второй
			 */
			const uint64_t * data;
		} precomputed_t;

		/**
		 * @brief Функция поиска заготовленных кратных по точке основания кривой
		 *
		 * @param x     первая координата точки основания в области Монтгомери
		 * @param y     вторая координата точки основания в области Монтгомери
		 * @param words число слов в одной координате точки
		 * @return      описание заготовленных кратных либо nullptr у кривой, кратные
		 *              которой не заготовлены
		 *
		 * @note Розыск идёт сличением с ПЕРВЫМ кратным первого окна: оно и есть сама
		 *       точка основания, и опознаёт кривую она однозначно
		 *
		 */
		const precomputed_t * precomputed(const uint64_t * x, const uint64_t * y, const size_t words) noexcept;
	};
};

