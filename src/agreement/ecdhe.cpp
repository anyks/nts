#include <agreement/ecdhe.hpp>
#include <entropy/entropy.hpp>
#include <sys/wipe.hpp>

/**
 * Используем стандартное пространство имён
 */
using namespace std;

/**
 * @brief Внутренние служебные объекты
 *
 */
namespace {
	/**
	 * Пространство имён библиотеки
	 */
	using namespace nts;

	// Затирание областей памяти берётся из открытого API библиотеки
	using nts::sys::wipe;
	/**
	 * @brief Функция разворота записи числа
	 *
	 * @param source разворачиваемая запись числа
	 * @param result место, в которое помещается развёрнутая запись числа
	 * @param size   длина записи числа в байтах
	 *
	 */
	static void reverse(const uint8_t * source, uint8_t * result, const size_t size) noexcept {
		/**
		 * Выполняем перебор байтов записи числа
		 */
		for(size_t i = 0; i < size; i++)
			// Переносим очередной байт записи числа
			result[i] = source[size - i - 1];
	}
};

/**
 * @brief Функция выработки мимолётной пары ключей
 *
 * @param curve  эллиптическая кривая обмена мимолётными ключами
 * @param secret место, в которое помещается секретный ключ длиной в размер кривой
 * @param key    место, в которое помещается открытый ключ длиной в два размера кривой
 * @return       признак успешности выработки мимолётной пары ключей
 *
 */
bool nts::agreement::generate(const curve::curve_t & curve, uint8_t * secret, uint8_t * key) noexcept {
	// Если кривая не установлена либо места ключей не переданы
	if(!curve.ready() || (secret == nullptr) || (key == nullptr))
		// Выводим отказ выработки мимолётной пары ключей
		return false;
	// Получаем размер записи координаты кривой
	const size_t size = curve.size();
	// Получаем арифметику порядка подгруппы точек кривой
	const math::modulus_t & order = curve.order();
	// Секретный ключ мимолётной пары
	math::number_t value;
	/**
	 * Выполняем отбор секретного ключа из области от единицы до порядка подгруппы
	 */
	do {
		// Если случайное значение выработать не удалось
		if(!entropy::number(order, value)){
			// Выполняем затирание выработанного значения
			wipe(value.words, sizeof(value.words));
			// Выводим отказ выработки мимолётной пары ключей
			return false;
		}
	// Продолжаем отбор, пока значение обращается в ноль
	} while(order.zero(value));
	// Места, в которые записываются число и координаты открытого ключа
	uint8_t buffer[math::NUMBER_SIZE], first[math::NUMBER_SIZE], second[math::NUMBER_SIZE];
	// Признак успешности выработки мимолётной пары ключей
	bool ok = order.store(value, buffer, size);
	// Если секретный ключ записать удалось
	if(ok){
		// Выполняем разворот записи секретного ключа
		reverse(buffer, secret, size);
		// Открытый ключ мимолётной пары
		curve::point_t point;
		// Выполняем умножение образующей точки на секретный ключ
		curve.product(value, point);
		// Если координаты открытого ключа записать удалось
		if((ok = curve.coordinates(point, first, second, size))){
			// Выполняем разворот записи первой координаты открытого ключа
			reverse(first, key, size);
			// Выполняем разворот записи второй координаты открытого ключа
			reverse(second, key + size, size);
		}
	}
	// Выполняем затирание записанных координат открытого ключа
	wipe(second, sizeof(second));
	// Выполняем затирание записанных координат открытого ключа
	wipe(first, sizeof(first));
	// Выполняем затирание записи секретного ключа
	wipe(buffer, sizeof(buffer));
	// Выполняем затирание секретного ключа мимолётной пары
	wipe(value.words, sizeof(value.words));
	// Если выработать мимолётную пару ключей не удалось
	if(!ok){
		// Выполняем затирание места открытого ключа
		wipe(key, size * 2);
		// Выполняем затирание места секретного ключа
		wipe(secret, size);
	}
	// Выводим признак успешности выработки мимолётной пары ключей
	return ok;
}
/**
 * @brief Функция выработки общего значения обмена мимолётными ключами
 *
 * @param curve  эллиптическая кривая обмена мимолётными ключами
 * @param secret секретный ключ своей стороны, записанный младшим байтом вперёд
 * @param key    открытый ключ встречной стороны, записанный младшим байтом вперёд
 * @param result место, в которое помещается общее значение длиной в размер кривой
 * @return       признак успешности выработки общего значения
 *
 */
bool nts::agreement::ecdhe(const curve::curve_t & curve, const view_t & secret, const view_t & key, uint8_t * result) noexcept {
	// Если кривая не установлена либо место общего значения не передано
	if(!curve.ready() || (result == nullptr))
		// Выводим отказ выработки общего значения
		return false;
	// Получаем размер записи координаты кривой
	const size_t size = curve.size();
	// Если секретный ключ своей стороны передан длиной не в размер кривой
	if((secret.data == nullptr) || (secret.size != size))
		// Выводим отказ выработки общего значения
		return false;
	// Если открытый ключ встречной стороны передан длиной не в две координаты
	if((key.data == nullptr) || (key.size != (size * 2)))
		// Выводим отказ выработки общего значения
		return false;
	// Места, в которые записываются число и координаты открытого ключа
	uint8_t buffer[math::NUMBER_SIZE], first[math::NUMBER_SIZE], second[math::NUMBER_SIZE];
	// Выполняем разворот записи секретного ключа своей стороны
	reverse(secret.data, buffer, size);
	// Выполняем разворот записи первой координаты открытого ключа
	reverse(key.data, first, size);
	// Выполняем разворот записи второй координаты открытого ключа
	reverse(key.data + size, second, size);
	// Получаем арифметику порядка подгруппы точек кривой
	const math::modulus_t & order = curve.order();
	// Секретный ключ своей стороны
	math::number_t value;
	// Признак успешности выработки общего значения
	bool ok = (order.load(view_t(buffer, size), value) && !order.zero(value));
	// Открытый ключ встречной стороны
	curve::point_t point;
	/**
	 * Разбор точки проверяет её принадлежность кривой: без этой проверки подставная
	 * точка вне кривой выдаёт секретный ключ своей стороны. Принадлежность подгруппе
	 * порядка q не просится (решение 5): кручение снимается ниже умножением точки на
	 * кофактор, как велит раздел 6.1.1 RFC 9367, а проверка по q стоила бы ещё одного
	 * полного умножения точки на каждый чужой ключ
	 */
	if(ok)
		// Выполняем разбор открытого ключа встречной стороны без проверки подгруппы
		ok = curve.point(view_t(first, size), view_t(second, size), point, false);
	// Значения, участвующие в выработке множителя кратной точки
	math::number_t entered, item;
	// Если открытый ключ встречной стороны разобрать удалось
	if(ok){
		// Выполняем приведение секретного ключа в область Монтгомери
		order.enter(value, entered);
		// Кофактор кривой, на который множится секретный ключ
		// Выполняем приведение секретного ключа из области Монтгомери
		order.leave(entered, value);
		// Проверяем множитель на ноль: нулевой отвергается
		ok = !order.zero(value);
	}
	// Если множитель кратной точки выработать удалось
	if(ok){
		// Кратная точка обмена мимолётными ключами
		curve::point_t common;
		/**
		 * Раздел 6.1.1 черновика наборов ГОСТ множит секретный ключ на кофактор, а
		 * умножение по модулю порядка подгруппы кручения не снимает: кофактором
		 * множится сама точка, и у годной точки итог тот же
		 */
		math::number_t cofactor;
		// Кратная точка по кофактору кривой
		curve::point_t cleared;
		/**
		 * Очистка от кофактора: у кривых простого порядка (P-256, CryptoPro-A) кофактор
		 * равен единице, и умножение на него - это полное умножение за постоянное время,
		 * вдвое удорожавшее обмен ключами впустую (74 мкс из 157). Кофактор не тайна:
		 * при единице точка берётся как есть, при степени двойки - удвоениями, иное -
		 * общим умножением
		 */
		const uint64_t h = curve.cofactor();
		// Если кофактор единичный либо кривая простого порядка
		if(h <= 1)
			// При единице точка берётся как есть
			cleared = point;
		else if((h & (h - 1)) == 0){
			// Начинаем с самой точки
			cleared = point;
			/**
			 * Выполняем удвоения до снятия кофактора-степени двойки
			 */
			for(uint64_t step = h; step > 1; step >>= 1)
				// Удваиваем точку
				curve.twice(cleared, cleared);
		} else {
			// Записываем кофактор кривой числом
			order.word(h, cofactor);
			// Выполняем умножение открытого ключа встречной стороны на кофактор кривой
			curve.multiply(point, cofactor, cleared);
		}
		// Выполняем умножение очищенной точки на секретный ключ
		curve.multiply(cleared, value, common);
		// Выполняем затирание очищенной точки
		wipe(&cleared, sizeof(cleared));
		/**
		 * Кратная точка, обратившаяся в ноль, стандартом отвергается: это вторая известная
		 * подмена, выдающая секретный ключ своей стороны
		 */
		if((ok = !curve.infinity(common))){
			// Если координаты кратной точки записать удалось
			if((ok = curve.coordinates(common, first, second, size)))
				// Выполняем разворот записи первой координаты кратной точки
				reverse(first, result, size);
		}
		// Выполняем затирание кратной точки обмена мимолётными ключами
		wipe(&common, sizeof(common));
	}
	// Выполняем затирание промежуточных значений выработки множителя
	wipe(item.words, sizeof(item.words));
	// Выполняем затирание промежуточных значений выработки множителя
	wipe(entered.words, sizeof(entered.words));
	// Выполняем затирание секретного ключа своей стороны
	wipe(value.words, sizeof(value.words));
	// Выполняем затирание записанных координат открытого ключа
	wipe(second, sizeof(second));
	// Выполняем затирание записанных координат открытого ключа
	wipe(first, sizeof(first));
	// Выполняем затирание записи секретного ключа своей стороны
	wipe(buffer, sizeof(buffer));
	// Если общее значение выработать не удалось
	if(!ok)
		// Выполняем затирание места общего значения
		wipe(result, size);
	// Выводим признак успешности выработки общего значения
	return ok;
}
