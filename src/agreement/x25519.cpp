using namespace std;

/**
 * @brief Внутренние служебные объекты
 *
 */
namespace {
	/**
	 * Пространство имён библиотеки
	 */
	using namespace nts;

	/**
	 * Пространство имён арифметики поля
	 */
	using namespace nts::math::field25519;

	/**
	 * @brief Множитель удвоения лестницы Монтгомери
	 *
	 * @details Раздел 5 RFC 7748: a24 = (486662 - 2) / 4 = 121665
	 *
	 */
	static constexpr uint64_t A24 = 121665;

	// Затирание областей памяти берётся из открытого API библиотеки
	using nts::sys::wipe;
	/**
	 * @brief Метод умножения точки на скаляр лестницей Монтгомери
	 *
	 * @details Раздел 5 RFC 7748: скаляр обязан быть уже зажатым, точка передаётся
	 *          первой координатой, итог выходит первой координатой кратной точки
	 *
	 * @param scalar зажатый скаляр, записанный младшим байтом вперёд
	 * @param point  первая координата множимой точки
	 * @param result место, в которое помещается первая координата кратной точки
	 *
	 */
	static void ladder(const uint8_t * scalar, const element_t & point, element_t & result) noexcept {
		// Координаты двух точек лестницы
		element_t x2, z2, x3, z3;
		/**
		 * Промежуточные значения шага лестницы: живут вне цикла и затираются один раз
		 * после него, ибо всякий шаг перезаписывает их целиком, и затирание на каждом
		 * шаге стоило десятую часть времени, не добавляя ничего к затиранию в конце
		 */
		element_t a, aa, b, bb, e, c, d, da, cb;
		// Первая точка лестницы начинается с нейтральной точки
		one(x2);
		// Вторая координата нейтральной точки
		zero(z2);
		// Вторая точка лестницы начинается с множимой точки
		x3 = point;
		// Вторая координата множимой точки
		one(z3);
		// Накопленный признак обмена точек лестницы
		uint64_t swapped = 0;
		/**
		 * Выполняем обход разрядов скаляра от 254-го к нулевому
		 */
		for(size_t i = 255; i > 0; i--){
			// Номер очередного разряда скаляра
			const size_t index = (i - 1);
			// Значение очередного разряда скаляра
			const uint64_t bit = ((scalar[index / 8] >> (index % 8)) & 1);
			// Складываем признак обмена с очередным разрядом
			swapped ^= bit;
			// Выполняем условный обмен первых координат точек
			swap(x2, x3, swapped);
			// Выполняем условный обмен вторых координат точек
			swap(z2, z3, swapped);
			// Запоминаем очередной разряд признаком обмена
			swapped = bit;
			// Вырабатываем сумму координат первой точки
			add(x2, z2, a);
			// Вырабатываем квадрат суммы координат первой точки
			square(a, aa);
			// Вырабатываем разность координат первой точки
			sub(x2, z2, b);
			// Вырабатываем квадрат разности координат первой точки
			square(b, bb);
			// Вырабатываем разность квадратов
			sub(aa, bb, e);
			// Вырабатываем сумму координат второй точки
			add(x3, z3, c);
			// Вырабатываем разность координат второй точки
			sub(x3, z3, d);
			// Вырабатываем произведение разности второй точки на сумму первой
			mul(d, a, da);
			// Вырабатываем произведение суммы второй точки на разность первой
			mul(c, b, cb);
			// Вырабатываем сумму произведений
			add(da, cb, x3);
			// Первая координата суммы точек - квадрат суммы произведений
			square(x3, x3);
			// Вырабатываем разность произведений
			sub(da, cb, z3);
			// Вырабатываем квадрат разности произведений
			square(z3, z3);
			// Вторая координата суммы точек - квадрат разности на исходную координату
			mul(point, z3, z3);
			// Первая координата удвоенной точки - произведение квадратов
			mul(aa, bb, x2);
			// Вырабатываем произведение множителя удвоения на разность квадратов
			mul(e, A24, z2);
			// Складываем произведение с квадратом суммы
			add(aa, z2, z2);
			// Вторая координата удвоенной точки - разность квадратов на полученную сумму
			mul(e, z2, z2);
		}
		// Выполняем заключительный условный обмен первых координат точек
		swap(x2, x3, swapped);
		// Выполняем заключительный условный обмен вторых координат точек
		swap(z2, z3, swapped);
		// Выполняем обращение второй координаты кратной точки
		invert(z2, z2);
		// Выполняем выработку первой координаты кратной точки
		mul(x2, z2, result);
		// Выполняем затирание промежуточных значений шага лестницы
		wipe(&cb, sizeof(cb));
		// Выполняем затирание промежуточных значений шага лестницы
		wipe(&da, sizeof(da));
		// Выполняем затирание промежуточных значений шага лестницы
		wipe(&d, sizeof(d));
		// Выполняем затирание промежуточных значений шага лестницы
		wipe(&c, sizeof(c));
		// Выполняем затирание промежуточных значений шага лестницы
		wipe(&e, sizeof(e));
		// Выполняем затирание промежуточных значений шага лестницы
		wipe(&bb, sizeof(bb));
		// Выполняем затирание промежуточных значений шага лестницы
		wipe(&b, sizeof(b));
		// Выполняем затирание промежуточных значений шага лестницы
		wipe(&aa, sizeof(aa));
		// Выполняем затирание промежуточных значений шага лестницы
		wipe(&a, sizeof(a));
		// Выполняем затирание координат точек лестницы
		wipe(&z3, sizeof(z3));
		// Выполняем затирание координат точек лестницы
		wipe(&x3, sizeof(x3));
		// Выполняем затирание координат точек лестницы
		wipe(&z2, sizeof(z2));
		// Выполняем затирание координат точек лестницы
		wipe(&x2, sizeof(x2));
	}
	/**
	 * @brief Метод выработки первой координаты кратной точки по записям
	 *
	 * @param secret секретный ключ длиной в тридцать два байта
	 * @param point  первая координата точки длиной в тридцать два байта
	 * @param result место, в которое помещается запись первой координаты кратной точки
	 *
	 * @return       признак того, что кратная точка не обратилась в ноль
	 *
	 */
	static bool multiply(const uint8_t * secret, const uint8_t * point, uint8_t * result) noexcept {
		// Зажатый секретный ключ
		uint8_t scalar[agreement::X25519_SIZE];
		/**
		 * Выполняем перенос секретного ключа в место зажима
		 */
		for(size_t i = 0; i < agreement::X25519_SIZE; i++)
			// Переносим очередной байт секретного ключа
			scalar[i] = secret[i];
		// Сбрасываем три младших разряда: раздел 5 RFC 7748 очищает кофактор
		scalar[0] &= 248;
		// Сбрасываем старший разряд скаляра
		scalar[31] &= 127;
		// Ставим разряд 254: число шагов лестницы от секрета не зависит
		scalar[31] |= 64;
		// Первая координата множимой точки и итог умножения
		element_t item, value;
		// Выполняем разбор первой координаты точки с отбрасыванием старшего разряда
		load(point, item);
		// Выполняем умножение точки на зажатый скаляр
		ladder(scalar, item, value);
		// Выполняем запись первой координаты кратной точки
		store(value, result);
		// Накопленное значение всех байтов итога
		uint8_t accumulated = 0;
		/**
		 * Выполняем перебор байтов итога: раздел 6.1 RFC 7748 велит проверять ноль
		 * накоплением всех байтов по ИЛИ
		 */
		for(size_t i = 0; i < agreement::X25519_SIZE; i++)
			// Накапливаем очередной байт итога
			accumulated |= result[i];
		// Выполняем затирание итога умножения
		wipe(&value, sizeof(value));
		// Выполняем затирание координаты множимой точки
		wipe(&item, sizeof(item));
		// Выполняем затирание зажатого секретного ключа
		wipe(scalar, sizeof(scalar));
		// Выводим признак того, что кратная точка не обратилась в ноль
		return (accumulated != 0);
	}
};

/**
 * @brief Метод выработки общего значения на кривой Curve25519
 *
 * @param secret секретный ключ своей стороны длиной в тридцать два байта
 * @param point  открытый ключ встречной стороны длиной в тридцать два байта
 * @param result место, в которое помещается общее значение длиной в тридцать два байта
 *
 * @return       признак успешности выработки общего значения
 *
 */
bool nts::agreement::x25519(const view_t & secret, const view_t & point, uint8_t * result) noexcept {
	// Если место общего значения не передано
	if(result == nullptr)
		// Выводим отказ выработки общего значения
		return false;
	// Если секретный ключ передан длиной не в тридцать два байта
	if((secret.data == nullptr) || (secret.size != X25519_SIZE))
		// Выводим отказ выработки общего значения
		return false;
	// Если открытый ключ передан длиной не в тридцать два байта
	if((point.data == nullptr) || (point.size != X25519_SIZE))
		// Выводим отказ выработки общего значения
		return false;
	// Выполняем умножение открытого ключа на секретный
	const bool ok = multiply(secret.data, point.data, result);
	// Если общее значение обратилось в ноль
	if(!ok)
		// Выполняем затирание места общего значения
		wipe(result, X25519_SIZE);
	// Выводим признак успешности выработки общего значения
	return ok;
}
/**
 * @brief Метод выработки открытого ключа на кривой Curve25519
 *
 * @param secret секретный ключ длиной в тридцать два байта
 * @param result место, в которое помещается открытый ключ длиной в тридцать два байта
 *
 * @return       признак успешности выработки открытого ключа
 *
 */
bool nts::agreement::x25519(const view_t & secret, uint8_t * result) noexcept {
	// Если место открытого ключа не передано
	if(result == nullptr)
		// Выводим отказ выработки открытого ключа
		return false;
	// Если секретный ключ передан длиной не в тридцать два байта
	if((secret.data == nullptr) || (secret.size != X25519_SIZE))
		// Выводим отказ выработки открытого ключа
		return false;
	// Точка основания кривой: первая координата девять
	uint8_t base[X25519_SIZE] = {9};
	// Выполняем умножение точки основания на секретный ключ
	const bool ok = multiply(secret.data, base, result);
	// Если открытый ключ обратился в ноль
	if(!ok)
		// Выполняем затирание места открытого ключа
		wipe(result, X25519_SIZE);
	// Выводим признак успешности выработки открытого ключа
	return ok;
}
/**
 * @brief Метод порождения пары ключей на кривой Curve25519
 *
 * @param secret место, в которое помещается секретный ключ длиной в тридцать два байта
 * @param key    место, в которое помещается открытый ключ длиной в тридцать два байта
 *
 * @return       признак успешности порождения пары ключей
 *
 */
bool nts::agreement::generate(uint8_t * secret, uint8_t * key) noexcept {
	// Если места ключей не переданы
	if((secret == nullptr) || (key == nullptr))
		// Выводим отказ порождения пары ключей
		return false;
	// Если случайные байты секретного ключа получить не удалось
	if(!entropy::bytes(secret, X25519_SIZE)){
		// Выполняем затирание места секретного ключа
		wipe(secret, X25519_SIZE);
		// Выполняем затирание места открытого ключа
		wipe(key, X25519_SIZE);
		// Выводим отказ порождения пары ключей
		return false;
	}
	// Сбрасываем три младших разряда: раздел 5 RFC 7748 очищает кофактор
	secret[0] &= 248;
	// Сбрасываем старший разряд секретного ключа
	secret[X25519_SIZE - 1] &= 127;
	// Ставим разряд 254 секретного ключа
	secret[X25519_SIZE - 1] |= 64;
	// Если открытый ключ вывести не удалось
	if(!nts::agreement::x25519(view_t(secret, X25519_SIZE), key)){
		// Выполняем затирание места секретного ключа
		wipe(secret, X25519_SIZE);
		// Выполняем затирание места открытого ключа
		wipe(key, X25519_SIZE);
		// Выводим отказ порождения пары ключей
		return false;
	}
	// Выводим успешность порождения пары ключей
	return true;
}
