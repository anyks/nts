/**
 * Подключаем стандартные заголовочные файлы
 */
#include <cstdio>
#include <cstdlib>
#include <vector>

/**
 * Подключаем заголовочные файлы проекта
 */
#include <curve/curve.hpp>
#include <curve/parameters.hpp>
#include <internal/curve/tables.hpp>

/**
 * Используем пространство имён проекта
 */
using namespace nts;

/**
 * Пространство имён локальных объектов
 */
namespace {
	/**
	 * Опознаватели наборов параметров, кратные которых заготавливаются
	 *
	 * @note Перечислен по одному опознавателю на набор значений: наборы, делящие
	 *       значения между собой, дают одну и ту же точку основания, и заготавливать
	 *       её дважды незачем
	 */
	static const char * IDENTIFIERS[] = {
		"1.2.643.7.1.2.1.2.0",
		"1.2.643.2.2.35.0",
		"1.2.643.7.1.2.1.1.1",
		"1.2.643.2.2.35.1",
		"1.2.643.2.2.35.2",
		"1.2.643.2.2.35.3",
		"1.2.643.7.1.2.1.2.1",
		"1.2.643.7.1.2.1.2.2",
		"1.2.643.7.1.2.1.2.3"
	};
};

/**
 * @brief Метод вывода кратных точки основания одной кривой
 *
 * @param identifier опознаватель набора параметров кривой
 * @param place      место набора в выводимом файле
 *
 * @return           признак успешности вывода кратных
 *
 */
static bool emit(const char * identifier, const size_t place) noexcept {
	// Объект эллиптической кривой
	curve::curve_t elliptic;
	// Если кривую набора параметров завести не удалось
	if(!curve::parameters(identifier, elliptic)){
		// Выводим сообщение о неудаче
		::fprintf(stderr, "кривую %s завести не удалось\n", identifier);
		// Выводим отказ вывода кратных
		return false;
	}
	// Получаем длину координаты точки кривой в байтах
	const size_t size = elliptic.size();
	// Определяем число слов в одной координате точки
	const size_t words = ((size + 7) / 8);
	// Определяем число окон, на которые разбит множитель
	const size_t positions = ((size * 8) / curve::TABLES_WINDOW);
	// Точка, кратные которой заготавливаются на очередном окне
	curve::point_t step;
	// Получаем точку основания кривой
	elliptic.base(step);
	// Выводим заголовок таблицы кратных
	::printf("\t/**\n\t * Заготовленные кратные точки основания набора параметров %s\n\t */\n", identifier);
	// Выводим объявление таблицы кратных
	::printf("\tstatic const uint64_t MULTIPLES%zu[] = {\n", place);
	/**
	 * Выполняем обход окон, на которые разбит множитель
	 */
	for(size_t i = 0; i < positions; i++){
		// Накапливаемое кратное точки очередного окна
		curve::point_t item = step;
		/**
		 * Выполняем обход кратных точки очередного окна
		 */
		for(size_t j = 1; j <= curve::TABLES_MULTIPLES; j++){
			// Места, в которые помещаются координаты кратного
			std::vector <uint8_t> first(size, 0), second(size, 0);
			// Если координаты кратного получить не удалось
			if(!elliptic.coordinates(item, first.data(), second.data(), size)){
				// Выводим сообщение о неудаче
				::fprintf(stderr, "координаты кратного %zu окна %zu кривой %s получить не удалось\n", j, i, identifier);
				// Выводим отказ вывода кратных
				return false;
			}
			// Кратное точки, приведённое к аффинному виду
			curve::point_t affine;
			/**
			 * Разбор координат обратно в точку приводит её к аффинному виду и
			 * возвращает в область Монтгомери: третья координата выходит единицей,
			 * и хранить её незачем
			 */
			if(!elliptic.point(view_t(first.data(), first.size()), view_t(second.data(), second.size()), affine)){
				// Выводим сообщение о неудаче
				::fprintf(stderr, "кратное %zu окна %zu кривой %s кривой не принадлежит\n", j, i, identifier);
				// Выводим отказ вывода кратных
				return false;
			}
			// Выводим отступ строки очередного кратного
			::printf("\t\t");
			/**
			 * Выполняем вывод слов первой координаты кратного
			 */
			for(size_t w = 0; w < words; w++)
				// Выводим очередное слово первой координаты
				::printf("0x%016llXULL, ", static_cast <unsigned long long> (affine.x.words[w]));
			/**
			 * Выполняем вывод слов второй координаты кратного
			 */
			for(size_t w = 0; w < words; w++)
				// Выводим очередное слово второй координаты
				::printf("0x%016llXULL,%s", static_cast <unsigned long long> (affine.y.words[w]), ((w + 1) < words ? " " : ""));
			// Выводим перевод строки очередного кратного
			::printf("\n");
			// Если очередное кратное окна не последнее
			if(j < curve::TABLES_MULTIPLES){
				// Следующее кратное точки очередного окна
				curve::point_t next;
				// Считаем следующее кратное сложением с точкой окна
				elliptic.add(item, step, next);
				// Запоминаем следующее кратное точки окна
				item = next;
			}
		}
		/**
		 * Выполняем сдвиг точки окна на его ширину удвоениями
		 */
		for(size_t k = 0; k < curve::TABLES_WINDOW; k++){
			// Удвоенная точка очередного окна
			curve::point_t twice;
			// Выполняем удвоение точки очередного окна
			elliptic.twice(step, twice);
			// Запоминаем удвоенную точку очередного окна
			step = twice;
		}
	}
	// Выводим завершение таблицы кратных
	::printf("\t};\n\n");
	// Выводим успешность вывода кратных
	return true;
}

/**
 * @brief Точка входа программы вычисления заготовленных кратных
 *
 * @return код возврата, нулевой у успешного вывода
 *
 */
int main() noexcept {
	// Число наборов параметров, кратные которых заготавливаются
	const size_t count = (sizeof(IDENTIFIERS) / sizeof(IDENTIFIERS[0]));
	// Выводим обвязку выводимого исходного файла
	::printf(
		"/**\n"
		" * @file tables.cpp\n"
		" *\n"
		" * @license{LicenseRef-A-NTS-1.0}\n"
		" *\n"
		" * @author Yuriy Lobarev\n"
		" *\n"
		" * @brief Исходный файл заготовленных кратных точки основания\n"
		" *\n"
		" * @note Файл ВЫЧИСЛЕН ПРИ СБОРКЕ программой tools/tables.cpp. Править его\n"
		" *       руками бессмысленно: всякая сборка пишет его заново\n"
		" *\n"
		" * @copyright Copyright © 2026\n"
		" *\n"
		" */\n\n"
		"/**\n"
		" * Подключаем заголовочные файлы проекта\n"
		" */\n"
		"#include <cstring>\n"
		"#include <internal/curve/tables.hpp>\n\n"
		"/**\n"
		" * Пространство имён локальных объектов\n"
		" */\n"
		"namespace {\n"
	);
	/**
	 * Выполняем обход наборов параметров, кратные которых заготавливаются
	 */
	for(size_t i = 0; i < count; i++){
		// Если кратные очередного набора вывести не удалось
		if(!emit(IDENTIFIERS[i], i))
			// Выводим код возврата неудачи
			return EXIT_FAILURE;
	}
	// Выводим заголовок описи заготовленных кратных
	::printf("\t/**\n\t * Опись заготовленных кратных точки основания всех кривых\n\t */\n");
	// Выводим объявление описи заготовленных кратных
	::printf("\tstatic const nts::curve::precomputed_t RECORDS[] = {\n");
	/**
	 * Выполняем обход наборов параметров, кратные которых заготовлены
	 */
	for(size_t i = 0; i < count; i++){
		// Объект эллиптической кривой очередного набора
		curve::curve_t elliptic;
		// Выполняем заведение кривой очередного набора
		if(!curve::parameters(IDENTIFIERS[i], elliptic))
			// Выводим код возврата неудачи
			return EXIT_FAILURE;
		// Получаем длину координаты точки кривой в байтах
		const size_t size = elliptic.size();
		// Выводим запись описи очередного набора
		::printf("\t\t{%zu, %zu, MULTIPLES%zu},\n", ((size + 7) / 8), ((size * 8) / curve::TABLES_WINDOW), i);
	}
	// Выводим завершение описи и тело метода розыска
	::printf(
		"\t};\n"
		"};\n\n"
		"/**\n"
		" * @brief Метод поиска заготовленных кратных по точке основания кривой\n"
		" *\n"
		" * @param x     первая координата точки основания в области Монтгомери\n"
		" * @param y     вторая координата точки основания в области Монтгомери\n"
		" * @param words число слов в одной координате точки\n"
		" *\n"
		" * @return      описание заготовленных кратных либо nullptr у кривой, кратные\n"
		" *              которой не заготовлены\n"
		" *\n"
		" */\n"
		"const nts::curve::precomputed_t * nts::curve::precomputed(const uint64_t * x, const uint64_t * y, const size_t words) noexcept {\n"
		"\t// Если координаты точки основания не переданы\n"
		"\tif((x == nullptr) || (y == nullptr) || (words == 0))\n"
		"\t\t// Выводим отсутствие заготовленных кратных\n"
		"\t\treturn nullptr;\n"
		"\t/**\n"
		"\t * Выполняем обход описи заготовленных кратных\n"
		"\t */\n"
		"\tfor(size_t i = 0; i < (sizeof(RECORDS) / sizeof(RECORDS[0])); i++){\n"
		"\t\t// Если число слов координаты набора с искомым разошлось\n"
		"\t\tif(RECORDS[i].words != words)\n"
		"\t\t\t// Переходим к следующему набору описи\n"
		"\t\t\tcontinue;\n"
		"\t\t/**\n"
		"\t\t * Первое кратное первого окна и есть сама точка основания: сличение с ним\n"
		"\t\t * опознаёт кривую однозначно\n"
		"\t\t */\n"
		"\t\tif((::memcmp(RECORDS[i].data, x, (words * sizeof(uint64_t))) == 0) &&\n"
		"\t\t   (::memcmp((RECORDS[i].data + words), y, (words * sizeof(uint64_t))) == 0))\n"
		"\t\t\t// Выводим найденное описание заготовленных кратных\n"
		"\t\t\treturn &RECORDS[i];\n"
		"\t}\n"
		"\t// Выводим отсутствие заготовленных кратных\n"
		"\treturn nullptr;\n"
		"}\n"
	);
	// Выводим код возврата успешности
	return EXIT_SUCCESS;
}
