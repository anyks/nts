/**
 * Стандартные модули
 */
#include <cstring>
#include <iomanip>
#include <iostream>

/**
 * Подключаем заголовочные файлы проекта
 */
#include <sys/vault.hpp>
#include <entropy/entropy.hpp>

/**
 * Используем стандартное пространство имён
 */
using namespace std;

/**
 * Подписываемся на пространство имён библиотеки
 */
using namespace nts;

/**
 * @brief Служебные объекты образца
 *
 */
namespace {
	/**
	 * @brief Метод печати области байтов шестнадцатеричной записью
	 *
	 * @param title подпись
	 * @param data  область байтов
	 * @param size  длина области
	 *
	 */
	void print(const char * title, const uint8_t * data, const size_t size) noexcept {
		// Печатаем подпись
		cout << title << ": ";
		/**
		 * Выполняем перебор байтов
		 */
		for(size_t i = 0; i < size; i++)
			// Печатаем байт
			cout << hex << setw(2) << setfill('0') << static_cast <uint32_t> (data[i]);
		// Завершаем строку
		cout << dec << endl;
	}
	/**
	 * @brief Метод печати сведений об укрытии
	 *
	 * @param shelter сведения об укрытии
	 *
	 */
	void report(const sys::shelter_t & shelter) noexcept {
		// Печатаем, что состоялось на деле
		cout << "Укрытие: подкачка запрещена - " << (shelter.wired ? "да" : "нет")
		     << ", от снимков памяти укрыто - " << (shelter.hidden ? "да" : "нет")
		     << ", потомку достаётся затёртым - " << (shelter.forked ? "да" : "нет") << endl;
	}
};

/**
 * @brief Точка входа образца
 *
 * @param argc число доводов
 * @param argv доводы
 *
 * @return     код завершения: нуль при успехе
 *
 */
int main(int argc, char * argv[]) noexcept {
	// Доводы образцу не нужны
	(void) argc;
	(void) argv;
	// Хранилище процесса: одно на всех, куски по 64 КБ
	sys::vault_t & vault = sys::Vault::instance();
	/**
	 * Участок с одним владельцем: заводится обнулённым, разрушением возвращается
	 * хранилищу затёртым; копировать нельзя, переносить можно
	 */
	sys::secret_t key;
	// Если участок под ключ завести не удалось
	if(!key.reserve(32)){
		// Печатаем отказ
		cout << "Хранилище участка не дало" << endl;
		// Выходим с отказом
		return EXIT_FAILURE;
	}
	// Заполняем ключ энтропией прямо в укрытой памяти, минуя кучу и стек
	if(!entropy::bytes(key.data(), key.size()))
		// Выходим с отказом
		return EXIT_FAILURE;
	// Печатаем ключ
	::print("Ключ в укрытой памяти", key.data(), key.size());
	// Печатаем, что состоялось на деле: понижение не отказ, но и не молчание
	::report(vault.shelter());
	// Адрес участка: понадобится показать затирание
	const uint8_t * address = key.data();
	// Переносим владение: прежний владелец пуст, участок тот же
	sys::secret_t owner(::move(key));
	// Печатаем итог переноса
	cout << "После переноса: у прежнего владельца " << key.size() << " байтов, у нового " << owner.size() << ", адрес тот же - " << ((owner.data() == address) ? "да" : "нет") << endl;
	// Возвращаем участок хранилищу: он затирается в момент возврата
	owner.release();
	// Берём участок той же длины: хранилище отдаёт только что возвращённый, и он нулевой
	uint8_t * again = static_cast <uint8_t *> (vault.take(32));
	// Если участок выдан
	if(again != nullptr){
		// Печатаем итог затирания
		cout << "Повторная выдача того же участка: " << ((again == address) ? "тот же адрес" : "иной адрес") << ", первый байт " << static_cast <uint32_t> (again[0]) << endl;
		// Возвращаем участок
		vault.give(again, 32);
	}
	/**
	 * Набор байтов над хранилищем: обычный vector, чья память - участок хранилища;
	 * освобождение затирает. Так хранятся ключи билетов и заранее разделённые ключи
	 */
	sys::bytes_t preshared;
	// Текст ключа
	const char * text = "заранее разделённый ключ достаточной длины";
	// Переносим ключ в укрытую память
	preshared.assign(reinterpret_cast <const uint8_t *> (text), reinterpret_cast <const uint8_t *> (text) + ::strlen(text));
	// Печатаем длину набора и число кусков хранилища
	cout << "Набор над хранилищем: " << preshared.size() << " байтов, кусков у хранилища: " << vault.chunks() << endl;
	/**
	 * Требование укрытия: кому понижение непозволительно, тот включает его - тогда кусок
	 * без запрета подкачки не принимается и запрос отвечается отказом, а связь без участка
	 * негодна с рождения
	 */
	vault.demand(true);
	// Печатаем требование
	cout << "Требование укрытия включено: " << (vault.demand() ? "да" : "нет") << endl;
	// Снимаем требование: образцу оно больше не нужно
	vault.demand(false);
	// Выходим с успехом
	return EXIT_SUCCESS;
}
