const nts::math::modulus_t & nts::curve::Curve::order() const noexcept {
	// Выводим арифметику порядка подгруппы точек кривой
	return this->_order;
}
/**
 * @brief Метод установки параметров кривой
 *
 * @param modulus модуль поля кривой
 * @param first   первый коэффициент уравнения кривой
 * @param second  второй коэффициент уравнения кривой
 * @param order   порядок подгруппы точек кривой
 * @param x        первая координата образующей точки
 * @param y        вторая координата образующей точки
 * @param cofactor отношение порядка группы точек кривой к порядку подгруппы
 *
 * @return         признак успешности установки параметров кривой
 *
 */
bool nts::curve::Curve::start(const view_t & modulus, const view_t & first, const view_t & second, const view_t & order, const view_t & x, const view_t & y, const uint64_t cofactor) noexcept {
	// Выполняем сброс прежде установленных параметров кривой
	this->clear();
	// Если кофактор кривой не передан
	if(cofactor == 0)
		// Выводим отказ установки параметров кривой
		return false;
	// Запоминаем кофактор кривой
	this->_cofactor = cofactor;
	// Если модуль поля кривой установить не удалось
	if(!this->_field.start(modulus))
		// Выводим отказ установки параметров кривой
		return false;
	// Если порядок подгруппы точек кривой установить не удалось
	if(!this->_order.start(order)){
		// Выполняем сброс установленных параметров кривой
		this->clear();
		// Выводим отказ установки параметров кривой
		return false;
	}
	// Разбираемые коэффициенты уравнения кривой
	math::number_t item;
	// Если первый коэффициент уравнения кривой разобрать не удалось
	if(!this->_field.load(first, item)){
		// Выполняем сброс установленных параметров кривой
		this->clear();
		// Выводим отказ установки параметров кривой
		return false;
	}
	// Выполняем приведение первого коэффициента в область Монтгомери
	this->_field.enter(item, this->_first);
	// Число три, которым опознаётся коэффициент кривой
	math::number_t three;
	// Получаем число три в виде числа поля
	this->_field.word(3, three);
	// Сумма первого коэффициента с числом три
	math::number_t sum;
	// Выполняем сложение первого коэффициента с числом три
	this->_field.add(item, three, sum);
	/**
	 * Коэффициент, равный модулю без трёх, даёт удвоению точки способ покороче:
	 * множитель касательной раскладывается на разность и сумму, и двух возведений в
	 * квадрат на всяком удвоении не нужно вовсе. Кривые ГОСТ такой коэффициент имеют
	 */
	this->_shortened = this->_field.zero(sum);
	// Если второй коэффициент уравнения кривой разобрать не удалось
	if(!this->_field.load(second, item)){
		// Выполняем сброс установленных параметров кривой
		this->clear();
		// Выводим отказ установки параметров кривой
		return false;
	}
	// Выполняем приведение второго коэффициента в область Монтгомери
	this->_field.enter(item, this->_second);
	// Устанавливаем признак того, что кривая установлена
	this->_ready = true;
	// Если образующую точку разобрать не удалось
	if(!this->point(x, y, this->_base)){
		// Выполняем сброс установленных параметров кривой
		this->clear();
		// Выводим отказ установки параметров кривой
		return false;
	}
	// Число один, приводимое в область Монтгомери
	math::number_t one;
	// Получаем число один в виде числа поля
	this->_field.word(1, one);
	// Выполняем приведение единицы поля в область Монтгомери
	this->_field.enter(one, this->_unit);
	/**
	 * Разыскиваем заготовленные при сборке кратные точки основания. Опознаются они
	 * самой точкой основания, а не опознавателем набора параметров: кривая, заведённая
	 * теми же значениями напрямую, получает заготовленное наравне с заведённой по
	 * опознавателю
	 */
	this->_multiples = precomputed(this->_base.x.words, this->_base.y.words, ((this->_order.size() + 7) / 8));
	/**
	 * Точка основания опознаёт кривую не вполне: кривая с тем же модулем и той же точкой,
	 * но иным первым коэффициентом, дала бы чужие кратные. Удвоение точки основания идёт
	 * через первый коэффициент, оттого второе кратное таблицы сверяется с удвоением своей
	 * арифметикой: расхождение снимает заготовленное
	 */
	if(this->_multiples != nullptr){
		// Число слов координаты
		const size_t words = ((this->_order.size() + 7) / 8);
		// Описание заготовленных кратных
		const precomputed_t * multiples = static_cast <const precomputed_t *> (this->_multiples);
		// Второе кратное таблицы: за первой парой координат
		point_t sample;
		// Переносим координаты второго кратного
		::memcpy(sample.x.words, multiples->data + (2 * words), words * sizeof(uint64_t));
		::memcpy(sample.y.words, multiples->data + (3 * words), words * sizeof(uint64_t));
		// Третья координата - единица поля
		sample.z = this->_unit;
		// Удвоенная точка основания своей арифметикой
		point_t doubled;
		// Выполняем удвоение
		this->twice(this->_base, doubled);
		// Координаты обеих точек
		uint8_t first[2 * math::NUMBER_SIZE], second[2 * math::NUMBER_SIZE];
		// Длина координаты в байтах
		const size_t size = this->_order.size();
		// Если координаты не сошлись - кратные чужие
		if(!this->coordinates(sample, first, first + size, size) || !this->coordinates(doubled, second, second + size, size) || (::memcmp(first, second, 2 * size) != 0))
			// Снимаем заготовленное
			this->_multiples = nullptr;
	}
	// Выводим успешность установки параметров кривой
	return true;
}
/**
 * @brief Метод сброса установленных параметров кривой
 *
 */
void nts::curve::Curve::clear() noexcept {
	// Сбрасываем кофактор кривой
	this->_cofactor = 1;
	// Сбрасываем заготовленные кратные точки основания
	this->_multiples = nullptr;
	// Выполняем сброс единицы поля кривой
	this->_unit = math::number_t();
	// Выполняем сброс образующей точки подгруппы точек кривой
	this->_base = point_t();
	// Выполняем сброс второго коэффициента уравнения кривой
	this->_second = math::number_t();
	// Выполняем сброс первого коэффициента уравнения кривой
	this->_first = math::number_t();
	// Сбрасываем признак коэффициента, равного модулю без трёх
	this->_shortened = false;
	// Выполняем сброс порядка подгруппы точек кривой
	this->_order.clear();
	// Выполняем сброс модуля поля кривой
	this->_field.clear();
	// Снимаем признак того, что кривая установлена
	this->_ready = false;
}
/**
 * @brief Метод получения образующей точки подгруппы точек кривой
 *
 * @param result место, в которое помещается образующая точка
 *
 */
void nts::curve::Curve::base(point_t & result) const noexcept {
	// Записываем образующую точку подгруппы точек кривой
	result = this->_base;
}
/**
 * @brief Метод разбора точки из координат
 *
 * @param x      первая координата разбираемой точки
 * @param y      вторая координата разбираемой точки
 * @param result место, в которое помещается разобранная точка
 *
 * @return       признак успешности разбора точки
 *
 */
bool nts::curve::Curve::point(const view_t & x, const view_t & y, point_t & result) const noexcept {
	// Выполняем сброс разбираемой точки
	result = point_t();
	// Если кривая не установлена
	if(!this->_ready)
		// Выводим отказ разбора точки
		return false;
	// Разбираемые координаты точки
	math::number_t first, second;
	// Если координаты точки разобрать не удалось
	if(!this->_field.load(x, first) || !this->_field.load(y, second))
		// Выводим отказ разбора точки
		return false;
	// Выполняем приведение первой координаты точки в область Монтгомери
	this->_field.enter(first, result.x);
	// Выполняем приведение второй координаты точки в область Монтгомери
	this->_field.enter(second, result.y);
	// Записываем единицу третьей координатой аффинной точки
	this->_field.word(1, first);
	// Выполняем приведение третьей координаты точки в область Монтгомери
	this->_field.enter(first, result.z);
	// Левая и правая части уравнения кривой
	math::number_t left, right;
	// Выполняем возведение второй координаты точки в квадрат
	this->_field.multiply(result.y, result.y, left);
	// Выполняем возведение первой координаты точки в квадрат
	this->_field.multiply(result.x, result.x, right);
	// Выполняем возведение первой координаты точки в куб
	this->_field.multiply(right, result.x, right);
	// Выполняем умножение первой координаты точки на первый коэффициент уравнения
	this->_field.multiply(result.x, this->_first, second);
	// Складываем куб первой координаты с полученным произведением
	this->_field.add(right, second, right);
	// Складываем полученную сумму со вторым коэффициентом уравнения
	this->_field.add(right, this->_second, right);
	// Если части уравнения кривой не сошлись
	if(!this->_field.equal(left, right)){
		// Выполняем сброс разбираемой точки
		result = point_t();
		// Выводим отказ разбора точки
		return false;
	}
	/**
	 * Кривые с кофактором больше единицы несут точки малого порядка, и уравнение
	 * кривой их не отсекает: раздел 5.2 ГОСТ Р 34.10-2012 велит проверять
	 * принадлежность точки подгруппе порядка q. Точка кручения обращается в ноль
	 * умножением на кофактор - по нему она здесь и отсекается
	 */
	if(this->_cofactor > 1){
		// Ноль, единица и порядок без единицы в арифметике порядка
		math::number_t zero, one, last;
		// Точки (q - 1)·Q и q·Q
		point_t nearly, cleared;
		// Ноль
		this->_order.word(0, zero);
		// Единица
		this->_order.word(1, one);
		// q - 1: сам порядок числом арифметики по модулю q не выразить
		this->_order.subtract(zero, one, last);
		/**
		 * Раздел 5.2 ГОСТ Р 34.10-2012 требует q·Q = O. Отсечь одни лишь точки кручения
		 * умножением на кофактор мало: точка G + T с T порядка два лежит на кривой,
		 * h·(G + T) = h·G не ноль, а q·(G + T) = T не ноль - такая точка проходила бы
		 */
		this->multiply(result, last, nearly);
		// q·Q = (q - 1)·Q + Q
		this->add(nearly, result, cleared);
		// Если точка не в подгруппе порядка q
		if(!this->infinity(cleared)){
			// Выполняем сброс разбираемой точки
			result = point_t();
			// Выводим отказ разбора точки
			return false;
		}
	}
	// Выводим успешность разбора точки
	return true;
}
/**
 * @brief Метод записи координат точки
 *
 * @param value записываемая точка
 * @param x     место, в которое записывается первая координата точки
 * @param y     место, в которое записывается вторая координата точки
 * @param size  размер места, в которое записывается всякая координата
 *
 * @return      признак успешности записи координат точки
 *
 */
bool nts::curve::Curve::coordinates(const point_t & value, uint8_t * x, uint8_t * y, const size_t size) const noexcept {
	// Если кривая не установлена либо точка бесконечно удалена
	if(!this->_ready || this->infinity(value))
		// Выводим отказ записи координат точки
		return false;
	// Обратное значение третьей координаты точки и его степени
	math::number_t item, square, item2;
	// Выполняем обращение третьей координаты точки
	this->_field.invert(value.z, item);
	// Выполняем возведение обратного значения в квадрат
	this->_field.multiply(item, item, square);
	// Выполняем умножение первой координаты точки на квадрат обратного значения
	this->_field.multiply(value.x, square, item2);
	// Выполняем вывод первой координаты точки из области Монтгомери
	this->_field.leave(item2, item2);
	// Признак успешности записи первой координаты точки
	bool ok = ((x == nullptr) || this->_field.store(item2, x, size));
	// Если первая координата точки записана
	if(ok){
		// Выполняем возведение обратного значения в куб
		this->_field.multiply(square, item, square);
		// Выполняем умножение второй координаты точки на куб обратного значения
		this->_field.multiply(value.y, square, item2);
		// Выполняем вывод второй координаты точки из области Монтгомери
		this->_field.leave(item2, item2);
		// Записываем вторую координату точки
		ok = ((y == nullptr) || this->_field.store(item2, y, size));
	}
	// Выполняем затирание выведенной координаты точки
	wipe(item2);
	// Выполняем затирание степеней обратного значения
	wipe(square);
	// Выполняем затирание обратного значения третьей координаты
	wipe(item);
	// Выводим признак успешности записи координат точки
	return ok;
}
/**
 * @brief Метод проверки точки на бесконечную удалённость
 *
 * @param value проверяемая точка
 *
 * @return      признак бесконечной удалённости точки
 *
 */
bool nts::curve::Curve::infinity(const point_t & value) const noexcept {
	// Выводим признак равенства третьей координаты точки нулю
	return this->_field.zero(value.z);
}
/**
 * @brief Метод удвоения точки кривой
 *
 * @param value  удваиваемая точка
 * @param result место, в которое помещается удвоенная точка
 *
 */
void nts::curve::Curve::twice(const point_t & value, point_t & result) const noexcept {
	// Квадрат второй координаты удваиваемой точки
	math::number_t square;
	// Промежуточное произведение первой координаты на квадрат второй
	math::number_t product;
	// Множитель уравнения касательной к кривой
	math::number_t factor;
	// Промежуточное значение степеней третьей координаты
	math::number_t item;
	// Первая координата удвоенной точки
	math::number_t x;
	// Вторая координата удвоенной точки
	math::number_t y;
	// Третья координата удвоенной точки
	math::number_t z;
	// Выполняем возведение второй координаты точки в квадрат
	this->_field.multiply(value.y, value.y, square);
	// Выполняем умножение первой координаты точки на квадрат второй
	this->_field.multiply(value.x, square, product);
	// Выполняем удвоение полученного произведения
	this->_field.add(product, product, product);
	// Выполняем повторное удвоение полученного произведения
	this->_field.add(product, product, product);
	/**
	 * Коэффициент, равный модулю без трёх, обращает множитель касательной в
	 * произведение разности и суммы первой координаты с квадратом третьей: два
	 * возведения в квадрат на этом пути не нужны вовсе
	 */
	if(this->_shortened){
		// Разность первой координаты с квадратом третьей
		math::number_t difference;
		// Выполняем возведение третьей координаты точки в квадрат
		this->_field.multiply(value.z, value.z, item);
		// Вычитаем квадрат третьей координаты из первой координаты
		this->_field.subtract(value.x, item, difference);
		// Складываем первую координату с квадратом третьей координаты
		this->_field.add(value.x, item, item);
		// Выполняем умножение разности на полученную сумму
		this->_field.multiply(difference, item, factor);
		// Выполняем удвоение полученного произведения
		this->_field.add(factor, factor, item);
		// Складываем удвоенное произведение с оставшимся его значением
		this->_field.add(item, factor, factor);
	// Если первый коэффициент уравнения кривой произволен
	} else {
		// Выполняем возведение первой координаты точки в квадрат
		this->_field.multiply(value.x, value.x, factor);
		// Выполняем удвоение полученного квадрата первой координаты
		this->_field.add(factor, factor, item);
		// Складываем удвоенный квадрат с оставшимся его значением
		this->_field.add(item, factor, factor);
		// Выполняем возведение третьей координаты точки в квадрат
		this->_field.multiply(value.z, value.z, item);
		// Выполняем возведение третьей координаты точки в четвёртую степень
		this->_field.multiply(item, item, item);
		// Выполняем умножение полученной степени на первый коэффициент уравнения
		this->_field.multiply(item, this->_first, item);
		// Складываем утроенный квадрат первой координаты с полученным произведением
		this->_field.add(factor, item, factor);
	}
	// Выполняем удвоение второй координаты точки
	this->_field.add(value.y, value.y, item);
	// Выполняем умножение удвоенной второй координаты на третью
	this->_field.multiply(item, value.z, z);
	// Выполняем возведение множителя уравнения касательной в квадрат
	this->_field.multiply(factor, factor, x);
	// Вычитаем из полученного квадрата учетверённое произведение
	this->_field.subtract(x, product, x);
	// Вычитаем оставшуюся часть учетверённого произведения
	this->_field.subtract(x, product, x);
	// Вычитаем полученную первую координату из учетверённого произведения
	this->_field.subtract(product, x, y);
	// Выполняем умножение разности на множитель уравнения касательной
	this->_field.multiply(y, factor, y);
	// Выполняем возведение квадрата второй координаты в квадрат
	this->_field.multiply(square, square, square);
	// Выполняем удвоение полученной четвёртой степени
	this->_field.add(square, square, square);
	// Выполняем повторное удвоение полученной четвёртой степени
	this->_field.add(square, square, square);
	// Выполняем третье удвоение полученной четвёртой степени
	this->_field.add(square, square, square);
	// Вычитаем восьмикратную четвёртую степень из произведения
	this->_field.subtract(y, square, result.y);
	// Записываем полученную третью координату удвоенной точки
	result.z = z;
	// Записываем полученную первую координату удвоенной точки
	result.x = x;
}
/**
 * @brief Метод сложения точек кривой без ветвления
 *
 * @param first  первое слагаемое
 * @param second второе слагаемое
 * @param result место, в которое помещается сумма точек
 *
 */
void nts::curve::Curve::attach(const point_t & first, const point_t & second, point_t & result) const noexcept {
	// Приведённые первые координаты слагаемых
	math::number_t u1, u2;
	// Приведённые вторые координаты слагаемых
	math::number_t s1, s2;
	// Разности приведённых координат слагаемых
	math::number_t h, r;
	// Промежуточное значение степеней третьих координат
	math::number_t item;
	// Собираемая сумма точек
	point_t value;
	// Выполняем возведение третьей координаты второго слагаемого в квадрат
	this->_field.multiply(second.z, second.z, item);
	// Выполняем приведение первой координаты первого слагаемого
	this->_field.multiply(first.x, item, u1);
	// Выполняем возведение третьей координаты второго слагаемого в куб
	this->_field.multiply(item, second.z, item);
	// Выполняем приведение второй координаты первого слагаемого
	this->_field.multiply(first.y, item, s1);
	// Выполняем возведение третьей координаты первого слагаемого в квадрат
	this->_field.multiply(first.z, first.z, item);
	// Выполняем приведение первой координаты второго слагаемого
	this->_field.multiply(second.x, item, u2);
	// Выполняем возведение третьей координаты первого слагаемого в куб
	this->_field.multiply(item, first.z, item);
	// Выполняем приведение второй координаты второго слагаемого
	this->_field.multiply(second.y, item, s2);
	// Вычисляем разность приведённых первых координат слагаемых
	this->_field.subtract(u2, u1, h);
	// Вычисляем разность приведённых вторых координат слагаемых
	this->_field.subtract(s2, s1, r);
	// Квадрат и куб разности приведённых первых координат
	math::number_t square, cube;
	// Выполняем возведение разности первых координат в квадрат
	this->_field.multiply(h, h, square);
	// Выполняем возведение разности первых координат в куб
	this->_field.multiply(square, h, cube);
	// Выполняем умножение приведённой первой координаты на квадрат разности
	this->_field.multiply(u1, square, u1);
	// Выполняем возведение разности вторых координат в квадрат
	this->_field.multiply(r, r, item);
	// Вычитаем куб разности первых координат из полученного квадрата
	this->_field.subtract(item, cube, item);
	// Вычитаем полученное произведение из разности
	this->_field.subtract(item, u1, item);
	// Вычитаем оставшуюся часть произведения из разности
	this->_field.subtract(item, u1, value.x);
	// Вычитаем полученную первую координату из произведения
	this->_field.subtract(u1, value.x, u1);
	// Выполняем умножение разности на разность вторых координат
	this->_field.multiply(u1, r, u1);
	// Выполняем умножение приведённой второй координаты на куб разности
	this->_field.multiply(s1, cube, cube);
	// Вычитаем полученное произведение из разности
	this->_field.subtract(u1, cube, value.y);
	// Выполняем умножение третьих координат слагаемых
	this->_field.multiply(first.z, second.z, item);
	// Выполняем умножение полученного произведения на разность первых координат
	this->_field.multiply(item, h, value.z);
	/**
	 * Бесконечно удалённое слагаемое обращает сумму в другое слагаемое: выбор ведётся
	 * наложением маски, оттого удалённость слагаемого временем работы не выдаётся
	 */
	choose(this->infinity(second) ? 1 : 0, first, value, value);
	// Выбираем сумму точек наложением маски удалённости первого слагаемого
	choose(this->infinity(first) ? 1 : 0, second, value, result);
}
/**
 * @brief Метод сложения точек кривой с аффинным вторым слагаемым
 *
 * @param first  первое слагаемое
 * @param second второе слагаемое, третья координата которого равна единице поля
 * @param result место, в которое помещается сумма точек
 *
 */
void nts::curve::Curve::join(const point_t & first, const point_t & second, point_t & result) const noexcept {
	// Приведённые первые координаты слагаемых
	math::number_t u1, u2;
	// Приведённые вторые координаты слагаемых
	math::number_t s1, s2;
	// Разности приведённых координат слагаемых
	math::number_t h, r;
	// Промежуточное значение степеней третьих координат
	math::number_t item;
	// Собираемая сумма точек
	point_t value;
	/**
	 * Третья координата второго слагаемого равна единице поля, оттого приведение
	 * координат первого слагаемого обращается в переписывание: умножение на единицу и
	 * возведение её в квадрат с кубом делать нечего
	 */
	u1 = first.x;
	// Записываем приведённую вторую координату первого слагаемого
	s1 = first.y;
	// Выполняем возведение третьей координаты первого слагаемого в квадрат
	this->_field.multiply(first.z, first.z, item);
	// Выполняем приведение первой координаты второго слагаемого
	this->_field.multiply(second.x, item, u2);
	// Выполняем возведение третьей координаты первого слагаемого в куб
	this->_field.multiply(item, first.z, item);
	// Выполняем приведение второй координаты второго слагаемого
	this->_field.multiply(second.y, item, s2);
	// Вычисляем разность приведённых первых координат слагаемых
	this->_field.subtract(u2, u1, h);
	// Вычисляем разность приведённых вторых координат слагаемых
	this->_field.subtract(s2, s1, r);
	// Квадрат и куб разности приведённых первых координат
	math::number_t square, cube;
	// Выполняем возведение разности первых координат в квадрат
	this->_field.multiply(h, h, square);
	// Выполняем возведение разности первых координат в куб
	this->_field.multiply(square, h, cube);
	// Выполняем умножение приведённой первой координаты на квадрат разности
	this->_field.multiply(u1, square, u1);
	// Выполняем возведение разности вторых координат в квадрат
	this->_field.multiply(r, r, item);
	// Вычитаем куб разности первых координат из полученного квадрата
	this->_field.subtract(item, cube, item);
	// Вычитаем полученное произведение из разности
	this->_field.subtract(item, u1, item);
	// Вычитаем оставшуюся часть произведения из разности
	this->_field.subtract(item, u1, value.x);
	// Вычитаем полученную первую координату из произведения
	this->_field.subtract(u1, value.x, u1);
	// Выполняем умножение разности на разность вторых координат
	this->_field.multiply(u1, r, u1);
	// Выполняем умножение приведённой второй координаты на куб разности
	this->_field.multiply(s1, cube, cube);
	// Вычитаем полученное произведение из разности
	this->_field.subtract(u1, cube, value.y);
	/**
	 * Произведение третьих координат слагаемых равно третьей координате первого:
	 * третья координата второго есть единица поля
	 */
	this->_field.multiply(first.z, h, value.z);
	/**
	 * Бесконечно удалённое слагаемое обращает сумму в другое слагаемое: выбор ведётся
	 * наложением маски, оттого удалённость слагаемого временем работы не выдаётся
	 */
	choose(this->infinity(second) ? 1 : 0, first, value, value);
	// Выбираем сумму точек наложением маски удалённости первого слагаемого
	choose(this->infinity(first) ? 1 : 0, second, value, result);
}
/**
 * @brief Метод сложения точек кривой
 *
 * @param first  первое слагаемое
 * @param second второе слагаемое
 * @param result место, в которое помещается сумма точек
 *
 */
void nts::curve::Curve::add(const point_t & first, const point_t & second, point_t & result) const noexcept {
	// Если первое слагаемое бесконечно удалено
	if(this->infinity(first)){
		// Записываем второе слагаемое суммой точек
		result = second;
		// Выходим из сложения точек
		return;
	}
	// Если второе слагаемое бесконечно удалено
	if(this->infinity(second)){
		// Записываем первое слагаемое суммой точек
		result = first;
		// Выходим из сложения точек
		return;
	}
	// Промежуточные значения сложения точек
	math::number_t u1, u2, s1, s2, h, r, item;
	// Выполняем возведение третьей координаты второго слагаемого в квадрат
	this->_field.multiply(second.z, second.z, item);
	// Выполняем приведение первой координаты первого слагаемого
	this->_field.multiply(first.x, item, u1);
	// Выполняем приведение второй координаты первого слагаемого
	this->_field.multiply(item, second.z, item);
	// Выполняем умножение второй координаты первого слагаемого
	this->_field.multiply(first.y, item, s1);
	// Выполняем возведение третьей координаты первого слагаемого в квадрат
	this->_field.multiply(first.z, first.z, item);
	// Выполняем приведение первой координаты второго слагаемого
	this->_field.multiply(second.x, item, u2);
	// Выполняем приведение второй координаты второго слагаемого
	this->_field.multiply(item, first.z, item);
	// Выполняем умножение второй координаты второго слагаемого
	this->_field.multiply(second.y, item, s2);
	// Вычисляем разность приведённых первых координат слагаемых
	this->_field.subtract(u2, u1, h);
	// Вычисляем разность приведённых вторых координат слагаемых
	this->_field.subtract(s2, s1, r);
	// Если приведённые первые координаты слагаемых совпали
	if(this->_field.zero(h)){
		// Если совпали и приведённые вторые координаты слагаемых
		if(this->_field.zero(r))
			// Выполняем удвоение первого слагаемого
			this->twice(first, result);
		// Если слагаемые оказались противоположны
		else {
			// Выполняем сброс суммы точек в бесконечно удалённую точку
			result = point_t();
		}
		// Выходим из сложения точек
		return;
	}
	// Промежуточные значения степеней разности координат
	math::number_t square, cube, value;
	// Выполняем возведение разности первых координат в квадрат
	this->_field.multiply(h, h, square);
	// Выполняем возведение разности первых координат в куб
	this->_field.multiply(square, h, cube);
	// Выполняем умножение приведённой первой координаты на квадрат разности
	this->_field.multiply(u1, square, value);
	// Выполняем возведение разности вторых координат в квадрат
	this->_field.multiply(r, r, item);
	// Вычитаем куб разности первых координат из полученного квадрата
	this->_field.subtract(item, cube, item);
	// Вычитаем полученное произведение из разности
	this->_field.subtract(item, value, item);
	// Вычитаем оставшуюся часть произведения из разности
	this->_field.subtract(item, value, item);
	// Вычитаем полученную первую координату из произведения
	this->_field.subtract(value, item, value);
	// Выполняем умножение разности на разность вторых координат
	this->_field.multiply(value, r, value);
	// Выполняем умножение приведённой второй координаты на куб разности
	this->_field.multiply(s1, cube, cube);
	// Вычитаем полученное произведение из разности
	this->_field.subtract(value, cube, cube);
	// Выполняем умножение третьих координат слагаемых
	this->_field.multiply(first.z, second.z, value);
	// Выполняем умножение полученного произведения на разность первых координат
	this->_field.multiply(value, h, result.z);
	// Записываем полученную вторую координату суммы точек
	result.y = cube;
	// Записываем полученную первую координату суммы точек
	result.x = item;
}
/**
 * @brief Метод умножения точки кривой на число
 *
 * @param value  умножаемая точка
 * @param factor число, на которое умножается точка
 * @param result место, в которое помещается произведение
 *
 */
void nts::curve::Curve::multiply(const point_t & value, const math::number_t & factor, point_t & result) const noexcept {
	/**
	 * Разрядность окна, которым перебирается множитель
	 *
	 * @note Разрядность обязана делить разрядность множителя нацело: остаток окна
	 *       перебор оставил бы без внимания, и произведение вышло бы неверным
	 */
	static constexpr size_t WINDOW = 4;
	// Число кратных точек, укладывающихся в окно
	static constexpr size_t MULTIPLES = (1 << WINDOW);
	/**
	 * Кратные умножаемой точки от нулевого до пятнадцатого
	 *
	 * @note Таблица считается от самой точки, а не от множителя: точка эта открыта, и
	 *       время её счёта секрета не выдаёт
	 */
	point_t table[MULTIPLES];
	// Записываем первое кратное умножаемой точки
	table[1] = value;
	/**
	 * Выполняем счёт оставшихся кратных умножаемой точки
	 */
	for(size_t i = 2; i < MULTIPLES; i++)
		// Считаем очередное кратное сложением с умножаемой точкой
		this->add(table[i - 1], value, table[i]);
	// Накапливаемое произведение точки на число
	point_t item;
	// Кратное точки, выбранное значением окна
	point_t chosen;
	// Удвоенное накопленное произведение
	point_t twice;
	// Сумма накопленного произведения с выбранным кратным
	point_t sum;
	/**
	 * Выполняем перебор окон множителя от старшего к младшему
	 */
	for(size_t i = (this->_order.size() * 8); i >= WINDOW; i -= WINDOW){
		/**
		 * Выполняем удвоение накопленного произведения по числу разрядов окна
		 */
		for(size_t j = 0; j < WINDOW; j++){
			// Выполняем удвоение накопленного произведения
			this->twice(item, twice);
			// Запоминаем удвоенное накопленное произведение
			item = twice;
		}
		// Извлекаем значение очередного окна множителя
		const uint64_t window = ((factor.words[(i - WINDOW) / 64] >> ((i - WINDOW) % 64)) & (MULTIPLES - 1));
		/**
		 * Выполняем перебор всех кратных умножаемой точки
		 *
		 * @note Перебираются все кратные, а не одно: чтение таблицы по значению окна
		 *       выдало бы разряды множителя временем работы через кеш
		 */
		for(size_t j = 0; j < MULTIPLES; j++)
			// Выбираем кратное точки наложением маски совпадения со значением окна
			choose(equal(window, static_cast <uint64_t> (j)), table[j], chosen, chosen);
		// Выполняем сложение накопленного произведения с выбранным кратным
		this->attach(item, chosen, sum);
		// Запоминаем накопленное произведение
		item = sum;
	}
	// Записываем накопленное произведение
	result = item;
	/**
	 * Накопленное произведение и выбранные кратные выведены из множителя, а
	 * множитель секретен: затираются они, а не таблица кратных открытой точки
	 */
	wipe(sum);
	// Выполняем затирание удвоенного накопленного произведения
	wipe(twice);
	// Выполняем затирание выбранного кратного точки
	wipe(chosen);
	// Выполняем затирание накопленного произведения
	wipe(item);
	// Выполняем перезапись кадров стека шагов умножения
	overwrite();
}
/**
 * @brief Метод умножения точки основания кривой на число
 *
 * @param factor число, на которое умножается точка основания
 * @param result место, в которое помещается произведение
 *
 */
void nts::curve::Curve::product(const math::number_t & factor, point_t & result) const noexcept {
	// Получаем заготовленные при сборке кратные точки основания
	const precomputed_t * multiples = static_cast <const precomputed_t *> (this->_multiples);
	// Если кратные точки основания этой кривой не заготовлены
	if(multiples == nullptr){
		// Выполняем общее умножение точки основания на число
		this->multiply(this->_base, factor, result);
		// Выходим из умножения точки основания
		return;
	}
	// Накапливаемое произведение точки основания на число
	point_t item;
	// Кратное точки основания, выбранное значением окна
	point_t chosen;
	// Сумма накопленного произведения с выбранным кратным
	point_t sum;
	/**
	 * Выполняем обход окон множителя от младшего к старшему: кратные заготовлены на
	 * всякое окно отдельно, и удвоений между окнами не требуется вовсе
	 */
	for(size_t i = 0; i < multiples->positions; i++){
		// Извлекаем значение очередного окна множителя
		const uint64_t window = ((factor.words[(i * TABLES_WINDOW) / 64] >> ((i * TABLES_WINDOW) % 64)) & (TABLES_MULTIPLES));
		// Получаем начало строки заготовленных кратных очередного окна
		const uint64_t * row = (multiples->data + (i * TABLES_MULTIPLES * 2 * multiples->words));
		// Выполняем обнуление выбираемого кратного точки основания
		chosen = point_t();
		/**
		 * Выполняем перебор ВСЕЙ строки заготовленных кратных: выбор идёт наложением
		 * маски совпадения, а не переходом, оттого время работы от значения окна не
		 * зависит и о секретном множителе не говорит
		 */
		for(size_t j = 1; j <= TABLES_MULTIPLES; j++){
			// Получаем маску совпадения значения окна с номером кратного
			const uint64_t mask = (0 - equal(window, static_cast <uint64_t> (j)));
			// Получаем место очередного кратного строки
			const uint64_t * place = (row + ((j - 1) * 2 * multiples->words));
			/**
			 * Выполняем обход слов координат очередного кратного
			 */
			for(size_t w = 0; w < multiples->words; w++){
				// Выбираем очередное слово первой координаты наложением маски
				chosen.x.words[w] |= (place[w] & mask);
				// Выбираем очередное слово второй координаты наложением маски
				chosen.y.words[w] |= (place[multiples->words + w] & mask);
			}
		}
		/**
		 * Кратные заготовлены аффинными, и третья координата их равна единице. У
		 * нулевого же окна кратного нет вовсе: место его занимает бесконечно
		 * удалённая точка, а её признак есть нулевая третья координата
		 */
		const uint64_t living = (0 - (equal(window, 0) ^ 0x01));
		/**
		 * Выполняем сборку третьей координаты выбранного кратного
		 */
		for(size_t w = 0; w < math::NUMBER_WORDS; w++)
			// Записываем очередное слово третьей координаты наложением маски
			chosen.z.words[w] = (this->_unit.words[w] & living);
		/**
		 * Сложение берётся смешанное: третья координата выбранного кратного равна
		 * единице поля, и пять умножений поля из двенадцати обращаются в переписывание.
		 * Нулевое окно единицы этой не несёт, и там смешанное сложение считает мусор -
		 * тот же самый мусор, что считает и сложение общего вида, и снимается он тою же
		 * маской удалённости слагаемого
		 */
		this->join(item, chosen, sum);
		// Запоминаем накопленное произведение
		item = sum;
	}
	// Записываем накопленное произведение итогом умножения
	result = item;
	// Выполняем затирание суммы накопленного произведения с кратным
	wipe(sum);
	// Выполняем затирание выбранного кратного точки основания
	wipe(chosen);
	// Выполняем затирание накопленного произведения
	wipe(item);
	// Выполняем перезапись кадров стека шагов умножения
	overwrite();
}
/**
 * @brief Метод счёта суммы двух произведений точек кривой на числа
 *
 * @param first  первая умножаемая точка
 * @param single число, на которое умножается первая точка
 * @param second вторая умножаемая точка
 * @param pair   число, на которое умножается вторая точка
 * @param result место, в которое помещается сумма произведений
 *
 * @warning Время работы зависит от чисел: метод положен лишь сличению подписи
 *
 */
void nts::curve::Curve::combine(const point_t & first, const math::number_t & single, const point_t & second, const math::number_t & pair, point_t & result) const noexcept {
	// Разрядность окна, которым перебираются оба множителя разом
	static constexpr size_t WINDOW = 2;
	// Число кратных, укладывающихся в окно одного множителя
	static constexpr size_t MULTIPLES = (1 << WINDOW);
	/**
	 * Кратные слагаемых от нулевого до третьего по каждому из множителей
	 *
	 * @note Таблица считается по обеим точкам разом: в ней лежат суммы, а не кратные
	 *       порознь, - оттого окно обоих множителей берёт из неё одно слагаемое
	 */
	point_t table[MULTIPLES][MULTIPLES];
	// Записываем первое кратное первой точки
	table[1][0] = first;
	// Записываем первое кратное второй точки
	table[0][1] = second;
	/**
	 * Выполняем счёт кратных первой точки
	 */
	for(size_t i = 2; i < MULTIPLES; i++)
		// Считаем очередное кратное сложением с первой точкой
		this->add(table[i - 1][0], first, table[i][0]);
	/**
	 * Выполняем счёт кратных второй точки
	 */
	for(size_t j = 2; j < MULTIPLES; j++)
		// Считаем очередное кратное сложением со второй точкой
		this->add(table[0][j - 1], second, table[0][j]);
	/**
	 * Выполняем счёт сумм кратных обеих точек
	 */
	for(size_t i = 1; i < MULTIPLES; i++){
		/**
		 * Выполняем перебор кратных второй точки
		 */
		for(size_t j = 1; j < MULTIPLES; j++)
			// Складываем кратное первой точки с кратным второй
			this->add(table[i][0], table[0][j], table[i][j]);
	}
	// Накапливаемая сумма произведений
	point_t item;
	// Удвоенная накопленная сумма произведений
	point_t doubled;
	// Сумма накопленного значения с выбранным слагаемым
	point_t sum;
	/**
	 * Выполняем перебор окон обоих множителей от старшего к младшему
	 */
	for(size_t i = (this->_order.size() * 8); i >= WINDOW; i -= WINDOW){
		/**
		 * Выполняем удвоение накопленной суммы по числу разрядов окна
		 */
		for(size_t j = 0; j < WINDOW; j++){
			// Выполняем удвоение накопленной суммы произведений
			this->twice(item, doubled);
			// Запоминаем удвоенную накопленную сумму
			item = doubled;
		}
		// Извлекаем значение очередного окна первого множителя
		const uint64_t left = ((single.words[(i - WINDOW) / 64] >> ((i - WINDOW) % 64)) & (MULTIPLES - 1));
		// Извлекаем значение очередного окна второго множителя
		const uint64_t right = ((pair.words[(i - WINDOW) / 64] >> ((i - WINDOW) % 64)) & (MULTIPLES - 1));
		// Если оба окна множителей пусты
		if((left == 0) && (right == 0))
			// Переходим к следующему окну множителей
			continue;
		/**
		 * Слагаемое берётся из таблицы прямо по значениям окон: числа здесь открыты, и
		 * прятать их время работы не от кого
		 */
		this->add(item, table[left][right], sum);
		// Запоминаем накопленную сумму произведений
		item = sum;
	}
	// Записываем накопленную сумму произведений
	result = item;
}
