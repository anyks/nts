using namespace std;

/**
 * @brief Внутренние служебные объекты
 *
 */
namespace {
	/**
	 * Пространство имён библиотеки
	 */
	using namespace nts;

	/**
	 * Пространство имён модуля
	 */
	using namespace nts::math::field448;

	/**
	 * @brief Маска пятидесяти шести разрядов конечности
	 *
	 */
	static constexpr uint64_t MASK = ((static_cast <uint64_t> (1) << 56) - 1);

	/**
	 * @brief Функция полного приведения элемента до единственной записи
	 *
	 * @details После двух волн переносов элемент меньше 2^448 с прибавкой и мог остаться
	 *          в области от модуля до неё: признак этого выводится сложением с 2^224 + 1
	 *          сквозь все конечности - вынести за 2^448 способен только элемент, не
	 *          меньший модуля, ибо модль сам есть 2^448 - 2^224 - 1. Модуль вычитается
	 *          наложением признака: вычитание модуля есть прибавление 2^224 + 1 со
	 *          сбросом разряда 2^448
	 *
	 * @param value приводимый элемент
	 *
	 */
	static void reduce(element_t & value) noexcept {
		// Первую волну переносов
		kernel::wave(value);
		// Вторую волну переносов: после первой конечности могли подрасти
		kernel::wave(value);
		// Признак выхода за 2^448 при прибавлении 2^224 + 1: перенос из нулевой конечности
		uint64_t flag = ((value.limbs[0] + 1) >> 56);
		// Проносим признак сквозь вторую конечность
		flag = ((value.limbs[1] + flag) >> 56);
		// Проносим признак сквозь третью конечность
		flag = ((value.limbs[2] + flag) >> 56);
		// Проносим признак сквозь четвёртую конечность
		flag = ((value.limbs[3] + flag) >> 56);
		// Проносим признак сквозь пятую конечность с прибавлением разряда 2^224
		flag = ((value.limbs[4] + flag + 1) >> 56);
		// Проносим признак сквозь шестую конечность
		flag = ((value.limbs[5] + flag) >> 56);
		// Проносим признак сквозь седьмую конечность
		flag = ((value.limbs[6] + flag) >> 56);
		// Проносим признак сквозь старшую конечность: единица означает выход за 2^448
		flag = ((value.limbs[7] + flag) >> 56);
		// Прибавляем признак к нулевой конечности: вычитание модуля есть прибавление единицы
		value.limbs[0] += flag;
		// Прибавляем признак к пятой конечности: вычитание модуля есть прибавление 2^224
		value.limbs[4] += flag;
		/**
		 * Выполняем волну переносов без сворачивания: разряд 2^448 здесь сбрасывается,
		 * а не возвращается в младшие конечности, иначе модуль вычелся бы дважды
		 */
		for(size_t i = 0; i < (LIMBS - 1); i++){
			// Переносим разряды очередной конечности сверх пятидесяти шести в следующую
			value.limbs[i + 1] += (value.limbs[i] >> 56);
			// Отбрасываем перенесённые разряды очередной конечности
			value.limbs[i] &= MASK;
		}
		// Сбрасываем разряд 2^448 старшей конечности
		value.limbs[LIMBS - 1] &= MASK;
	}
	/**
	 * @brief Функция возведения элемента в степень 2^count
	 *
	 * @param value  возводимый элемент
	 * @param count  число возведений в квадрат
	 * @param result место, в которое помещается степень
	 *
	 */
	static void power(const element_t & value, const size_t count, element_t & result) noexcept {
		// Переносим возводимый элемент в место итога
		result = value;
		/**
		 * Выполняем возведение в квадрат заданное число раз
		 */
		for(size_t i = 0; i < count; i++)
			// Возводим накопленное значение в квадрат
			square(result, result);
	}
	/**
	 * @brief Функция возведения элемента в степень 2^37 - 1
	 *
	 * @details Тридцать семь единиц набираются скольжением: на всяком шаге накопленное
	 *          возводится в квадрат и умножается на исходный элемент, отчего за два
	 *          действия к показателю приписывается один разряд. Степени с единичными
	 *          показателями нужны цепочке блоками по тридцать семь разрядов
	 *
	 * @param value  возводимый элемент
	 * @param result место, в которое помещается степень
	 *
	 */
	static void ones(const element_t & value, element_t & result) noexcept {
		// Начинаем с самого элемента: показатель из одной единицы
		result = value;
		/**
		 * Выполняем приписывание тридцати шести разрядов
		 */
		for(size_t i = 0; i < 36; i++){
			// Возводим накопленное в квадрат: сдвиг показателя на разряд
			square(result, result);
			// Умножаем на исходный элемент: приписываем единицу показателя
			mul(result, value, result);
		}
	}
	/**
	 * @brief Функция возведения элемента в степень 2^446 - 2^222 - 1
	 *
	 * @details Общая часть цепочек обращения и корня: показатель раскладывается в
	 *          (2^223 - 1) * 2^223 + (2^222 - 1), а степень с единичным показателем
	 *          2^222 - 1 собирается из шести блоков по тридцать семь разрядов, ибо
	 *          222 = 6 * 37. Из неё обращение выводится двумя квадратами и умножением
	 *          на исходный элемент, а корень - одним умножением
	 *
	 * @param value  возводимый элемент
	 * @param result место, в которое помещается степень
	 *
	 */
	static void chain(const element_t & value, element_t & result) noexcept {
		// Блок с единичным показателем 2^37 - 1
		element_t block;
		// Вырабатываем блок возведением в степень 2^37 - 1
		ones(value, block);
		// Накопитель степени 2^222 - 1
		element_t item = block;
		/**
		 * Выполняем приписывание пяти блоков по тридцать семь разрядов
		 */
		for(size_t i = 0; i < 5; i++){
			// Сдвигаем накопитель на ширину блока
			power(item, 37, item);
			// Приписываем блок к показателю накопителя
			mul(item, block, item);
		}
		// Вырабатываем x^(2^223 - 1) удвоением показателя и приписыванием единицы
		power(item, 1, result);
		// Приписываем единицу показателя умножением на исходный элемент
		mul(result, value, result);
		// Сдвигаем показатель на двести двадцать три разряда
		power(result, 223, result);
		// Прибавляем показатель накопителя: выходит 2^446 - 2^222 - 1
		mul(result, item, result);
	}
};

/**
 * @brief Функция получения нуля поля
 *
 * @param result место, в которое помещается ноль поля
 *
 */
void nts::math::field448::zero(element_t & result) noexcept {
	/**
	 * Выполняем перебор конечностей элемента
	 */
	for(size_t i = 0; i < LIMBS; i++)
		// Обнуляем очередную конечность
		result.limbs[i] = 0;
}
/**
 * @brief Функция получения единицы поля
 *
 * @param result место, в которое помещается единица поля
 *
 */
void nts::math::field448::one(element_t & result) noexcept {
	// Обнуляем все конечности элемента
	zero(result);
	// Записываем единицу в нулевую конечность
	result.limbs[0] = 1;
}
/**
 * @brief Функция разбора элемента поля из пятидесяти шести байтов
 *
 * @param data   разбираемые байты, записанные младшим байтом вперёд
 * @param result место, в которое помещается разобранный элемент
 *
 */
void nts::math::field448::load(const uint8_t * data, element_t & result) noexcept {
	// Слова разбираемой записи
	uint64_t words[7];
	/**
	 * Выполняем перебор слов записи
	 */
	for(size_t i = 0; i < 7; i++){
		// Обнуляем очередное слово
		words[i] = 0;
		/**
		 * Выполняем перебор байтов очередного слова от старшего к младшему
		 */
		for(size_t j = 8; j > 0; j--)
			// Дописываем очередной байт в слово
			words[i] = ((words[i] << 8) | data[(i * 8) + (j - 1)]);
	}
	// Выделяем нулевую конечность из первого слова
	result.limbs[0] = (words[0] & MASK);
	// Выделяем первую конечность из первого и второго слов
	result.limbs[1] = (((words[0] >> 56) | (words[1] << 8)) & MASK);
	// Выделяем вторую конечность из второго и третьего слов
	result.limbs[2] = (((words[1] >> 48) | (words[2] << 16)) & MASK);
	// Выделяем третью конечность из третьего и четвёртого слов
	result.limbs[3] = (((words[2] >> 40) | (words[3] << 24)) & MASK);
	// Выделяем четвёртую конечность из четвёртого и пятого слов
	result.limbs[4] = (((words[3] >> 32) | (words[4] << 32)) & MASK);
	// Выделяем пятую конечность из пятого и шестого слов
	result.limbs[5] = (((words[4] >> 24) | (words[5] << 40)) & MASK);
	// Выделяем шестую конечность из шестого и седьмого слов
	result.limbs[6] = (((words[5] >> 16) | (words[6] << 48)) & MASK);
	// Выделяем старшую конечность из седьмого слова
	result.limbs[7] = ((words[6] >> 8) & MASK);
	// Приведение записи, не меньшей модуля
	reduce(result);
}
/**
 * @brief Функция записи элемента поля в пятьдесят шесть байтов
 *
 * @param value записываемый элемент
 * @param data  место, в которое помещается запись младшим байтом вперёд
 *
 */
void nts::math::field448::store(const element_t & value, uint8_t * data) noexcept {
	// Приводимая копия элемента
	element_t item = value;
	// Полное приведение элемента
	reduce(item);
	// Слова записываемого элемента
	uint64_t words[7];
	// Собираем первое слово из нулевой и первой конечностей
	words[0] = (item.limbs[0] | (item.limbs[1] << 56));
	// Собираем второе слово из первой и второй конечностей
	words[1] = ((item.limbs[1] >> 8) | (item.limbs[2] << 48));
	// Собираем третье слово из второй и третьей конечностей
	words[2] = ((item.limbs[2] >> 16) | (item.limbs[3] << 40));
	// Собираем четвёртое слово из третьей и четвёртой конечностей
	words[3] = ((item.limbs[3] >> 24) | (item.limbs[4] << 32));
	// Собираем пятое слово из четвёртой и пятой конечностей
	words[4] = ((item.limbs[4] >> 32) | (item.limbs[5] << 24));
	// Собираем шестое слово из пятой и шестой конечностей
	words[5] = ((item.limbs[5] >> 40) | (item.limbs[6] << 16));
	// Собираем седьмое слово из шестой и старшей конечностей
	words[6] = ((item.limbs[6] >> 48) | (item.limbs[7] << 8));
	/**
	 * Выполняем перебор слов записи
	 */
	for(size_t i = 0; i < 7; i++){
		/**
		 * Выполняем перебор байтов очередного слова от младшего к старшему
		 */
		for(size_t j = 0; j < 8; j++)
			// Записываем очередной байт слова
			data[(i * 8) + j] = static_cast <uint8_t> (words[i] >> (j * 8));
	}
}
/**
 * @brief Функция сложения элементов поля
 *
 * @param first  первое слагаемое
 * @param second второе слагаемое
 * @param result место, в которое помещается сумма
 *
 */
void nts::math::field448::add(const element_t & first, const element_t & second, element_t & result) noexcept {
	/**
	 * Выполняем перебор конечностей слагаемых
	 */
	for(size_t i = 0; i < LIMBS; i++)
		// Складываем очередные конечности
		result.limbs[i] = (first.limbs[i] + second.limbs[i]);
	// Волну переносов
	kernel::wave(result);
}
/**
 * @brief Функция вычитания элементов поля
 *
 * @param first  уменьшаемое
 * @param second вычитаемое
 * @param result место, в которое помещается разность
 *
 */
void nts::math::field448::sub(const element_t & first, const element_t & second, element_t & result) noexcept {
	// Вычитаем конечности с прибавлением удвоенного модуля
	kernel::minus(first, second, result);
	// Волну переносов
	kernel::wave(result);
}
/**
 * @brief Функция умножения элементов поля
 *
 * @param first  первый сомножитель
 * @param second второй сомножитель
 * @param result место, в которое помещается произведение
 *
 */
void nts::math::field448::mul(const element_t & first, const element_t & second, element_t & result) noexcept {
	// Умножаем ядром
	kernel::multiply(first, second, result);
}
/**
 * @brief Функция возведения элемента поля в квадрат
 *
 * @param value  возводимый элемент
 * @param result место, в которое помещается квадрат
 *
 */
void nts::math::field448::square(const element_t & value, element_t & result) noexcept {
	// Возводим в квадрат ядром
	kernel::square(value, result);
}
/**
 * @brief Функция умножения элемента поля на малое число
 *
 * @param value  умножаемый элемент
 * @param factor множитель, не больше 2^32
 * @param result место, в которое помещается произведение
 *
 */
void nts::math::field448::mul(const element_t & value, const uint64_t factor, element_t & result) noexcept {
	// Умножаем на малое число ядром
	kernel::scale(value, factor, result);
}
/**
 * @brief Функция обращения элемента поля
 *
 * @param value  обращаемый элемент
 * @param result место, в которое помещается обратный элемент
 *
 */
void nts::math::field448::invert(const element_t & value, element_t & result) noexcept {
	// Степень 2^446 - 2^222 - 1
	element_t item;
	// Общую часть цепочки степеней
	chain(value, item);
	// Вырабатываем x^(2^447 - 2^223 - 2)
	square(item, item);
	// Вырабатываем x^(2^448 - 2^224 - 4)
	square(item, item);
	// Вырабатываем x^(2^448 - 2^224 - 3) умножением на исходный элемент
	mul(item, value, result);
}
/**
 * @brief Функция возведения элемента поля в степень (2^448 - 2^224 + 3) / 4
 *
 * @param value  возводимый элемент
 * @param result место, в которое помещается степень
 *
 */
void nts::math::field448::root(const element_t & value, element_t & result) noexcept {
	// Степень 2^446 - 2^222 - 1
	element_t item;
	// Общую часть цепочки степеней
	chain(value, item);
	// Вырабатываем x^(2^446 - 2^222) умножением на исходный элемент
	mul(item, value, result);
}
/**
 * @brief Функция сличения элементов поля
 *
 * @param first  первый сличаемый элемент
 * @param second второй сличаемый элемент
 * @return       признак равенства элементов
 *
 */
bool nts::math::field448::equal(const element_t & first, const element_t & second) noexcept {
	// Записи сличаемых элементов
	uint8_t a[SIZE], b[SIZE];
	// Записываем первый элемент
	store(first, a);
	// Записываем второй элемент
	store(second, b);
	// Накопленная разность записей
	uint8_t item = 0;
	/**
	 * Выполняем перебор байтов записей
	 */
	for(size_t i = 0; i < SIZE; i++)
		// Накапливаем разность очередных байтов
		item |= (a[i] ^ b[i]);
	// Выводим признак равенства: разность обратилась в ноль
	return (((static_cast <uint32_t> (item) - 1) >> 8) & 1);
}
/**
 * @brief Функция проверки обращения элемента поля в ноль
 *
 * @param value проверяемый элемент
 * @return      признак обращения элемента в ноль
 *
 */
bool nts::math::field448::nil(const element_t & value) noexcept {
	// Ноль поля
	element_t item;
	// Выводим признак равенства элемента нулю
	return equal(value, item);
}
/**
 * @brief Функция условного обмена элементов поля
 *
 * @param first  первый обмениваемый элемент
 * @param second второй обмениваемый элемент
 * @param flag   признак обмена
 *
 */
void nts::math::field448::swap(element_t & first, element_t & second, const uint64_t flag) noexcept {
	// Маска обмена: все разряды по признаку
	const uint64_t mask = (0 - (flag & 1));
	/**
	 * Выполняем перебор конечностей элементов
	 */
	for(size_t i = 0; i < LIMBS; i++){
		// Разность конечностей под маской
		const uint64_t item = ((first.limbs[i] ^ second.limbs[i]) & mask);
		// Накладываем разность на первую конечность
		first.limbs[i] ^= item;
		// Накладываем разность на вторую конечность
		second.limbs[i] ^= item;
	}
}
