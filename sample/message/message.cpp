/**
 * Используем стандартное пространство имён
 */
using namespace std;

/**
 * Подписываемся на пространство имён библиотеки
 */
using namespace nts;

/**
 * @brief Пространство имён образца
 *
 */
namespace {
	/**
	 * @brief Схема подписи владения ключом сертификата образца
	 *
	 * @details Подпись на кривой набора параметров A длиной 256 разрядов
	 *
	 */
	static const extension::scheme_t SCHEME = extension::scheme_t::S256A;

	/**
	 * @brief Метод вывода области байтов шестнадцатеричной записью
	 *
	 * @param title заголовок выводимой области байтов
	 * @param data  выводимая область байтов
	 * @param size  размер выводимой области байтов
	 *
	 */
	void print(const char * title, const uint8_t * data, const size_t size) noexcept {
		// Выводим заголовок области байтов
		cout << title << ": ";
		/**
		 * Выполняем перебор байтов выводимой области
		 */
		for(size_t i = 0; i < size; i++)
			// Выводим очередной байт шестнадцатеричной записью
			cout << hex << setw(2) << setfill('0') << static_cast <uint32_t> (data[i]);
		// Выполняем перевод строки за областью байтов
		cout << dec << endl;
	}
};

/**
 * @brief Функция запуска приложения
 *
 * @param argc длина массива параметров
 * @param argv массив параметров
 *
 * @return     код выхода из приложения
 *
 */
int main(int argc, char * argv[]) noexcept {
	// Объект эллиптической кривой схемы подписи
	curve::curve_t curve;
	// Не используем параметры приложения
	(void) argc;
	// Не используем параметры приложения
	(void) argv;
	// Если кривую схемы подписи завести не удалось
	if(!curve::parameters(extension::curve(SCHEME), curve)){
		// Выводим сообщение об отказе заведения кривой
		cout << "Завести кривую схемы подписи не удалось" << endl;
		// Выходим из приложения с признаком отказа
		return EXIT_FAILURE;
	}
	// Выводим опознаватель кривой схемы подписи
	cout << "Кривая схемы       : " << extension::curve(SCHEME) << endl;
	// Объект электронной подписи владения ключом
	sign::gost_t sign;
	// Выполняем заведение подписи на кривой схемы
	sign.start(curve);
	// Вырабатываемое случайное число закрытого ключа подписи
	math::number_t number;
	// Закрытый ключ подписи владения ключом
	uint8_t secret[64];
	// Если закрытый ключ подписи выработать не удалось
	if(!entropy::number(curve.order(), number)){
		// Выводим сообщение об отказе выработки закрытого ключа
		cout << "Выработать закрытый ключ не удалось" << endl;
		// Выходим из приложения с признаком отказа
		return EXIT_FAILURE;
	}
	// Выполняем запись выработанного закрытого ключа строкой байтов
	curve.order().store(number, secret, curve.size());
	// Выполняем установку закрытого ключа подписи
	sign.secret(view_t(secret, curve.size()));
	// Хеш переписки рукопожатия на миг подписания
	uint8_t transcript[32];
	/**
	 * Выполняем выработку хеша переписки рукопожатия
	 *
	 * @note В настоящей связи хеш берётся от всех сообщений рукопожатия подряд: здесь
	 *       он взят от строки лишь затем, чтобы образец обошёлся без рукопожатия
	 */
	digest::streebog(digest::type_t::SHORT, view_t(reinterpret_cast <const uint8_t *> ("переписка рукопожатия"), 40), transcript, sizeof(transcript));
	// Выводим хеш переписки рукопожатия
	::print("Хеш переписки      ", transcript, sizeof(transcript));
	// Накопитель, в который складывается подписываемое содержимое
	vector <uint8_t> content;
	/**
	 * Выполняем составление подписываемого содержимого владения ключом
	 *
	 * @note Подписывается не хеш переписки сам по себе: пробелами подпись отделяется от
	 *       подписей предыдущих изданий протокола, а названием назначения - подпись
	 *       сервера от подписи клиента
	 */
	if(message::content(view_t(transcript, sizeof(transcript)), true, content) != message::error_t::NONE){
		// Выводим сообщение об отказе составления содержимого
		cout << "Составить подписываемое содержимое не удалось" << endl;
		// Выходим из приложения с признаком отказа
		return EXIT_FAILURE;
	}
	// Выводим длину подписываемого содержимого
	cout << "Подписывается      : " << content.size() << " байтов" << endl;
	// Место, в которое помещается хеш подписываемого содержимого
	uint8_t digest[32];
	/**
	 * Выполняем хеширование подписываемого содержимого
	 *
	 * @note Хеш берётся записью вектором: стандарт подписи толкует его числом
	 */
	digest::streebog(digest::type_t::SHORT, view_t(content.data(), content.size()), digest, sizeof(digest), digest::order_t::VECTOR);
	// Место, в которое помещается подпись владения ключом
	uint8_t signature[128];
	// Если подписать владение ключом сертификата не удалось
	if(!sign.make(view_t(digest, sizeof(digest)), signature)){
		// Выводим сообщение об отказе подписания владения ключом
		cout << "Подписать владение ключом не удалось" << endl;
		// Выходим из приложения с признаком отказа
		return EXIT_FAILURE;
	}
	// Определяем длину подписи владения ключом сертификата
	const size_t length = (curve.size() * 2);
	// Выводим подпись владения ключом в записи модуля подписи
	::print("Подпись, числами   ", signature, length);
	// Место, в которое помещается подпись в записи протокола
	uint8_t wire[128];
	/**
	 * Выполняем обращение записи подписи владения ключом
	 *
	 * @note Раздел 5.3 описания наборов велит писать обе половины подписи младшим
	 *       разрядом вперёд: без обращения собеседник подпись отвергнет, и разобраться
	 *       в этом отказе будет непросто - он ничем не отличается от подписи подделанной
	 */
	if(message::reverse(view_t(signature, length), wire) != message::error_t::NONE){
		// Выводим сообщение об отказе обращения записи подписи
		cout << "Обратить запись подписи не удалось" << endl;
		// Выходим из приложения с признаком отказа
		return EXIT_FAILURE;
	}
	// Выводим подпись владения ключом в записи протокола
	::print("Подпись, протокол  ", wire, length);
	// Составляемое сообщение подписи владения ключом
	message::verify_t verify;
	// Устанавливаем схему подписи владения ключом сертификата
	verify.scheme = SCHEME;
	// Устанавливаем значение подписи владения ключом сертификата
	verify.signature = view_t(wire, length);
	// Накопитель, в который складывается тело сообщения подписи
	vector <uint8_t> body;
	// Выполняем составление тела сообщения подписи владения ключом
	message::build(verify, body);
	// Объект составителя исходящих сообщений рукопожатия
	handshake::writer_t writer;
	// Выполняем составление сообщения подписи владения ключом
	writer.push(handshake::type_t::VERIFY, view_t(body.data(), body.size()));
	// Получаем составленное сообщение подписи владения ключом
	const view_t sample = writer.data();
	// Выводим длину составленного сообщения подписи
	cout << "Длина сообщения    : " << sample.size << " байтов" << endl;
	// Обвязка принятого сообщения подписи владения ключом
	handshake::header_t header;
	// Выполняем разбор обвязки принятого сообщения
	handshake::parse(sample, header);
	// Разобранное сообщение подписи владения ключом
	message::verify_t parsed;
	// Если тело принятого сообщения разобрать не удалось
	if(message::parse(view_t(sample.data + handshake::HANDSHAKE_HEADER, header.size), parsed) != message::error_t::NONE){
		// Выводим сообщение об отказе разбора сообщения
		cout << "Разобрать сообщение подписи не удалось" << endl;
		// Выходим из приложения с признаком отказа
		return EXIT_FAILURE;
	}
	// Место, в которое помещается обращённая обратно подпись
	uint8_t restored[128];
	// Выполняем обращение записи принятой подписи обратно
	message::reverse(parsed.signature, restored);
	// Если подпись владения ключом сертификата не сошлась
	if(!sign.check(view_t(digest, sizeof(digest)), view_t(restored, parsed.signature.size))){
		// Выводим сообщение об отказе проверки подписи
		cout << "Подпись владения ключом не сошлась" << endl;
		// Выходим из приложения с признаком отказа
		return EXIT_FAILURE;
	}
	// Выводим сообщение об успешной проверке подписи владения ключом
	cout << "Проверка подписи   : подпись сошлась" << endl;
	// Ключ выработки завершения рукопожатия
	uint8_t key[schedule::SCHEDULE_SECRET];
	// Значение направления связи, из которого выводится ключ завершения
	uint8_t traffic[schedule::SCHEDULE_SECRET];
	// Выполняем выработку значения направления связи
	entropy::bytes(traffic, sizeof(traffic));
	/**
	 * Выполняем вывод ключа выработки завершения рукопожатия
	 *
	 * @note Ключ этот выводится расписанием ключей меткою «finished» из значения
	 *       направления связи - того же, из которого выведены ключ и вектор замены
	 */
	if(!schedule::derive(view_t(traffic, sizeof(traffic)), view_t(reinterpret_cast <const uint8_t *> ("finished"), 8), view_t(nullptr, 0), key, sizeof(key))){
		// Выводим сообщение об отказе вывода ключа завершения
		cout << "Вывести ключ завершения не удалось" << endl;
		// Выходим из приложения с признаком отказа
		return EXIT_FAILURE;
	}
	// Место, в которое помещается тело сообщения завершения рукопожатия
	uint8_t finished[32];
	// Выполняем выработку тела сообщения завершения рукопожатия
	if(message::finished(view_t(key, sizeof(key)), view_t(transcript, sizeof(transcript)), finished) != message::error_t::NONE){
		// Выводим сообщение об отказе выработки завершения
		cout << "Выработать завершение рукопожатия не удалось" << endl;
		// Выходим из приложения с признаком отказа
		return EXIT_FAILURE;
	}
	// Выводим тело сообщения завершения рукопожатия
	::print("Завершение         ", finished, sizeof(finished));
	// Место, в которое помещается завершение встречной стороны
	uint8_t incoming[32];
	// Выполняем выработку завершения рукопожатия встречной стороной
	message::finished(view_t(key, sizeof(key)), view_t(transcript, sizeof(transcript)), incoming);
	/**
	 * Выполняем сличение завершений рукопожатия сторон
	 *
	 * @note Сличение ведётся за постоянное время: время сличения не выдаёт, сколько
	 *       байтов принятого завершения сошлось
	 */
	if(message::compare(view_t(finished, sizeof(finished)), view_t(incoming, sizeof(incoming))))
		// Выводим сообщение о схождении завершений рукопожатия сторон
		cout << "Сличение           : стороны видели одну переписку" << endl;
	// Портим один байт хеша переписки рукопожатия
	transcript[0] = static_cast <uint8_t> (transcript[0] ^ 0x01);
	// Выполняем выработку завершения на подменённой переписке
	message::finished(view_t(key, sizeof(key)), view_t(transcript, sizeof(transcript)), incoming);
	// Если завершение на подменённой переписке разошлось
	if(!message::compare(view_t(finished, sizeof(finished)), view_t(incoming, sizeof(incoming))))
		// Выводим сообщение о расхождении завершений на подменённой переписке
		cout << "Подмена переписки  : завершения разошлись" << endl;
	// Выходим из приложения с признаком успеха
	return EXIT_SUCCESS;
}
