/**
 * @note Переносимый путь и векторные ветви собираются в один двоичный файл, а выбор
 *       делается на исполнении по опознанию машины (sys/machine.hpp). Команды
 *       порождаются в отдельных функциях с атрибутом цели, оттого общих ключей
 *       расширений сборке не нужно. Признак ANTS_NO_MACHINE выбрасывает векторные
 *       ветви из сборки вовсе. Векторная ветвь берётся только на целых блоках гаммы:
 *       остаток блока и хвост короче пачки идут переносимым путём, и нарезка данных
 *       на куски на итог не влияет. Рабочие слова векторных ветвей живут в регистрах
 *       и не затираются: взятие их адреса ради затирания заставило бы собирателя
 *       держать их в памяти и стоило бы дороже самих раундов, а ключ и без того
 *       лежит в состоянии шифра и затирается при сбросе.
 *       Восемь блоков у NEON (круг 37, 23.09.2026): четвёрка блоков давала лишь четыре
 *       независимые цепочки четвертьраундов, и машина с четырьмя векторными
 *       устройствами и задержкой команды в два такта простаивала наполовину - полоса
 *       упиралась в задержку, а не в число устройств; две четвёрки вперемешку дают
 *       восемь цепочек: на Apple M4 1,86 → 2,8 ГБ/с при 3,0 у OpenSSL, ведущего шесть
 *       блоков векторами и два скалярами. Хвост от четырёх до семи блоков идёт четвёркой
 */

