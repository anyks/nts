				extension::group_t _group;
			private:
				// Мимолётные пары ключей своей стороны по группам обмена
				vector <exchange_t> _exchanges;
			private:
				/**
				 * \~russian
				 * @brief Структура ключевого материала связи, живущего между вызовами
				 *
				 * @details Лежит целиком в укрытой памяти хранилища (sys::Vault): подкачка
				 *          запрещена, снимки памяти его не содержат, потомок процесса получает
				 *          затёртым. Решение 17 шапки
				 *
				 * \~english
				 * @brief Structure of the key material of the connection living between the calls
				 *
				 * \~
				 */
				typedef struct Keys {
					// Главный секрет связи издания TLS 1.2
					uint8_t master[48];
					// Ключи завершения рукопожатия сторон связи
					uint8_t completion[2][schedule::SCHEDULE_WIDEST];
					// Ключевой материал прикладных данных сторон связи
					uint8_t key[2][protect::PROTECT_KEY], vector[2][protect::PROTECT_VECTOR];
					// Ключи имитовставки сторон связи наборов CBC издания TLS 1.2
					uint8_t stamp[2][protect::PROTECT_MAC];
					// Значения направлений связи по уровням защиты и сторонам
					uint8_t traffic[3][2][schedule::SCHEDULE_WIDEST];
				} keys_t;
			private:
				// Участок укрытой памяти под ключевой материал связи
				sys::secret_t _shelter;
				// Ключевой материал связи в укрытой памяти; nullptr, если хранилище участка не дало
				keys_t * _keys;
			private:
				// Случайное значение своего приветствия
				uint8_t _random[32];
				// Опознаватель связи, доставшийся от предыдущих изданий
				vector <uint8_t> _session;
			private:
				// Накопитель отправляемых байтов связи
				vector <uint8_t> _wire;
				// Накопитель принятых прикладных данных
				vector <uint8_t> _plain;
				// Накопитель открытого содержимого принятой записи: живёт с движком, чтобы не занимать память на каждую запись
				vector <uint8_t> _opened;
			private:
				// Наборы шифрования, предлагаемые связью
				vector <protect::suite_t> _suites;
				// Настройка наборов шифрования: источник для _suites при всяком заведении связи
				vector <protect::suite_t> _catalog;
				// Кривые обмена ключами, предлагаемые связью
