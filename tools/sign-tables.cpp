/**
 * @brief Функция вывода одного места таблицы кратных в суммарно-разностном виде
 *
 * @param item точка места с произвольным знаменателем
 *
 */
static void place(const sign::kernel::point_t & item) noexcept {
	// Обратный знаменатель места и значения суммарно-разностного вида
	sign::kernel::element_t inverse, x, y, plus, minus, product, coefficient, crossed;
	// Выполняем обращение знаменателя места
	math::field25519::invert(item.z, inverse);
	// Приводим первую координату места к единичному знаменателю
	math::field25519::mul(item.x, inverse, x);
	// Приводим вторую координату места к единичному знаменателю
	math::field25519::mul(item.y, inverse, y);
	// Вычисляем сумму координат места
	math::field25519::add(y, x, plus);
	// Вычисляем разность координат места
	math::field25519::sub(y, x, minus);
	// Вычисляем произведение координат места
	math::field25519::mul(x, y, product);
	// Разбираем коэффициент кривой
	math::field25519::load(sign::kernel::COEFFICIENT, coefficient);
	// Умножаем произведение координат на коэффициент кривой
	math::field25519::mul(product, coefficient, crossed);
	// Удваиваем произведение с коэффициентом кривой
	math::field25519::add(crossed, crossed, crossed);
	// Выводим открывающую скобку места таблицы
	::printf("{");
	// Выводим открывающую скобку суммы координат
	::printf("{");
	// Выполняем вывод суммы координат места
	emit(plus);
	// Выводим закрывающую скобку суммы координат и разделитель
	::printf("}, {");
	// Выполняем вывод разности координат места
	emit(minus);
	// Выводим закрывающую скобку разности координат и разделитель
	::printf("}, {");
	// Выполняем вывод удвоенного произведения координат с коэффициентом
	emit(crossed);
	// Выводим закрывающую скобку удвоенного произведения
	::printf("}");
	// Выводим закрывающую скобку места таблицы
	::printf("}");
}
/**
 * @brief Точка входа программы вычисления заготовленных кратных точки основания
 *
 * @return код возврата, нулевой у успешного вывода
 *
 */
int main() noexcept {
	// Выводим обвязку выводимого исходного файла
	::printf(
		"/**\n"
		" * @file sign-tables.cpp\n"
		" *\n"
		" * @license{LicenseRef-A-NTS-1.0}\n"
		" *\n"
		" * @author Yuriy Lobarev\n"
		" *\n"
		" * @brief Исходный файл заготовленных кратных точек основания кривых Эдвардса Ed25519 и Ed448\n"
		" *\n"
		" * @note Файл ВЫЧИСЛЕН ПРИ СБОРКЕ программой tools/sign-tables.cpp. Править его\n"
		" *       руками бессмысленно: всякая сборка пишет его заново\n"
		" *\n"
		" * @copyright Copyright © 2026\n"
		" *\n"
		" */\n\n"
		"/**\n"
		" * Подключаем заголовочные файлы проекта\n"
		" */\n"
		"#include <internal/sign/tables.hpp>\n\n"
		"/**\n"
		" * Пространство имён локальных объектов\n"
		" */\n"
		"namespace {\n"
		"\t/**\n"
		"\t * Заготовленная гребёнка кратных точки основания\n"
		"\t */\n"
		"\tstatic const nts::sign::comb_t COMB[nts::sign::COMB_ROWS][nts::sign::COMB_PLACES] = {\n"
	);
	// Точка, кратные которой занимает очередная строка гребёнки
	sign::kernel::point_t step;
	// Получаем точку основания кривой
	sign::kernel::base(step);
	/**
	 * Выполняем обход строк гребёнки кратных
	 */
	for(size_t i = 0; i < sign::COMB_ROWS; i++){
		// Выводим открывающую скобку строки гребёнки
		::printf("\t\t{\n");
		// Нейтральная точка - нулевое место строки
		sign::kernel::point_t item;
		// Выполняем получение нейтральной точки
		sign::kernel::neutral(item);
		/**
		 * Выполняем обход мест строки гребёнки
		 */
		for(size_t j = 0; j < sign::COMB_PLACES; j++){
			// Обратный знаменатель места и значения суммарно-разностного вида
			sign::kernel::element_t inverse, x, y, plus, minus, product, coefficient, crossed;
			// Выполняем обращение знаменателя места
			math::field25519::invert(item.z, inverse);
			// Приводим первую координату места к единичному знаменателю
			math::field25519::mul(item.x, inverse, x);
			// Приводим вторую координату места к единичному знаменателю
			math::field25519::mul(item.y, inverse, y);
			// Вычисляем сумму координат места
			math::field25519::add(y, x, plus);
			// Вычисляем разность координат места
			math::field25519::sub(y, x, minus);
			// Вычисляем произведение координат места
			math::field25519::mul(x, y, product);
			// Разбираем коэффициент кривой
			math::field25519::load(sign::kernel::COEFFICIENT, coefficient);
			// Умножаем произведение координат на коэффициент кривой
			math::field25519::mul(product, coefficient, crossed);
			// Удваиваем произведение с коэффициентом кривой
			math::field25519::add(crossed, crossed, crossed);
			// Выводим отступ места строки гребёнки
			::printf("\t\t\t{");
			// Выводим открывающую скобку суммы координат
			::printf("{");
			// Выполняем вывод суммы координат места
			emit(plus);
			// Выводим закрывающую скобку суммы координат и разделитель
			::printf("}, {");
			// Выполняем вывод разности координат места
			emit(minus);
			// Выводим закрывающую скобку разности координат и разделитель
			::printf("}, {");
			// Выполняем вывод удвоенного произведения координат с коэффициентом
			emit(crossed);
			// Выводим закрывающую скобку удвоенного произведения
			::printf("}");
			// Выводим конец записи места строки с разделителем мест
			::printf("}%s\n", ((j + 1) < sign::COMB_PLACES ? "," : ""));
			// Если место строки не последнее
			if((j + 1) < sign::COMB_PLACES){
				// Следующее кратное строки
				sign::kernel::point_t next;
				// Выполняем сложение кратного с точкой строки
				sign::kernel::add(item, step, next);
				// Запоминаем следующее кратное строки
				item = next;
			}
		}
		// Выводим закрывающую скобку строки гребёнки с разделителем строк
		::printf("\t\t}%s\n", ((i + 1) < sign::COMB_ROWS ? "," : ""));
		/**
		 * Выполняем сдвиг точки строки на шестнадцать разрядов удвоениями
		 */
		for(size_t k = 0; k < 16; k++){
			// Удвоенная точка строки
			sign::kernel::point_t twice;
			// Выполняем удвоение точки строки
			sign::kernel::twice(step, twice);
			// Запоминаем удвоенную точку строки
			step = twice;
		}
	}
	// Выводим завершение гребёнки Ed25519 и заголовок позиционной таблицы окон
	::printf(
		"\t};\n\n"
		"\t/**\n"
		"\t * Позиционная таблица кратных точки основания: окно четырёх разрядов несёт восемь мест со знаком\n"
		"\t */\n"
		"\tstatic const nts::sign::comb_t WINDOWED[nts::sign::COMB_WINDOWS][nts::sign::COMB_CHOICES] = {\n"
	);
	// Точка окна: кратное шестнадцати в степени номера окна точки основания
	sign::kernel::point_t window;
	// Начинаем окна с точки основания
	sign::kernel::base(window);
	/**
	 * Выполняем обход окон позиционной таблицы
	 */
	for(size_t i = 0; i < sign::COMB_WINDOWS; i++){
		// Выводим открывающую скобку окна
		::printf("\t\t{\n");
		// Накапливаемое кратное окна: начинается с нейтральной точки
		sign::kernel::point_t item;
		// Выполняем получение нейтральной точки
		sign::kernel::neutral(item);
		/**
		 * Выполняем обход мест окна
		 */
		for(size_t j = 0; j < sign::COMB_CHOICES; j++){
			// Выводим отступ места окна
			::printf("\t\t\t");
			// Выводим место окна в суммарно-разностном виде
			place(item);
			// Выводим конец записи места окна с разделителем мест
			::printf("%s\n", ((j + 1) < sign::COMB_CHOICES ? "," : ""));
			// Если место окна не последнее
			if((j + 1) < sign::COMB_CHOICES){
				// Следующее кратное окна
				sign::kernel::point_t next;
				// Выполняем сложение кратного с точкой окна
				sign::kernel::add(item, window, next);
				// Запоминаем следующее кратное окна
				item = next;
			}
		}
		// Выводим закрывающую скобку окна с разделителем окон
		::printf("\t\t}%s\n", ((i + 1) < sign::COMB_WINDOWS ? "," : ""));
		/**
		 * Выполняем сдвиг точки окна на четыре разряда удвоениями
		 */
		for(size_t k = 0; k < 4; k++){
			// Удвоенная точка окна
			sign::kernel::point_t twice;
			// Выполняем удвоение точки окна
			sign::kernel::twice(window, twice);
			// Запоминаем удвоенную точку окна
			window = twice;
		}
	}
	// Выводим завершение позиционной таблицы и начало гребёнки Ed448
	::printf(
		"\t};\n\n"
		"\t/**\n"
		"\t * Заготовленная гребёнка кратных точки основания Ed448\n"
		"\t */\n"
		"\tstatic const nts::sign::comb448_t COMB448[nts::sign::COMB448_ROWS][nts::sign::COMB448_PLACES] = {\n"
	);
	// Точка, кратные которой занимает очередная строка гребёнки Ed448
	sign::kernel448::point_t stride;
	// Получаем точку основания кривой Ed448
	sign::kernel448::base(stride);
	/**
	 * Выполняем обход строк гребёнки кратных Ed448
	 */
	for(size_t i = 0; i < sign::COMB448_ROWS; i++){
		// Выводим открывающую скобку строки гребёнки
		::printf("\t\t{\n");
		// Нейтральная точка - нулевое место строки
		sign::kernel448::point_t item;
		// Выполняем получение нейтральной точки
		sign::kernel448::neutral(item);
		/**
		 * Выполняем обход мест строки гребёнки
		 */
		for(size_t j = 0; j < sign::COMB448_PLACES; j++){
			// Выводим отступ места строки гребёнки
			::printf("\t\t\t{");
			// Выводим открывающую скобку первой координаты
			::printf("{");
			// Выполняем вывод первой координаты места
			emit448(item.x);
			// Выводим закрывающую скобку первой координаты и разделитель
			::printf("}, {");
			// Выполняем вывод второй координаты места
			emit448(item.y);
			// Выводим закрывающую скобку второй координаты и разделитель
			::printf("}, {");
			// Выполняем вывод знаменателя места
			emit448(item.z);
			// Выводим закрывающую скобку знаменателя и разделитель
			::printf("}, {");
			// Выполняем вывод произведения координат места
			emit448(item.t);
			// Выводим закрывающую скобку произведения координат
			::printf("}");
			// Выводим конец записи места строки с разделителем мест
			::printf("}%s\n", ((j + 1) < sign::COMB448_PLACES ? "," : ""));
			// Если место строки не последнее
			if((j + 1) < sign::COMB448_PLACES){
				// Следующее кратное строки
				sign::kernel448::point_t next;
				// Выполняем сложение кратного с точкой строки
				sign::kernel448::add(item, stride, next);
				// Запоминаем следующее кратное строки
				item = next;
			}
		}
		// Выводим закрывающую скобку строки гребёнки с разделителем строк
		::printf("\t\t}%s\n", ((i + 1) < sign::COMB448_ROWS ? "," : ""));
		/**
		 * Выполняем сдвиг точки строки на шестнадцать разрядов удвоениями
		 */
		for(size_t k = 0; k < 16; k++){
			// Удвоенная точка строки
			sign::kernel448::point_t twice;
			// Выполняем удвоение точки строки
			sign::kernel448::twice(stride, twice);
			// Запоминаем удвоенную точку строки
			stride = twice;
		}
	}
	// Выводим завершение гребёнки Ed448 и тела методов розыска
	::printf(
		"\t};\n"
		"};\n\n"
		"/**\n"
		" * @brief Метод поиска заготовленной гребёнки кратных точки основания\n"
		" *\n"
		" * @return указатель на первую строку гребёнки подряд\n"
		" *\n"
		" */\n"
		"const nts::sign::comb_t * nts::sign::prepared() noexcept {\n"
		"\t// Выводим указатель на заготовленную гребёнку\n"
		"\treturn &COMB[0][0];\n"
		"}\n\n"
		"/**\n"
		" * @brief Метод поиска позиционной таблицы окон кратных точки основания\n"
		" *\n"
		" * @return указатель на первое окно таблицы\n"
		" *\n"
		" */\n"
		"const nts::sign::comb_t (* nts::sign::positioned() noexcept)[nts::sign::COMB_CHOICES] {\n"
		"\t// Выводим указатель на первое окно позиционной таблицы\n"
		"\treturn &WINDOWED[0];\n"
		"}\n\n"
		"/**\n"
		" * @brief Метод поиска заготовленной гребёнки кратных точки основания Ed448\n"
		" *\n"
		" * @return указатель на первую строку гребёнки подряд\n"
		" *\n"
		" */\n"
		"const nts::sign::comb448_t * nts::sign::prepared448() noexcept {\n"
		"\t// Выводим указатель на заготовленную гребёнку\n"
		"\treturn &COMB448[0][0];\n"
		"}\n"
	);
	// Выводим код возврата успешности
	return EXIT_SUCCESS;
}
