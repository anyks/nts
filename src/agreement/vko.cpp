/**
 * Используем стандартное пространство имён
 */
using namespace std;

/**
 * @brief Внутренние служебные объекты
 *
 */
namespace {
	/**
	 * Пространство имён библиотеки
	 */
	using namespace anyks;

	/**
	 * @brief Метод затирания области памяти
	 *
	 * @details Затирание ведётся через изменчивый указатель: обычное присваивание
	 *          собиратель вправе выбросить, увидев, что записанное значение больше
	 *          никем не читается, - и секрет остался бы в памяти
	 *
	 * @param data затираемая область памяти
	 * @param size размер затираемой области памяти
	 *
	 */
	static void wipe(void * data, const size_t size) noexcept {
		// Получаем изменчивый указатель на затираемую область памяти
		volatile uint8_t * item = static_cast <volatile uint8_t *> (data);
		/**
		 * Выполняем перебор байтов затираемой области памяти
		 */
		for(size_t i = 0; i < size; i++)
			// Обнуляем очередной байт области памяти
			item[i] = 0;
	}
};

/**
 * @brief Метод выработки общего ключа
 *
 * @param curve  эллиптическая кривая выработки общего ключа
 * @param secret секретный ключ своей стороны
 * @param x      первая координата открытого ключа встречной стороны
 * @param y      вторая координата открытого ключа встречной стороны
 * @param ukm    добавочное значение сторон, задаваемое протоколом
 * @param result место, в которое помещается общий ключ
 * @param size   требуемая длина общего ключа в байтах
 *
 * @return       признак успешности выработки общего ключа
 *
 */
bool anyks::agreement::vko(const curve::curve_t & curve, const view_t & secret, const view_t & x, const view_t & y, const view_t & ukm, uint8_t * result, const size_t size) noexcept {
	// Если кривая не установлена либо место общего ключа не передано
	if(!curve.ready() || (result == nullptr))
		// Выводим отказ выработки общего ключа
		return false;
	// Если требуемая длина общего ключа не отвечает ни одному из хешей
	if((size != 32) && (size != 64))
		// Выводим отказ выработки общего ключа
		return false;
	// Получаем арифметику порядка подгруппы точек кривой
	const math::modulus_t & order = curve.order();
	// Секретный ключ своей стороны
	math::number_t value;
	// Если секретный ключ разобрать не удалось
	if(!order.load(secret, value) || order.zero(value))
		// Выводим отказ выработки общего ключа
		return false;
	// Открытый ключ встречной стороны
	curve::point_t point;
	/**
	 * Разбор точки проверяет её принадлежность кривой: без этой проверки подставная
	 * точка малого порядка выдаёт секретный ключ своей стороны
	 */
	if(!curve.point(x, y, point)){
		// Выполняем затирание секретного ключа своей стороны
		wipe(value.words, sizeof(value.words));
		// Выводим отказ выработки общего ключа
		return false;
	}
	// Значения, участвующие в выработке множителя кратной точки
	math::number_t entered, item;
	// Выполняем приведение секретного ключа в область Монтгомери
	order.enter(value, entered);
	// Кофактор кривой, на который множится секретный ключ
	math::number_t cofactor;
	// Записываем кофактор кривой
	order.word(curve.cofactor(), cofactor);
	// Выполняем приведение кофактора кривой в область Монтгомери
	order.enter(cofactor, item);
	// Выполняем умножение секретного ключа на кофактор кривой
	order.multiply(entered, item, entered);
	// Добавочное значение сторон
	math::number_t addition;
	/**
	 * Пустое добавочное значение стандарт полагает равным единице: тем выработка
	 * общего ключа без добавочного значения и задана
	 */
	if((ukm.data == nullptr) || (ukm.size == 0))
		// Записываем единичное добавочное значение
		order.word(1, addition);
	// Если добавочное значение сторон передано
	else if(!order.reduce(ukm, addition) || order.zero(addition)){
		// Выполняем затирание промежуточных значений выработки множителя
		wipe(entered.words, sizeof(entered.words));
		// Выполняем затирание секретного ключа своей стороны
		wipe(value.words, sizeof(value.words));
		// Выводим отказ выработки общего ключа
		return false;
	}
	// Выполняем приведение добавочного значения в область Монтгомери
	order.enter(addition, item);
	// Выполняем умножение полученного произведения на добавочное значение
	order.multiply(entered, item, entered);
	// Выполняем вывод множителя кратной точки из области Монтгомери
	order.leave(entered, value);
	// Признак успешности выработки общего ключа
	bool ok = !order.zero(value);
	// Если множитель кратной точки в ноль не обратился
	if(ok){
		// Кратная точка выработки общего ключа
		curve::point_t common;
		// Выполняем умножение открытого ключа встречной стороны на полученный множитель
		curve.multiply(point, value, common);
		// Место, в которое записываются координаты кратной точки
		uint8_t buffer[math::NUMBER_SIZE * 2];
		// Места, в которые записываются координаты кратной точки
		uint8_t first[math::NUMBER_SIZE], second[math::NUMBER_SIZE];
		// Если координаты кратной точки записать не удалось
		if((ok = curve.coordinates(common, first, second, curve.size()))){
			/**
			 * Выполняем разворот записи координат: хешу они подаются от младшего байта к
			 * старшему, той же записью, какой открытый ключ лежит в сертификате
			 */
			for(size_t i = 0; i < curve.size(); i++){
				// Переносим очередной байт первой координаты
				buffer[i] = first[curve.size() - i - 1];
				// Переносим очередной байт второй координаты
				buffer[curve.size() + i] = second[curve.size() - i - 1];
			}
			// Определяем длину хеша выработки общего ключа
			const digest::type_t type = (size == 32 ? digest::type_t::SHORT : digest::type_t::LONG);
			/**
			 * Общий ключ выходит хешем строкой байтов: порядок этот установлен сличением
			 * с контрольными примерами приложения А RFC 7836
			 */
			ok = digest::streebog(type, view_t(buffer, curve.size() * 2), result, size);
		}
		// Выполняем затирание записанных координат кратной точки
		wipe(buffer, sizeof(buffer));
		// Выполняем затирание второй координаты кратной точки
		wipe(second, sizeof(second));
		// Выполняем затирание первой координаты кратной точки
		wipe(first, sizeof(first));
		// Выполняем затирание кратной точки выработки общего ключа
		wipe(&common, sizeof(common));
	}
	// Выполняем затирание множителя кратной точки
	wipe(value.words, sizeof(value.words));
	// Выполняем затирание промежуточных значений выработки множителя
	wipe(item.words, sizeof(item.words));
	// Выполняем затирание промежуточных значений выработки множителя
	wipe(entered.words, sizeof(entered.words));
	// Выводим признак успешности выработки общего ключа
	return ok;
}
