/**
 * Экранируем повторную инициализацию модуля
 */
#ifndef __ANTS_CURVE_TABLES__
#define __ANTS_CURVE_TABLES__

/**
 * Подключаем стандартные заголовочные файлы
 */
#include <cstddef>
#include <cstdint>

/**
 * nts пространство имён
 */
namespace nts {
	/**
	 * curve пространство имён
	 */
	namespace curve {
		/**
		 * @brief Размер окна перебора множителя в разрядах
		 *
		 * @details Пять разрядов вместо четырёх: у множителя в 256 разрядов выходит 52 окна
		 *          вместо 64, и умножение точки основания стоит 52 смешанных сложения вместо
		 *          64 при переборе строки в 31 кратное вместо 15. Окно шести разрядов сложений
		 *          даёт 43, но строка в 63 кратных съедает выигрыш перебором, а заготовка
		 *          растёт вдвое. Окно не обязано делить разрядность нацело: старшее окно
		 *          неполное и дополняется нулями, а окно через границу слова собирается из
		 *          двух слов. Заготовка при пяти разрядах занимает около 1,85 МБ
		 *
		 */
		static constexpr size_t TABLES_WINDOW = 5;

		/**
		 * @brief Число кратных точки основания, хранимых на одно окно
		 *
		 * @note Кратное нулевое не хранится: оно есть бесконечно удалённая точка, и
		 *       выдаётся она обнулением третьей координаты, а не чтением из таблицы
		 *
		 */
		static constexpr size_t TABLES_MULTIPLES = ((1 << TABLES_WINDOW) - 1);

		/**
		 * @brief Описание заготовленных кратных точки основания одной кривой
		 *
		 */
		typedef struct Precomputed {
			// Число слов в одной координате точки
			size_t words;
			// Число окон, на которые разбит множитель
			size_t positions;
			/**
			 * Кратные точки основания в области Монтгомери, идущие подряд:
			 * окно за окном, внутри окна кратное за кратным, у кратного первая
			 * координата за второй
			 */
			const uint64_t * data;
		} precomputed_t;

		/**
		 * @brief Метод поиска заготовленных кратных по точке основания кривой
		 *
		 * @param x     первая координата точки основания в области Монтгомери
		 * @param y     вторая координата точки основания в области Монтгомери
		 * @param words число слов в одной координате точки
		 *
		 * @return      описание заготовленных кратных либо nullptr у кривой, кратные
		 *              которой не заготовлены
		 *
		 * @note Розыск идёт сличением с ПЕРВЫМ кратным первого окна: оно и есть сама
		 *       точка основания, и опознаёт кривую она однозначно
		 *
		 */
		const precomputed_t * precomputed(const uint64_t * x, const uint64_t * y, const size_t words) noexcept;
	};
};

#endif // __ANTS_CURVE_TABLES__
