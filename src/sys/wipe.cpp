/**
 * Подключаем заголовочные файлы проекта
 */
#include <cstring>
#include <cstdint>
#include <sys/wipe.hpp>

/**
 * Используем стандартное пространство имён
 */
using namespace std;

/**
 * Служебные объекты модуля
 */
namespace {
	/**
	 * Вид указателя на функцию заполнения области памяти
	 */
	typedef void * (* filler_t)(void *, int, size_t);
	/**
	 * Изменчивый указатель на memset (путь OpenSSL, crypto/mem_clr.c): собиратель обязан
	 * прочитать его при каждом вызове и не вправе знать, что за ним стоит memset, оттого
	 * не вправе и выбросить вызов как бесполезный; сам memset идёт полной скоростью
	 */
	static volatile filler_t filler = ::memset;
};

/**
 * @brief Функция затирания области памяти
 *
 * @param data затираемая область памяти
 * @param size размер затираемой области памяти в байтах
 *
 */
void nts::sys::wipe(void * data, const size_t size) noexcept {
	// Если область памяти передана
	if((data != nullptr) && (size > 0)){
		// Заполняем область нулями вызовом по изменчивому указателю
		filler(data, 0, size);
		/**
		 * Для компиляторов GNU и Clang с поддержкой пустых вставок
		 */
		#if defined(__GNUC__) || defined(__clang__)
			/**
			 * Барьер собирателя (путь BoringSSL и libsodium): пустая вставка с доводом-указателем
			 * и пометкой «memory» объявляет область прочитанной, и запись перед ней не
			 * выбрасывается даже там, где вызов по указателю окажется встроенным
			 */
			__asm__ __volatile__("" : : "r"(data) : "memory");
		#endif
	}
}
/**
 * @brief Функция затирания набора байтов с его опустошением
 *
 * @param data затираемый набор байтов; после затирания пуст
 *
 */
void nts::sys::wipe(vector <uint8_t> & data) noexcept {
	// Затираем содержимое набора байтов
	wipe(data.data(), data.size());
	// Опустошаем набор байтов
	data.clear();
}
/**
 * @brief Функция затирания строки с её опустошением
 *
 * @param data затираемая строка; после затирания пуста
 *
 */
void nts::sys::wipe(string & data) noexcept {
	// Затираем содержимое строки: у строки собственный буфер, и запись в него законна
	wipe(&data[0], data.size());
	// Опустошаем строку
	data.clear();
}
